#[test]
fn receipt_digest_hashes_canonical_json() {
    let value = json!({
        "b": 1,
        "a": [true, null, "x\"y\n"],
        "c": { "z": 1, "y": { "é": 2, "z": 3 } },
        "produced_at": "2026-10-27T21:00:00Z",
        "duration_ms": 5
    });
    let canonical = r#"{"a":[true,null,"x\"y\n"],"b":1,"c":{"y":{"z":3,"é":2},"z":1}}"#;
    assert_eq!(
        receipt_digest(&value).as_str(),
        blake3_hex(canonical.as_bytes())
    );
    // Integers of any length are written digit for digit.
    let big: Value =
        serde_json::from_str(r#"{"seed": 123456789012345678901234567890, "n": -7}"#).expect("json");
    assert_eq!(
        receipt_digest(&big).as_str(),
        blake3_hex(br#"{"n":-7,"seed":123456789012345678901234567890}"#)
    );
    // Only the top-level informational fields are left out.
    let nested = |ms: u64| json!({ "tests": [{ "duration_ms": ms }] });
    assert_ne!(receipt_digest(&nested(1)), receipt_digest(&nested(2)));
    assert_eq!(
        receipt_digest(&json!([1, 2])).as_str(),
        blake3_hex(b"[1,2]")
    );
}

#[test]
fn equal_evidence_has_equal_digests() {
    let (_, receipt) = milestone_one_receipt();
    let mut later = receipt.clone();
    later.produced_at = "2030-01-01T00:00:00Z".into();
    later.duration_ms = 1234;
    let digest = |r: &cpl_diag::json::VerificationReceipt| {
        receipt_digest(&serde_json::to_value(r).expect("serializes"))
    };
    assert_eq!(digest(&receipt), digest(&later));
    assert_eq!(digest(&receipt).as_str().len(), 64);
    let mut proved = receipt.clone();
    proved.status = ProofStatus::Proved;
    assert_ne!(digest(&receipt), digest(&proved));
    let mut other_inputs = receipt;
    other_inputs
        .inputs
        .sources
        .insert("src/new.cpl".into(), Digest("1".repeat(64)));
    assert_ne!(digest(&later), digest(&other_inputs));
}
