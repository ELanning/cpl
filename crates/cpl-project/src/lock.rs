const TARGET_C_KEYS: [&str; 14] = [
    "api",
    "runtime",
    "runtime_digest",
    "target",
    "compiler",
    "compiler_path",
    "compiler_digest",
    "flags_digest",
    "system_digest",
    "prefix",
    "abi",
    "exports_digest",
    "exports",
    "symbols",
];

fn target_c_from(value: &toml::Value, path: &str) -> Result<TargetC, String> {
    let t = c_table(value, path)?;
    c_closed(t, path, &TARGET_C_KEYS)?;
    let abi = match c_get(t, path, "abi")? {
        toml::Value::Integer(v) if (0..=i64::from(u16::MAX)).contains(v) => {
            u16::try_from(*v).expect("checked against u16::MAX")
        }
        other => {
            return Err(format!(
                "`{path}.abi` in cpl.lock must be an integer from 0 to 65535, found {other}"
            ))
        }
    };
    let mut exports = BTreeMap::new();
    let exports_path = format!("{path}.exports");
    for (symbol, entry) in c_table(c_get(t, path, "exports")?, &exports_path)? {
        let entry_path = format!("{exports_path}.{}", key(symbol));
        let e = c_table(entry, &entry_path)?;
        c_closed(e, &entry_path, &["function", "id", "signature", "int"])?;
        let id_text = c_string(e, &entry_path, "id")?;
        let id = StableId::parse(&id_text).map_err(|err| {
            format!("`{entry_path}.id` in cpl.lock must be a stable id, found {id_text:?}: {err}")
        })?;
        let int_text = c_string(e, &entry_path, "int")?;
        let int = IntMapping::parse(&int_text).ok_or_else(|| {
            format!(
                "`{entry_path}.int` in cpl.lock must be one of handle, int64, int32, uint64, uint32, found {int_text:?}"
            )
        })?;
        exports.insert(
            symbol.clone(),
            LockedExport {
                function: c_string(e, &entry_path, "function")?,
                id,
                signature: c_digest(e, &entry_path, "signature")?,
                int,
            },
        );
    }
    let symbols = match c_get(t, path, "symbols")? {
        toml::Value::Array(items) => items
            .iter()
            .map(|item| match item {
                toml::Value::String(s) => Ok(s.clone()),
                other => Err(format!(
                    "`{path}.symbols` in cpl.lock must be an array of strings, found {}",
                    other.type_str()
                )),
            })
            .collect::<Result<Vec<_>, _>>()?,
        other => {
            return Err(format!(
                "`{path}.symbols` in cpl.lock must be an array of strings, found {}",
                other.type_str()
            ))
        }
    };
    Ok(TargetC {
        api: c_string(t, path, "api")?,
        runtime: c_string(t, path, "runtime")?,
        runtime_digest: c_digest(t, path, "runtime_digest")?,
        target: c_string(t, path, "target")?,
        compiler: c_string(t, path, "compiler")?,
        compiler_path: c_string(t, path, "compiler_path")?,
        compiler_digest: c_digest(t, path, "compiler_digest")?,
        flags_digest: c_digest(t, path, "flags_digest")?,
        system_digest: c_digest(t, path, "system_digest")?,
        prefix: c_string(t, path, "prefix")?,
        abi,
        exports_digest: c_digest(t, path, "exports_digest")?,
        exports,
        symbols,
    })
}

fn adapter_c_from(value: &toml::Value, path: &str) -> Result<AdapterC, String> {
    let t = c_table(value, path)?;
    c_closed(
        t,
        path,
        &["backend", "form", "isolation", "capability", "files"],
    )?;
    let form_text = c_string(t, path, "form")?;
    let form = AdapterForm::parse(&form_text).ok_or_else(|| {
        format!(
            "`{path}.form` in cpl.lock must be \"wrapper\" or \"declarative\", found {form_text:?}"
        )
    })?;
    let isolation = c_string(t, path, "isolation")?;
    if isolation != "worker" && isolation != "in_process" {
        return Err(format!(
            "`{path}.isolation` in cpl.lock must be \"worker\" or \"in_process\", found {isolation:?}"
        ));
    }
    Ok(AdapterC {
        form,
        isolation,
        capability: c_string(t, path, "capability")?,
        files: c_digests(c_get(t, path, "files")?, &format!("{path}.files"))?,
    })
}

fn foreign_c_from(value: &toml::Value, path: &str) -> Result<ForeignC, String> {
    let t = c_table(value, path)?;
    c_closed(t, path, &["sources", "headers", "libraries"])?;
    let libraries_path = format!("{path}.libraries");
    let mut libraries = BTreeMap::new();
    for (name, library) in c_table(c_get(t, path, "libraries")?, &libraries_path)? {
        let library_path = format!("{libraries_path}.{}", key(name));
        let l = c_table(library, &library_path)?;
        c_closed(l, &library_path, &["path", "digest"])?;
        libraries.insert(
            name.clone(),
            LockedLibrary {
                path: c_string(l, &library_path, "path")?,
                digest: c_digest(l, &library_path, "digest")?,
            },
        );
    }
    Ok(ForeignC {
        sources: c_digests(c_get(t, path, "sources")?, &format!("{path}.sources"))?,
        headers: c_digest(t, path, "headers")?,
        libraries,
    })
}

fn c_table<'v>(value: &'v toml::Value, path: &str) -> Result<&'v toml::Table, String> {
    match value {
        toml::Value::Table(t) => Ok(t),
        other => Err(format!(
            "`{path}` in cpl.lock must be a table, found {}",
            other.type_str()
        )),
    }
}

/// Exactly the keys `known`, each required.
fn c_closed(table: &toml::Table, path: &str, known: &[&str]) -> Result<(), String> {
    if let Some(k) = table.keys().find(|k| !known.contains(&k.as_str())) {
        return Err(format!("unknown key `{path}.{}` in cpl.lock", key(k)));
    }
    if let Some(k) = known.iter().find(|k| !table.contains_key(**k)) {
        return Err(format!("missing required key `{path}.{k}` in cpl.lock"));
    }
    Ok(())
}

fn c_get<'t>(table: &'t toml::Table, path: &str, name: &str) -> Result<&'t toml::Value, String> {
    table
        .get(name)
        .ok_or_else(|| format!("missing required key `{path}.{name}` in cpl.lock"))
}

fn c_string(table: &toml::Table, path: &str, name: &str) -> Result<String, String> {
    match c_get(table, path, name)? {
        toml::Value::String(s) => Ok(s.clone()),
        other => Err(format!(
            "`{path}.{name}` in cpl.lock must be a string, found {}",
            other.type_str()
        )),
    }
}

fn c_digest(table: &toml::Table, path: &str, name: &str) -> Result<Digest, String> {
    let hex = c_string(table, path, name)?;
    digest(&hex, &format!("{path}.{name}")).map_err(|e| e.message)
}

/// A table from path (or name) to digest.
fn c_digests(value: &toml::Value, path: &str) -> Result<BTreeMap<String, Digest>, String> {
    let mut out = BTreeMap::new();
    for (k, v) in c_table(value, path)? {
        let entry = format!("{path}.{}", key(k));
        let toml::Value::String(hex) = v else {
            return Err(format!(
                "`{entry}` in cpl.lock must be a digest string, found {}",
                v.type_str()
            ));
        };
        out.insert(k.clone(), digest(hex, &entry).map_err(|e| e.message)?);
    }
    Ok(out)
}

fn string_value(s: &str) -> toml::Value {
    toml::Value::String(s.to_string())
}

fn digests_value(map: &BTreeMap<String, Digest>) -> toml::Value {
    let mut table = toml::Table::new();
    for (k, d) in map {
        table.insert(k.clone(), string_value(d.as_str()));
    }
    toml::Value::Table(table)
}

fn target_c_value(t: &TargetC) -> toml::Value {
    let mut exports = toml::Table::new();
    for (symbol, e) in &t.exports {
        let mut entry = toml::Table::new();
        entry.insert("function".into(), string_value(&e.function));
        entry.insert("id".into(), string_value(e.id.as_str()));
        entry.insert("signature".into(), string_value(e.signature.as_str()));
        entry.insert("int".into(), string_value(e.int.as_str()));
        exports.insert(symbol.clone(), toml::Value::Table(entry));
    }
    let mut table = toml::Table::new();
    table.insert("api".into(), string_value(&t.api));
    table.insert("runtime".into(), string_value(&t.runtime));
    table.insert(
        "runtime_digest".into(),
        string_value(t.runtime_digest.as_str()),
    );
    table.insert("target".into(), string_value(&t.target));
    table.insert("compiler".into(), string_value(&t.compiler));
    table.insert("compiler_path".into(), string_value(&t.compiler_path));
    table.insert(
        "compiler_digest".into(),
        string_value(t.compiler_digest.as_str()),
    );
    table.insert("flags_digest".into(), string_value(t.flags_digest.as_str()));
    table.insert(
        "system_digest".into(),
        string_value(t.system_digest.as_str()),
    );
    table.insert("prefix".into(), string_value(&t.prefix));
    table.insert("abi".into(), toml::Value::Integer(i64::from(t.abi)));
    table.insert(
        "exports_digest".into(),
        string_value(t.exports_digest.as_str()),
    );
    table.insert("exports".into(), toml::Value::Table(exports));
    table.insert(
        "symbols".into(),
        toml::Value::Array(t.symbols.iter().map(|s| string_value(s)).collect()),
    );
    toml::Value::Table(table)
}

