fn git_available() -> bool {
    let found = Command::new("git")
        .arg("--version")
        .output()
        .is_ok_and(|o| o.status.success());
    if !found {
        eprintln!("skipped: git is not installed");
    }
    found
}

static TEMP_NAMES: Mutex<BTreeSet<String>> = Mutex::new(BTreeSet::new());

/// A fresh, empty directory under `CARGO_TARGET_TMPDIR`, unique per test.
fn temp_dir(name: &str) -> PathBuf {
    let unique = format!("cpl-index-adversarial-rdr-{name}");
    assert!(
        TEMP_NAMES
            .lock()
            .unwrap_or_else(|e| e.into_inner())
            .insert(unique.clone()),
        "temporary directory {name} requested twice"
    );
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join(unique);
    if dir.exists() {
        std::fs::remove_dir_all(&dir).expect("clear the temporary directory");
    }
    std::fs::create_dir_all(&dir).expect("create the temporary directory");
    dir
}

fn write_bytes(root: &Path, path: &str, bytes: &[u8]) {
    let full = root.join(path);
    if let Some(parent) = full.parent() {
        std::fs::create_dir_all(parent).expect("create directories");
    }
    std::fs::write(&full, bytes).expect("write a file");
}

/// A temporary repository driven through the git command line, with a
/// fixed identity and no hooks, signing, or line-ending conversion.
struct TestRepo {
    dir: PathBuf,
}

impl TestRepo {
    fn init(name: &str) -> TestRepo {
        let repo = TestRepo {
            dir: temp_dir(name),
        };
        repo.git(&["init", "-q", "-b", "main"]);
        repo
    }

    #[track_caller]
    fn git(&self, args: &[&str]) -> String {
        let output = Command::new("git")
            .arg("-C")
            .arg(&self.dir)
            .args([
                "-c",
                "user.name=cpl adversary",
                "-c",
                "user.email=adversary@example.invalid",
                "-c",
                "commit.gpgsign=false",
                "-c",
                "tag.gpgsign=false",
                "-c",
                "core.autocrlf=false",
                "-c",
                "core.hooksPath=/dev/null",
                "-c",
                "advice.detachedHead=false",
            ])
            .args(args)
            .env("LC_ALL", "C")
            .env("GIT_TERMINAL_PROMPT", "0")
            .output()
            .expect("run git");
        assert!(
            output.status.success(),
            "git {args:?}: {}",
            String::from_utf8_lossy(&output.stderr)
        );
        String::from_utf8(output.stdout)
            .expect("utf-8")
            .trim()
            .to_string()
    }

    fn write(&self, files: &[(&str, &str)]) {
        for (path, text) in files {
            write_bytes(&self.dir, path, text.as_bytes());
        }
    }

    fn remove(&self, path: &str) {
        std::fs::remove_file(self.dir.join(path)).expect("remove a file");
    }

    /// Commit everything; the new HEAD.
    fn commit(&self, message: &str) -> String {
        self.git(&["add", "-A"]);
        self.git(&[
            "commit",
            "-q",
            "--no-verify",
            "--allow-empty",
            "-m",
            message,
        ]);
        self.git(&["rev-parse", "HEAD"])
    }
}

