fn foreign_c_value(f: &ForeignC) -> toml::Value {
    let mut libraries = toml::Table::new();
    for (name, l) in &f.libraries {
        let mut entry = toml::Table::new();
        entry.insert("path".into(), string_value(&l.path));
        entry.insert("digest".into(), string_value(l.digest.as_str()));
        libraries.insert(name.clone(), toml::Value::Table(entry));
    }
    let mut table = toml::Table::new();
    table.insert("sources".into(), digests_value(&f.sources));
    table.insert("headers".into(), string_value(f.headers.as_str()));
    table.insert("libraries".into(), toml::Value::Table(libraries));
    toml::Value::Table(table)
}
