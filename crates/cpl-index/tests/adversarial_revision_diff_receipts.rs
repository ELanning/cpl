#[test]
fn kind_changes_are_a_removal_and_an_addition_noted_kind_changed() {
    let before = [("src/k.cpl", KINDS_BEFORE)];
    let after = [("src/k.cpl", KINDS_AFTER)];
    let diff = diff_of(&before, &after);
    // Section 9.1: a facet that applies on one side only (refinement ->
    // struct, fn -> test, test -> property, capability -> struct) is
    // `identity_removed` plus `identity_added` noted `kind_changed`, and
    // nothing else for that id, not even the rename of fn_bbbb...; the pair
    // is ordered by the new side's path, then table order.
    let got: Vec<(K, &str)> = diff
        .statements
        .iter()
        .map(|s| (s.statement, s.id.as_str()))
        .collect();
    assert_eq!(
        got,
        [
            (K::IdentityAdded, "fn_bbbbbbbbbbbbbbbb"),
            (K::IdentityRemoved, "fn_bbbbbbbbbbbbbbbb"),
            (K::IdentityAdded, "test_cccccccccccccccc"),
            (K::IdentityRemoved, "test_cccccccccccccccc"),
            (K::IdentityAdded, "cap_dddddddddddddddd"),
            (K::IdentityRemoved, "cap_dddddddddddddddd"),
            (K::IdentityAdded, "ty_aaaaaaaaaaaaaaaa"),
            (K::IdentityRemoved, "ty_aaaaaaaaaaaaaaaa"),
            (K::BodyChanged, "k.middle"),
        ]
    );
    let cases = [
        ("fn_bbbbbbbbbbbbbbbb", "fn", "zeta", "test", "alpha"),
        ("test_cccccccccccccccc", "test", "probe", "prop", "probe"),
        ("cap_dddddddddddddddd", "cap", "Port", "ty", "Port"),
        ("ty_aaaaaaaaaaaaaaaa", "ty", "Size", "ty", "Size"),
    ];
    for (id, old_kind, old_name, new_kind, new_name) in cases {
        let of = |kind: K| {
            diff.statements
                .iter()
                .find(|s| s.statement == kind && s.id.as_str() == id)
                .expect("the statement")
        };
        let (added, removed) = (of(K::IdentityAdded), of(K::IdentityRemoved));
        for s in [added, removed] {
            assert_eq!(s.detail["note"], json!("kind_changed"), "{id}");
            assert_eq!(s.facet, None, "{id}");
        }
        assert_eq!(added.kind, new_kind, "{id}");
        assert_eq!(removed.kind, old_kind, "{id}");
        let new_version = version_in(&after, "src/k.cpl", new_name);
        let old_version = version_in(&before, "src/k.cpl", old_name);
        assert_eq!(added.path, new_version.path, "{id}");
        // 9.1: `path` is the new side's whenever the id is in the new map,
        // the removal of a kind change included (its version is the old).
        assert_eq!(removed.path, new_version.path, "{id}");
        assert_eq!(
            added.detail["version"],
            serde_json::to_value(&new_version).expect("serializes"),
            "{id}"
        );
        assert_eq!(
            removed.detail["version"],
            serde_json::to_value(&old_version).expect("serializes"),
            "{id}"
        );
    }
}

#[test]
fn duplicates_compare_the_first_occurrence_in_path_order() {
    let helper = |n: u32| {
        format!("module m\n\n@id(\"fn_dddddddddddddddd\")\nfn helper() -> Int {{\n    {n}\n}}\n")
    };
    let (one, two) = (helper(1), helper(2));
    // Byte order puts src/m/a-b.cpl before src/m/a/b.cpl (Section 5.4
    // "path order"); the new side's first occurrence is the edited copy.
    let diff = diff_of(
        &[("src/m/a/b.cpl", one.as_str())],
        &[
            ("src/m/a-b.cpl", two.as_str()),
            ("src/m/a/b.cpl", one.as_str()),
        ],
    );
    // Section 9.2: the diff uses the first occurrence and reports the
    // duplicates.
    assert_eq!(summary(&diff), pairs(&[("body_changed", "m.helper")]));
    assert_eq!(
        diff.statements[0].detail,
        json!({ "old": hash("{\n    1\n}"), "new": hash("{\n    2\n}") })
    );
    assert!(diff.duplicates.old.is_empty());
    assert_eq!(diff.duplicates.new.len(), 1);
    assert_eq!(diff.duplicates.new[0].id.as_str(), "fn_dddddddddddddddd");
    let files: BTreeSet<&str> = diff.duplicates.new[0]
        .files
        .iter()
        .map(String::as_str)
        .collect();
    assert_eq!(files, BTreeSet::from(["src/m/a-b.cpl", "src/m/a/b.cpl"]));

    // Within one file the first declaration is the occurrence.
    let first = "module m\n\n@id(\"fn_eeeeeeeeeeeeeeee\")\nfn first() -> Int {\n    1\n}\n";
    let twice =
        format!("{first}\n@id(\"fn_eeeeeeeeeeeeeeee\")\nfn second() -> Int {{\n    2\n}}\n");
    let ids = |list: &[cpl_diag::json::DuplicateId]| -> Vec<String> {
        list.iter().map(|d| d.id.as_str().to_string()).collect()
    };
    let grew = diff_of(&[("src/m.cpl", first)], &[("src/m.cpl", twice.as_str())]);
    assert!(grew.statements.is_empty(), "{:?}", summary(&grew));
    assert!(grew.duplicates.old.is_empty());
    assert_eq!(ids(&grew.duplicates.new), ["fn_eeeeeeeeeeeeeeee"]);
    let shrank = diff_of(&[("src/m.cpl", twice.as_str())], &[("src/m.cpl", first)]);
    assert!(shrank.statements.is_empty(), "{:?}", summary(&shrank));
    assert_eq!(ids(&shrank.duplicates.old), ["fn_eeeeeeeeeeeeeeee"]);
    assert!(shrank.duplicates.new.is_empty());
}

