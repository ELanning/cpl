//! The Rust printer: a crate whose modules mirror the program's, with CPL functions as Rust
//! functions, structs and enums as Rust types deriving `Clone`, `PartialEq`, `Eq`, `Hash`, and
//! `Debug`, and capabilities as traits (`spec/hosts.md` 2).
//!
//! Every function has an internal form `f__x(args..., cx)` that the program's own calls use,
//! returning `Result<T, cpl::Fault>`; a `pub fn` also has a host form `f(args...)` that makes
//! the calling context and checks refinements and invariants of its arguments.

use crate::lir::*;
use crate::lower::{diverges, Lowered};
use crate::{erase, instantiate, needs_validation, std_type, Options, Package, StdType};
use cpl_hir::{DefId, DefKind, Program, Ty};
use num_traits::ToPrimitive;
use std::collections::{BTreeMap, BTreeSet, HashSet};
use std::fmt::Write as _;

const RESERVED: &[&str] = &[
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for",
    "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return",
    "self", "Self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use", "where",
    "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen", "cpl", "std",
    "core", "alloc",
    // the names the generated functions declare themselves: the calling context
    "cx",
];

const FALLIBLE: &[&str] = FALLIBLE_BUILTINS;

pub fn emit(p: &Program, lowered: &Lowered, options: &Options) -> Package {
    let mut r = Printer {
        p,
        q: crate::rust_q::RustQ::new(p),
        cycles: crate::Cycles::new(p),
        out: String::new(),
        validators: BTreeMap::new(),
        pending: Vec::new(),
        fn_ids: lowered
            .fns
            .iter()
            .enumerate()
            .map(|(i, f)| (f.def, i as u32))
            .collect(),
    };
    // the generated paths of the speculative forms' records and enums
    for d in r.q.named() {
        let path = r.path(d);
        r.q.gen.insert(d, path.clone());
        if let Some(e) = p.def(d).kind.as_enum() {
            for (v, var) in e.variants.iter().enumerate() {
                r.q.variants.insert((d, v as u32), format!("{path}::{}", ident(&var.name)));
            }
        }
    }
    let mut files = BTreeMap::new();
    let crate_name = options.name.replace('-', "_");
    files.insert(
        "Cargo.toml".to_string(),
        format!(
            "[package]\nname = \"{}\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n# A standalone package: depend on it by path.\n[workspace]\n\n[lib]\npath = \"src/lib.rs\"\n{}\n[profile.release]\ndebug = false\n",
            options.name,
            if options.driver {
                "\n[[bin]]\nname = \"cpl-driver\"\npath = \"src/bin/cpl-driver.rs\"\n"
            } else {
                ""
            }
        ),
    );
    files.insert(
        "src/cpl.rs".to_string(),
        include_str!("runtime/cpl.rs").to_string(),
    );
    // Group the definitions by module path.
    let mut modules: BTreeMap<Vec<String>, Vec<DefId>> = BTreeMap::new();
    for d in p.defs() {
        if lowered.defs.contains(&d.id) && std_type(p, d.id).is_none() {
            modules.entry(module_path(p, d.id)).or_default().push(d.id);
        }
    }
    let fns: BTreeMap<DefId, &LFn> = lowered.fns.iter().map(|f| (f.def, f)).collect();
    let preds: BTreeMap<DefId, &LPred> = lowered.preds.iter().map(|q| (q.def, q)).collect();
    let mut exports = Vec::new();
    let mut lib = String::new();
    lib.push_str("//! Generated by `cpl build --target rust`: do not edit.\n#![allow(unused_variables, unused_mut, unused_parens, unused_braces, unused_imports, unused_assignments, unused_labels, non_snake_case, non_camel_case_types, unreachable_code, unreachable_patterns, dead_code, clippy::all)]\n\npub mod cpl;\n\n");
    // A tree of nested modules.
    let mut tree: Tree = Tree::default();
    for (path, defs) in &modules {
        let mut node = &mut tree;
        for seg in path {
            node = node.children.entry(seg.clone()).or_default();
        }
        node.defs.extend(defs.iter().copied());
    }
    r.tree(&tree, 0, &fns, &preds, &mut exports, &mut lib);
    if options.driver {
        r.out.clear();
        r.driver(lowered);
        lib.push_str(&r.out);
        files.insert(
            "src/bin/cpl-driver.rs".to_string(),
            format!("fn main() {{\n    {crate_name}::__driver::main();\n}}\n"),
        );
    }
    // The records of the speculative forms, at the crate root.
    lib.push_str(&r.q.module(p, &|d| r.path(d)));
    // Every validator requested while printing, at the crate root.
    lib.push_str("\n#[doc(hidden)]\npub mod __validate {\n    use super::*;\n");
    let mut done = BTreeSet::new();
    while let Some((key, ty)) = r.pending.pop() {
        if !done.insert(key.clone()) {
            continue;
        }
        r.out.clear();
        r.validator(&key, &ty);
        lib.push_str(&r.out);
    }
    lib.push_str("}\n");
    files.insert("src/lib.rs".to_string(), lib);
    Package { files, exports }
}

#[derive(Default)]
struct Tree {
    children: BTreeMap<String, Tree>,
    defs: Vec<DefId>,
}

fn module_path(p: &Program, d: DefId) -> Vec<String> {
    let path = &p.module(p.def(d).module).path;
    if path.first().is_some_and(|s| s == "std") {
        let mut out = vec!["cpl_std".to_string()];
        out.extend(path[1..].iter().cloned());
        out
    } else {
        path.clone()
    }
}

struct Printer<'p> {
    p: &'p Program,
    /// The functions with a speculative form (`rust_q.rs`).
    q: crate::rust_q::RustQ,
    /// The declarations whose own types may contain them (`boxed_*` asks `reaches` only there).
    cycles: crate::Cycles,
    out: String,
    /// Validators requested: (key, type).
    validators: BTreeMap<String, String>,
    pending: Vec<(String, Ty)>,
    fn_ids: BTreeMap<DefId, u32>,
}

impl<'p> Printer<'p> {
    fn tree(
        &mut self,
        node: &Tree,
        depth: usize,
        fns: &BTreeMap<DefId, &LFn>,
        preds: &BTreeMap<DefId, &LPred>,
        exports: &mut Vec<String>,
        lib: &mut String,
    ) {
        let pad = "    ".repeat(depth);
        for d in &node.defs {
            self.out.clear();
            self.def(*d, fns, preds, exports);
            for line in self.out.lines() {
                if line.is_empty() {
                    lib.push('\n');
                } else {
                    let _ = writeln!(lib, "{pad}{line}");
                }
            }
        }
        for (name, child) in &node.children {
            let _ = writeln!(lib, "{pad}pub mod {} {{\n{pad}    use crate::cpl;\n{pad}    use crate::cpl::{{ValueText as _, ToJson as _, FromJson as _}};", ident(name));
            self.tree(child, depth + 1, fns, preds, exports, lib);
            let _ = writeln!(lib, "{pad}}}");
        }
    }

    fn path(&self, d: DefId) -> String {
        let mut s = String::from("crate");
        for seg in module_path(self.p, d) {
            s.push_str("::");
            s.push_str(&ident(&seg));
        }
        s.push_str("::");
        s.push_str(&ident(&self.p.def(d).name.display()));
        s
    }

    fn def(
        &mut self,
        d: DefId,
        fns: &BTreeMap<DefId, &LFn>,
        preds: &BTreeMap<DefId, &LPred>,
        exports: &mut Vec<String>,
    ) {
        let p = self.p;
        let def = p.def(d);
        let name = ident(&def.name.display());
        match &def.kind {
            DefKind::Struct(s) => {
                let g = generics_decl(&s.generics, false);
                let _ = writeln!(
                    self.out,
                    "#[derive(Clone, Debug, PartialEq, Eq, Hash)]\npub struct {name}{g} {{"
                );
                for (i, f) in s.fields.iter().enumerate() {
                    let t = self.boxed_ty(self.boxed_field(d, i), self.ty(&f.ty, &s.generics));
                    let _ = writeln!(self.out, "    pub {}: {t},", ident(&f.name));
                }
                let _ = writeln!(self.out, "}}\n");
                self.value_impls_struct(
                    d,
                    &name,
                    &s.generics,
                    &s.fields
                        .iter()
                        .map(|f| (f.name.clone(), f.ty.clone()))
                        .collect::<Vec<_>>(),
                );
                if let Some(pred) = preds.get(&d) {
                    self.pred(pred);
                }
            }
            DefKind::Enum(e) => {
                let g = generics_decl(&e.generics, false);
                let _ = writeln!(
                    self.out,
                    "#[derive(Clone, Debug, PartialEq, Eq, Hash)]\npub enum {name}{g} {{"
                );
                for (vi, v) in e.variants.iter().enumerate() {
                    if v.payload.is_empty() {
                        let _ = writeln!(self.out, "    {},", ident(&v.name));
                    } else {
                        let tys: Vec<String> = v
                            .payload
                            .iter()
                            .enumerate()
                            .map(|(i, t)| {
                                self.boxed_ty(self.boxed_payload(d, vi, i), self.ty(t, &e.generics))
                            })
                            .collect();
                        let _ = writeln!(self.out, "    {}({}),", ident(&v.name), tys.join(", "));
                    }
                }
                let _ = writeln!(self.out, "}}\n");
                self.value_impls_enum(d, &name, &e.generics);
            }
            DefKind::Wrapper(w) => {
                let inner = self.boxed_ty(self.boxed_wrapper(d), self.ty(&w.inner, &[]));
                let qualified = crate::lower::type_name(p, d);
                let bare = def.name.display();
                let _ = writeln!(self.out, "#[derive(Clone, Debug, PartialEq, Eq, Hash)]\npub struct {name}(pub {inner});\n");
                let _ = writeln!(self.out, "impl cpl::ValueText for {name} {{\n    fn write_text(&self, out: &mut ::std::string::String) {{\n        out.push_str(\"{bare}(\");\n        self.0.write_text(out);\n        out.push(')');\n    }}\n}}");
                let _ = writeln!(self.out, "impl cpl::ToJson for {name} {{\n    fn to_json(&self) -> cpl::Json {{\n        cpl::tagged({qualified:?}, None, Some(vec![self.0.to_json()]))\n    }}\n}}");
                let _ = writeln!(self.out, "impl cpl::FromJson for {name} {{\n    fn from_json(j: &cpl::Json) -> Result<Self, ::std::string::String> {{\n        match cpl::untag(j, {qualified:?})? {{\n            (_, [x]) => Ok({name}(cpl::FromJson::from_json(x)?)),\n            _ => Err(\"expected a {bare}\".into()),\n        }}\n    }}\n}}\n");
            }
            DefKind::Refinement(_) => {
                if let Some(pred) = preds.get(&d) {
                    self.pred(pred);
                }
            }
            DefKind::Capability(c) => {
                let _ = writeln!(
                    self.out,
                    "/// The capability `{}`: the host implements it.\npub trait {name} {{",
                    p.display_path(d)
                );
                for op in &c.ops {
                    let params: Vec<String> = op
                        .params
                        .iter()
                        .map(|q| format!("{}: {}", ident(&q.name), self.ty(&q.ty, &[])))
                        .collect();
                    let ret = if self.is_unit(&op.ret) {
                        String::new()
                    } else {
                        format!(" -> {}", self.ty(&op.ret, &[]))
                    };
                    let _ = writeln!(
                        self.out,
                        "    fn {}(&self, {}){ret};",
                        ident(&op.name),
                        params.join(", ")
                    );
                }
                let _ = writeln!(self.out, "}}\n");
            }
            DefKind::Fn(_) => {
                if let Some(f) = fns.get(&d) {
                    self.function(f);
                    if def.is_pub {
                        exports.push(p.display_path(d));
                        self.host_function(f);
                    }
                }
            }
            _ => {}
        }
    }

    // ---- types -----------------------------------------------------------------------

    /// A field that contains its own struct is held by `cpl::Boxed` (`spec/hosts.md` 2.2, H6).
    fn boxed_field(&self, d: DefId, i: usize) -> bool {
        self.p
            .def(d)
            .kind
            .as_struct()
            .is_some_and(|s| {
                self.cycles.may_contain_itself(d) && crate::reaches(self.p, &s.fields[i].ty, d, true)
            })
    }

    /// The constructor of a `cpl::Boxed` of a value of `ty`: an option's `None` needs no allocation.
    fn boxing(&self, ty: &Ty) -> &'static str {
        match ty {
            Ty::Adt(d, args) if *d == self.p.std_defs.option && args.len() == 1 => "cpl::Boxed::opt",
            _ => "cpl::Boxed::new",
        }
    }

    fn boxed_payload(&self, d: DefId, variant: usize, i: usize) -> bool {
        self.p
            .def(d)
            .kind
            .as_enum()
            .is_some_and(|e| {
                self.cycles.may_contain_itself(d)
                    && crate::reaches(self.p, &e.variants[variant].payload[i], d, true)
            })
    }

    fn boxed_wrapper(&self, d: DefId) -> bool {
        self.p
            .def(d)
            .kind
            .as_wrapper()
            .is_some_and(|w| self.cycles.may_contain_itself(d) && crate::reaches(self.p, &w.inner, d, true))
    }

    fn boxed_ty(&self, boxed: bool, t: String) -> String {
        if boxed {
            format!("cpl::Boxed<{t}>")
        } else {
            t
        }
    }

    fn is_unit(&self, t: &Ty) -> bool {
        matches!(t, Ty::Adt(d, _) if *d == self.p.std_defs().unit)
    }

    fn ty(&self, t: &Ty, generics: &[String]) -> String {
        let p = self.p;
        match t {
            Ty::Int => "cpl::Int".into(),
            Ty::Bool => "bool".into(),
            Ty::Text => "cpl::Text".into(),
            Ty::Bytes => "cpl::Bytes".into(),
            Ty::List(e) => format!("cpl::List<{}>", self.ty(e, generics)),
            Ty::Adt(d, args) => {
                let a: Vec<String> = args.iter().map(|x| self.ty(x, generics)).collect();
                match std_type(p, *d) {
                    Some(StdType::Unit) => "()".into(),
                    Some(StdType::Option) => format!("Option<{}>", a[0]),
                    Some(StdType::Result) => format!("Result<{}, {}>", a[0], a[1]),
                    Some(StdType::ConstraintError) => "cpl::ConstraintError".into(),
                    Some(StdType::ForeignError) => "cpl::ForeignError".into(),
                    Some(StdType::ForeignErrorKind) => "cpl::ForeignErrorKind".into(),
                    Some(StdType::ForeignDetail) => "cpl::ForeignDetail".into(),
                    None if a.is_empty() => self.path(*d),
                    None => format!("{}<{}>", self.path(*d), a.join(", ")),
                }
            }
            Ty::Wrapper(d) => self.path(*d),
            Ty::Refined(..) => self.ty(&erase(p, t), generics),
            Ty::Param(i) => generics
                .get(*i as usize)
                .map(|g| format!("G{g}"))
                .unwrap_or_else(|| "()".into()),
            Ty::Capability(d) => format!("&dyn {}", self.path(*d)),
            Ty::Gen(_) | Ty::Error => "()".into(),
        }
    }

    /// `Path::<args>` for a generic type in expression position.
    fn ty_expr(&self, t: &Ty, generics: &[String]) -> String {
        let s = self.ty(t, generics);
        match s.find('<') {
            Some(i) => format!("{}::{}", &s[..i], &s[i..]),
            None => s,
        }
    }

    fn value_impls_struct(
        &mut self,
        d: DefId,
        name: &str,
        generics: &[String],
        fields: &[(String, Ty)],
    ) {
        let p = self.p;
        let g = generics_decl(generics, true);
        let gu = generics_use(generics);
        let qualified = crate::lower::type_name(p, d);
        let bare = p.def(d).name.display();
        let _ = writeln!(self.out, "impl{g} cpl::ValueText for {name}{gu} {{\n    fn write_text(&self, out: &mut ::std::string::String) {{");
        if fields.is_empty() {
            let _ = writeln!(self.out, "        out.push_str(\"{bare} {{}}\");");
        } else {
            let _ = writeln!(self.out, "        out.push_str(\"{bare} {{ \");");
            for (i, (f, _)) in fields.iter().enumerate() {
                let sep = if i > 0 { ", " } else { "" };
                let _ = writeln!(
                    self.out,
                    "        out.push_str(\"{sep}{f}: \");\n        self.{}.write_text(out);",
                    ident(f)
                );
            }
            let _ = writeln!(self.out, "        out.push_str(\" }}\");");
        }
        let _ = writeln!(self.out, "    }}\n}}");
        let _ = writeln!(self.out, "impl{g} cpl::ToJson for {name}{gu} {{\n    fn to_json(&self) -> cpl::Json {{\n        cpl::Json::object(vec![(\"$type\".into(), cpl::Json::Str({qualified:?}.into())),");
        for (f, _) in fields {
            let _ = writeln!(
                self.out,
                "            ({f:?}.into(), self.{}.to_json()),",
                ident(f)
            );
        }
        let _ = writeln!(self.out, "        ])\n    }}\n}}");
        let _ = writeln!(self.out, "impl{g} cpl::FromJson for {name}{gu} {{\n    fn from_json(j: &cpl::Json) -> Result<Self, ::std::string::String> {{\n        match j.get(\"$type\") {{\n            Some(cpl::Json::Str(t)) if t == {qualified:?} => {{}}\n            _ => return Err(\"expected a {bare}\".into()),\n        }}\n        Ok({name} {{");
        for (f, _) in fields {
            let _ = writeln!(self.out, "            {}: cpl::field(j, {f:?})?,", ident(f));
        }
        let _ = writeln!(self.out, "        }})\n    }}\n}}\n");
    }

    fn value_impls_enum(&mut self, d: DefId, name: &str, generics: &[String]) {
        let p = self.p;
        let e = p.def(d).kind.as_enum().expect("an enum");
        let g = generics_decl(generics, true);
        let gu = generics_use(generics);
        let qualified = crate::lower::type_name(p, d);
        // An enum without variants has no values: `match *self {}`.
        let subject = if e.variants.is_empty() {
            "*self"
        } else {
            "self"
        };
        let _ = writeln!(self.out, "impl{g} cpl::ValueText for {name}{gu} {{\n    fn write_text(&self, out: &mut ::std::string::String) {{\n        match {subject} {{");
        for v in &e.variants {
            let vn = ident(&v.name);
            if v.payload.is_empty() {
                let _ = writeln!(
                    self.out,
                    "            {name}::{vn} => out.push_str({:?}),",
                    v.name
                );
            } else {
                let xs: Vec<String> = (0..v.payload.len()).map(|i| format!("x{i}")).collect();
                let _ = writeln!(
                    self.out,
                    "            {name}::{vn}({}) => {{\n                out.push_str(\"{}(\");",
                    xs.join(", "),
                    v.name
                );
                for (i, x) in xs.iter().enumerate() {
                    if i > 0 {
                        let _ = writeln!(self.out, "                out.push_str(\", \");");
                    }
                    let _ = writeln!(self.out, "                {x}.write_text(out);");
                }
                let _ = writeln!(self.out, "                out.push(')');\n            }}");
            }
        }
        let _ = writeln!(self.out, "        }}\n    }}\n}}");
        let _ = writeln!(self.out, "impl{g} cpl::ToJson for {name}{gu} {{\n    fn to_json(&self) -> cpl::Json {{\n        match {subject} {{");
        for v in &e.variants {
            let vn = ident(&v.name);
            if v.payload.is_empty() {
                let _ = writeln!(
                    self.out,
                    "            {name}::{vn} => cpl::tagged({qualified:?}, Some({:?}), None),",
                    v.name
                );
            } else {
                let xs: Vec<String> = (0..v.payload.len()).map(|i| format!("x{i}")).collect();
                let js: Vec<String> = xs.iter().map(|x| format!("{x}.to_json()")).collect();
                let _ = writeln!(self.out, "            {name}::{vn}({}) => cpl::tagged({qualified:?}, Some({:?}), Some(vec![{}])),", xs.join(", "), v.name, js.join(", "));
            }
        }
        let _ = writeln!(self.out, "        }}\n    }}\n}}");
        let _ = writeln!(self.out, "impl{g} cpl::FromJson for {name}{gu} {{\n    fn from_json(j: &cpl::Json) -> Result<Self, ::std::string::String> {{\n        match cpl::untag(j, {qualified:?})? {{");
        for v in &e.variants {
            let vn = ident(&v.name);
            if v.payload.is_empty() {
                let _ = writeln!(
                    self.out,
                    "            ({:?}, []) => Ok({name}::{vn}),",
                    v.name
                );
            } else {
                let xs: Vec<String> = (0..v.payload.len()).map(|i| format!("x{i}")).collect();
                let fs: Vec<String> = xs
                    .iter()
                    .map(|x| format!("cpl::FromJson::from_json({x})?"))
                    .collect();
                let _ = writeln!(
                    self.out,
                    "            ({:?}, [{}]) => Ok({name}::{vn}({})),",
                    v.name,
                    xs.join(", "),
                    fs.join(", ")
                );
            }
        }
        let _ = writeln!(
            self.out,
            "            _ => Err(\"expected a {}\".into()),\n        }}\n    }}\n}}\n",
            p.def(d).name.display()
        );
    }

    // ---- functions -------------------------------------------------------------------

    fn sig_params(&self, f: &LFn) -> Vec<String> {
        f.params
            .iter()
            .chain(&f.using)
            .map(|v| {
                format!(
                    "mut v{v}: {}",
                    self.ty(&f.vars[*v as usize].ty, &f.generics)
                )
            })
            .collect()
    }

    fn function(&mut self, f: &LFn) {
        let p = self.p;
        let name = ident(&p.def(f.def).name.display());
        let g = generics_decl(&f.generics, true);
        let gu = generics_turbofish(&f.generics);
        let ret = self.ty(&f.ret, &f.generics);
        let mut params = self.sig_params(f);
        params.push("cx: &mut cpl::Cx".into());
        // Nothing reads a parameter after the body unless an `ensures` does: the body borrows
        // such a parameter (a `Bool` or a handle is copied), and the others are moved into it.
        let after = crate::moves::read_before_written(&f.ensures);
        let refs: BTreeSet<Var> = f
            .params
            .iter()
            .copied()
            .filter(|v| {
                let d = &f.vars[*v as usize];
                after.contains(v)
                    && !d.mutable
                    && !matches!(d.ty, Ty::Bool | Ty::Capability(_))
                    && !self.is_unit(&d.ty)
            })
            .collect();
        let args: Vec<String> = f
            .params
            .iter()
            .chain(&f.using)
            .map(|v| {
                if refs.contains(v) {
                    format!("&v{v}")
                } else if after.contains(v) {
                    self.read(*v, &f.vars)
                } else {
                    format!("v{v}")
                }
            })
            .collect();
        let mut fx = Fx {
            r: self,
            f_vars: &f.vars,
            generics: &f.generics,
            moves: crate::moves::movable(&f.body),
            refs: BTreeSet::new(),
        };
        let mut out = String::new();
        // the internal forms are the crate's: a host calls the host form, which checks its arguments
        let _ = writeln!(out, "#[doc(hidden)]\npub(crate) fn {name}__x{g}({}) -> Result<{ret}, cpl::Fault> {{", params.join(", "));
        if fx.r.q.has(f.def) {
            // the speculative form first (rust_q.rs); on None the generic form below runs
            let names: Vec<String> = f.params.iter().map(|v| format!("v{v}")).collect();
            let id = fx.r.fn_ids[&f.def];
            let w = fx.r.q.wrapper(p, f.def, &names, id, &|d| fx.r.path(d));
            out.push_str(&w);
        }
        out.push_str("    cx.enter()?;\n");
        // S35: the activation's measure slot exists from entry to exit, past the `ensures`.
        let id = fx.r.fn_ids[&f.def];
        if f.measure.is_some() {
            let _ = writeln!(out, "    cx.measure_push({id});");
        }
        fx.stmts(&f.requires, 1, &mut out);
        if let Some((stmts, value, clause)) = &f.measure {
            fx.stmts(stmts, 1, &mut out);
            let v = fx.expr(value);
            let _ = writeln!(
                out,
                "    cx.measure_set({id}, {v}, {clause:?}, {:?})?;",
                p.def(f.def).stable_id.as_str()
            );
        }
        let _ = writeln!(
            out,
            "    let __r = {name}__b{gu}({}cx)?;",
            args.iter().map(|a| format!("{a}, ")).collect::<String>()
        );
        if !f.ensures.is_empty() {
            // `result` is the returned value, borrowed
            if let Some(r) = f.result {
                let _ = writeln!(
                    out,
                    "    let v{r}: &{} = &__r;",
                    fx.r.ty(&f.vars[r as usize].ty, &f.generics)
                );
                fx.refs.insert(r);
            }
            fx.stmts(&f.ensures, 1, &mut out);
            fx.refs.clear();
        }
        if f.measure.is_some() {
            let _ = writeln!(out, "    cx.measure_pop();");
        }
        let _ = writeln!(out, "    cx.leave();\n    Ok(__r)\n}}\n");
        let mut body = String::new();
        let mut params: Vec<String> = f
            .params
            .iter()
            .chain(&f.using)
            .map(|v| {
                let t = fx.r.ty(&f.vars[*v as usize].ty, &f.generics);
                if refs.contains(v) {
                    format!("v{v}: &{t}")
                } else {
                    format!("mut v{v}: {t}")
                }
            })
            .collect();
        params.push("cx: &mut cpl::Cx".into());
        let _ = writeln!(
            body,
            "#[doc(hidden)]\n#[inline]\npub(crate) fn {name}__b{g}({}) -> Result<{ret}, cpl::Fault> {{",
            params.join(", ")
        );
        fx.refs = refs;
        fx.stmts(&f.body, 1, &mut body);
        if !diverges(&f.body) {
            body.push_str("    unreachable!(\"a body ends in a return\")\n");
        }
        body.push_str("}\n\n");
        self.out.push_str(&out);
        self.out.push_str(&body);
        if self.q.has(f.def) {
            let qf = self.q.functions(p, f.def, &|d| self.path(d));
            self.out.push_str(&qf);
        }
    }

    /// The host form of a `pub fn`: a fresh calling context and the boundary checks of its
    /// arguments (semantics S39, S81).
    fn host_function(&mut self, f: &LFn) {
        let p = self.p;
        let def = p.def(f.def);
        let fd = def.kind.as_fn().expect("a function");
        let name = ident(&def.name.display());
        let g = generics_decl(&f.generics, true);
        let gu = generics_turbofish(&f.generics);
        let ret = self.ty(&f.ret, &f.generics);
        let params: Vec<String> = fd
            .params
            .iter()
            .chain(&fd.using)
            .map(|q| format!("{}: {}", ident(&q.name), self.ty(&q.ty, &f.generics)))
            .collect();
        let _ = writeln!(
            self.out,
            "/// `{}`{}\npub fn {name}{g}({}) -> Result<{ret}, cpl::Fault> {{\n    let mut cx = cpl::Cx::new();",
            p.display_path(f.def),
            def.docs.as_ref().map(|d| format!(": {}", d.lines().next().unwrap_or(""))).unwrap_or_default(),
            params.join(", ")
        );
        {
            // every parameter whose type is closed, a generic function's included
            for q in &fd.params {
                if !crate::has_type_param(&q.ty) && needs_validation(p, &q.ty) {
                    let v = self.validator_name(&q.ty);
                    let _ = writeln!(
                        self.out,
                        "    if !crate::__validate::{v}(&{}, &mut cx).map_err(|f| cx.attribute(f))? {{\n        return Err(cpl::Fault::refinement({:?}, \"\", {:?}));\n    }}",
                        ident(&q.name),
                        p.display_ty(&q.ty),
                        def.stable_id.as_str()
                    );
                }
            }
        }
        let args: Vec<String> = fd
            .params
            .iter()
            .chain(&fd.using)
            .map(|q| ident(&q.name))
            .collect();
        let _ = writeln!(
            self.out,
            "    {name}__x{gu}({}&mut cx).map_err(|f| cx.attribute(f))\n}}\n",
            args.iter().map(|a| format!("{a}, ")).collect::<String>()
        );
    }

    fn pred(&mut self, q: &LPred) {
        let p = self.p;
        let name = ident(&p.def(q.def).name.display());
        let g = generics_decl(&q.generics, true);
        let self_ty = self.ty(&q.self_ty, &q.generics);
        let mut out = String::new();
        let _ = writeln!(out, "#[doc(hidden)]\npub fn __pred_{name}{g}(mut v{}: {self_ty}, cx: &mut cpl::Cx) -> Result<bool, cpl::Fault> {{", q.self_var);
        let mut fx = Fx {
            r: self,
            f_vars: &q.vars,
            generics: &q.generics,
            moves: HashSet::new(),
            refs: BTreeSet::new(),
        };
        fx.stmts(&q.body, 1, &mut out);
        if !diverges(&q.body) {
            let v = fx.expr(&q.value);
            let _ = writeln!(out, "    Ok({v})");
        }
        out.push_str("}\n\n");
        self.out.push_str(&out);
    }

    fn read(&self, v: Var, vars: &[VarDef]) -> String {
        match &vars[v as usize].ty {
            Ty::Bool | Ty::Capability(_) => format!("v{v}"),
            t if self.is_unit(t) => format!("v{v}"),
            _ => format!("v{v}.clone()"),
        }
    }

    // ---- validation at the boundary ---------------------------------------------------

    fn validator_name(&mut self, ty: &Ty) -> String {
        let key = self.p.display_ty(ty);
        let n = self.validators.len();
        let name = self
            .validators
            .entry(key.clone())
            .or_insert_with(|| format!("valid_{n}"))
            .clone();
        self.pending.push((key, ty.clone()));
        name
    }

    fn validator(&mut self, key: &str, ty: &Ty) {
        let p = self.p;
        let name = self.validators[key].clone();
        let t = self.ty(ty, &[]);
        let mut body = String::new();
        match ty {
            Ty::Refined(..) => {
                let base = match ty {
                    Ty::Refined(_, d) => p.def(*d).kind.as_refinement().map(|r| r.base.clone()),
                    _ => None,
                };
                if let Some(b) = base.filter(|b| needs_validation(p, b)) {
                    let v = self.validator_name(&b);
                    let _ = writeln!(body, "    if !{v}(x, cx)? {{ return Ok(false); }}");
                }
                if let Ty::Refined(_, d) = ty {
                    for r in crate::lower::check_order(p, *d) {
                        let _ = writeln!(
                            body,
                            "    if !{}::__pred_{}(x.clone(), cx)? {{ return Ok(false); }}",
                            self.module_of(r),
                            ident(&p.def(r).name.display())
                        );
                    }
                }
            }
            Ty::List(e) => {
                let v = self.validator_name(e);
                let _ = writeln!(
                    body,
                    "    for y in x.iter() {{ if !{v}(y, cx)? {{ return Ok(false); }} }}"
                );
            }
            Ty::Wrapper(d) => {
                if let Some(w) = p.def(*d).kind.as_wrapper() {
                    let v = self.validator_name(&w.inner);
                    let _ = writeln!(body, "    if !{v}(&x.0, cx)? {{ return Ok(false); }}");
                }
            }
            Ty::Adt(d, args) => {
                match (std_type(p, *d), &p.def(*d).kind) {
                    (Some(StdType::Option), _) => {
                        if needs_validation(p, &args[0]) {
                            let v = self.validator_name(&args[0]);
                            let _ = writeln!(body, "    if let Some(y) = x {{ if !{v}(y, cx)? {{ return Ok(false); }} }}");
                        }
                    }
                    (Some(StdType::Result), _) => {
                        for (i, a) in args.iter().enumerate() {
                            if needs_validation(p, a) {
                                let v = self.validator_name(a);
                                let pat = if i == 0 { "Ok(y)" } else { "Err(y)" };
                                let _ = writeln!(body, "    if let {pat} = x {{ if !{v}(y, cx)? {{ return Ok(false); }} }}");
                            }
                        }
                    }
                    (_, DefKind::Struct(s)) => {
                        for f in &s.fields {
                            let ft = instantiate(&f.ty, args);
                            if needs_validation(p, &ft) {
                                let v = self.validator_name(&ft);
                                let _ = writeln!(
                                    body,
                                    "    if !{v}(&x.{}, cx)? {{ return Ok(false); }}",
                                    ident(&f.name)
                                );
                            }
                        }
                        if s.invariant.is_some() {
                            let _ = writeln!(
                                body,
                                "    if !{}::__pred_{}{}(x.clone(), cx)? {{ return Ok(false); }}",
                                self.module_of(*d),
                                ident(&p.def(*d).name.display()),
                                turbofish_args(self, args)
                            );
                        }
                    }
                    (_, DefKind::Enum(e)) => {
                        let path = self.path(*d);
                        for v in &e.variants {
                            let tys: Vec<Ty> =
                                v.payload.iter().map(|t| instantiate(t, args)).collect();
                            if !tys.iter().any(|t| needs_validation(p, t)) {
                                continue;
                            }
                            let xs: Vec<String> = (0..tys.len()).map(|i| format!("y{i}")).collect();
                            let _ = writeln!(
                                body,
                                "    if let {path}::{}({}) = x {{",
                                ident(&v.name),
                                xs.join(", ")
                            );
                            for (i, t) in tys.iter().enumerate() {
                                if needs_validation(p, t) {
                                    let vn = self.validator_name(t);
                                    let _ = writeln!(
                                        body,
                                        "        if !{vn}(y{i}, cx)? {{ return Ok(false); }}"
                                    );
                                }
                            }
                            let _ = writeln!(body, "    }}");
                        }
                    }
                    _ => {}
                }
            }
            _ => {}
        }
        let _ = writeln!(self.out, "    pub fn {name}(x: &{t}, cx: &mut cpl::Cx) -> Result<bool, cpl::Fault> {{\n{body}    Ok(true)\n    }}");
    }

    fn module_of(&self, d: DefId) -> String {
        let mut s = String::from("crate");
        for seg in module_path(self.p, d) {
            s.push_str("::");
            s.push_str(&ident(&seg));
        }
        s
    }

    // ---- the JSON driver ---------------------------------------------------------------

    fn driver(&mut self, lowered: &Lowered) {
        let p = self.p;
        let mut arms = String::new();
        for d in crate::driver_functions(p, lowered) {
            let def = p.def(d);
            let fd = def.kind.as_fn().expect("a function");
            let qualified = p.display_path(d);
            let _ = writeln!(arms, "        {qualified:?} => {{\n            if args.len() != {} {{ return outside(\"arity\"); }}", fd.params.len());
            let mut names = Vec::new();
            for (i, q) in fd.params.iter().enumerate() {
                let t = self.ty(&q.ty, &[]);
                let _ = writeln!(arms, "            let a{i}: {t} = match cpl::FromJson::from_json(&args[{i}]) {{ Ok(v) => v, Err(e) => return outside(&e) }};");
                if needs_validation(p, &q.ty) {
                    let v = self.validator_name(&q.ty);
                    let _ = writeln!(arms, "            match crate::__validate::{v}(&a{i}, &mut cx) {{ Ok(true) => {{}} Ok(false) => return outside(\"refinement\"), Err(f) => return fault(&cx.attribute(f)) }}");
                }
                names.push(format!("a{i}, "));
            }
            let _ = writeln!(arms, "            match {}::{}__x({}&mut cx) {{ Ok(v) => value(cpl::ToJson::to_json(&v)), Err(f) => fault(&cx.attribute(f)) }}\n        }}", self.module_of(d), ident(&def.name.display()), names.concat());
        }
        let _ = writeln!(
            self.out,
            r##"
#[doc(hidden)]
pub mod __driver {{
    use crate::cpl;
    use crate::__validate;

    fn outside(why: &str) -> cpl::Json {{
        cpl::Json::object(vec![("outside".into(), cpl::Json::Str(why.into()))])
    }}
    fn value(v: cpl::Json) -> cpl::Json {{
        cpl::Json::object(vec![("value".into(), v)])
    }}
    fn fault(f: &cpl::Fault) -> cpl::Json {{
        let mut fields = vec![
            ("code".into(), cpl::Json::Str(f.code.into())),
            ("symbol".into(), cpl::Json::Str(f.symbol.clone())),
        ];
        if let Some(k) = f.clause_kind {{
            fields.push(("clause_kind".into(), cpl::Json::Str(k.into())));
        }}
        cpl::Json::object(vec![("fault".into(), cpl::Json::object(fields))])
    }}

    /// One request: a function's qualified name and its arguments in value JSON.
    pub fn call(function: &str, args: &[cpl::Json]) -> cpl::Json {{
        let mut cx = cpl::Cx::new();
        match function {{
{arms}            _ => outside("unknown function"),
        }}
    }}

    pub fn main() {{
        use std::io::{{BufRead, Write}};
        let stdin = std::io::stdin();
        let mut stdout = std::io::stdout().lock();
        for line in stdin.lock().lines() {{
            let Ok(line) = line else {{ break }};
            if line.trim().is_empty() {{
                continue;
            }}
            let answer = match cpl::Json::parse(&line) {{
                Ok(request) => {{
                    let function = match request.get("function") {{ Some(cpl::Json::Str(s)) => s.clone(), _ => String::new() }};
                    let args = match request.get("args") {{ Some(cpl::Json::Array(a)) => a.clone(), _ => Vec::new() }};
                    let thread = std::thread::Builder::new().stack_size(64 << 20).spawn(move || call(&function, &args).to_text());
                    match thread.map(|t| t.join()) {{
                        Ok(Ok(text)) => text,
                        _ => r#"{{"panic":true}}"#.to_string(),
                    }}
                }}
                Err(e) => outside(&e).to_text(),
            }};
            let _ = writeln!(stdout, "{{answer}}");
            let _ = stdout.flush();
        }}
    }}
}}
"##
        );
    }
}

/// The printing context of one function body.
struct Fx<'a, 'p> {
    r: &'a mut Printer<'p>,
    f_vars: &'a [VarDef],
    generics: &'a [String],
    /// The reads printed as moves (`crate::moves`).
    moves: HashSet<usize>,
    /// The parameters the body borrows (`&T`): read by cloning through the reference, never
    /// moved.
    refs: BTreeSet<Var>,
}

impl Fx<'_, '_> {
    /// A chain of fields over a variable as a Rust place (`v3.line.sku`, `(*v3.next).value`),
    /// and whether it goes through an `Arc` (nothing can be moved out of it then).
    fn chain_place(&self, e: &LExpr) -> Option<(String, bool)> {
        let p = self.r.p;
        match e {
            LExpr::Var(v) if self.refs.contains(v) => Some((format!("(*v{v})"), true)),
            LExpr::Var(v) => Some((format!("v{v}"), false)),
            LExpr::Field {
                base, def, index, ..
            } => {
                let (b, through) = self.chain_place(base)?;
                let s = p.def(*def).kind.as_struct().expect("a struct");
                let f = ident(&s.fields[*index as usize].name);
                if std_type(p, *def).is_none() && self.r.boxed_field(*def, *index as usize) {
                    Some((format!("(*{b}.{f})"), true))
                } else {
                    Some((format!("{b}.{f}"), through))
                }
            }
            LExpr::Unwrap { base, def } => {
                let (b, through) = self.chain_place(base)?;
                if self.r.boxed_wrapper(*def) {
                    Some((format!("(*{b}.0)"), true))
                } else {
                    Some((format!("{b}.0"), through))
                }
            }
            _ => None,
        }
    }

    fn ty(&self, t: &Ty) -> String {
        self.r.ty(t, self.generics)
    }

    fn var_ty(&self, v: Var) -> String {
        self.ty(&self.f_vars[v as usize].ty)
    }

    fn stmts(&mut self, stmts: &[LStmt], depth: usize, out: &mut String) {
        for s in stmts {
            self.stmt(s, depth, out);
        }
    }

    fn stmt(&mut self, s: &LStmt, depth: usize, out: &mut String) {
        let pad = "    ".repeat(depth);
        match s {
            LStmt::Let { var, value } => {
                let e = self.expr(value);
                let _ = writeln!(out, "{pad}let mut v{var}: {} = {e};", self.var_ty(*var));
            }
            LStmt::Decl { var } => {
                let _ = writeln!(out, "{pad}let mut v{var}: {};", self.var_ty(*var));
            }
            LStmt::Assign { var, value } => {
                // `x = x ++ a ++ b ...` appends to a list or text nothing else shares, after
                // every part is computed (each sees `x` unchanged): a loop of appends is linear.
                if let LExpr::Op {
                    op: Op::Concat,
                    ty,
                    ..
                } = value
                {
                    let mut parts = Vec::new();
                    let mut e = value;
                    while let LExpr::Op {
                        op: Op::Concat,
                        args,
                        ..
                    } = e
                    {
                        parts.push(&args[1]);
                        e = &args[0];
                    }
                    if matches!(e, LExpr::Var(v) if v == var)
                        && matches!(ty, Ty::List(_) | Ty::Text)
                    {
                        parts.reverse();
                        if let [part] = parts.as_slice() {
                            let b = self.expr(part);
                            let _ = writeln!(out, "{pad}v{var}.append_mut(&{b});");
                        } else {
                            let _ = writeln!(out, "{pad}{{");
                            for (i, part) in parts.iter().enumerate() {
                                let b = self.expr(part);
                                let _ = writeln!(out, "{pad}    let __a{i} = {b};");
                            }
                            for i in 0..parts.len() {
                                let _ = writeln!(out, "{pad}    v{var}.append_mut(&__a{i});");
                            }
                            let _ = writeln!(out, "{pad}}}");
                        }
                        return;
                    }
                }
                let e = self.expr(value);
                let _ = writeln!(out, "{pad}v{var} = {e};");
            }
            LStmt::Expr(e) => {
                let e = self.expr(e);
                let _ = writeln!(out, "{pad}let _ = {e};");
            }
            LStmt::If { cond, then, els } => {
                let c = self.expr(cond);
                let _ = writeln!(out, "{pad}if {c} {{");
                self.stmts(then, depth + 1, out);
                if els.is_empty() {
                    let _ = writeln!(out, "{pad}}}");
                } else {
                    let _ = writeln!(out, "{pad}}} else {{");
                    self.stmts(els, depth + 1, out);
                    let _ = writeln!(out, "{pad}}}");
                }
            }
            LStmt::Match { scrutinee, arms } => {
                let label = format!("'m{scrutinee}_{}", out.len());
                let _ = writeln!(out, "{pad}{label}: {{");
                for arm in arms {
                    let mut opens = 0;
                    let mut lines = String::new();
                    let ty = self.f_vars[*scrutinee as usize].ty.clone();
                    // An arm after which the scrutinee is dead binds by moving out of it, when
                    // its pattern has one level (`Some(x)`): a failed `if let` moves nothing.
                    let owned = !self.refs.contains(scrutinee)
                        && self.moves.contains(&crate::moves::arm_site(arm))
                        && match &arm.pattern {
                            LPat::Bind(_) | LPat::Wild => true,
                            LPat::Ctor { args, .. } => {
                                args.iter().all(|a| matches!(a, LPat::Bind(_) | LPat::Wild))
                            }
                            _ => false,
                        };
                    let subject = if owned {
                        format!("v{scrutinee}")
                    } else {
                        format!("(&v{scrutinee})")
                    };
                    self.pattern(
                        &arm.pattern,
                        &subject,
                        &ty,
                        depth + 1,
                        &mut opens,
                        &mut lines,
                        owned,
                    );
                    out.push_str(&lines);
                    let inner = depth + 1 + opens;
                    self.stmts(&arm.body, inner, out);
                    if !diverges(&arm.body) {
                        let _ = writeln!(out, "{}break {label};", "    ".repeat(inner));
                    }
                    for k in (0..opens).rev() {
                        let _ = writeln!(out, "{}}}", "    ".repeat(depth + 1 + k));
                    }
                }
                let _ = writeln!(out, "{pad}    unreachable!(\"no arm matched\");\n{pad}}}");
            }
            LStmt::Loop { label, body } => {
                let _ = writeln!(out, "{pad}'l{label}: loop {{");
                self.stmts(body, depth + 1, out);
                let _ = writeln!(out, "{pad}}}");
            }
            LStmt::ForEach {
                label,
                var,
                list,
                body,
            } => {
                let l = match list {
                    LExpr::Var(v) => format!("v{v}.iter()"),
                    other => format!("{}.iter()", self.expr(other)),
                };
                let _ = writeln!(out, "{pad}'l{label}: for __it in {l} {{\n{pad}    let mut v{var}: {} = __it.clone();", self.var_ty(*var));
                self.stmts(body, depth + 1, out);
                let _ = writeln!(out, "{pad}}}");
            }
            LStmt::Break { label } => {
                let _ = writeln!(out, "{pad}break 'l{label};");
            }
            LStmt::Return(e) => {
                // A returned variable is not read again: it is moved.
                let e = match e {
                    LExpr::Var(v) if self.refs.contains(v) => format!("v{v}.clone()"),
                    LExpr::Var(v) => format!("v{v}"),
                    other => self.expr(other),
                };
                let _ = writeln!(out, "{pad}return Ok({e});");
            }
            LStmt::Fault(f) => {
                let kind = match f.clause_kind {
                    Some(k) => format!("Some({k:?})"),
                    None => "None".into(),
                };
                let _ = writeln!(
                    out,
                    "{pad}return Err(cpl::Fault::new({:?}, {kind}, {:?}, {:?}, {:?}));",
                    f.code, f.clause, f.symbol, f.message
                );
            }
            LStmt::Push { list, value } => {
                let e = self.expr(value);
                let _ = writeln!(out, "{pad}v{list}.push_mut({e});");
            }
            LStmt::ClauseEnter { owner } => {
                let _ = writeln!(out, "{pad}cx.clause_enter({owner:?});");
            }
            LStmt::ClauseLeave => {
                let _ = writeln!(out, "{pad}cx.clause_leave();");
            }
        }
    }

    /// Open the tests of `pat` against `subject` (a reference expression of type `&ty`),
    /// binding its variables; each `if` opened counts in `opens`.
    #[allow(clippy::too_many_arguments)]
    fn pattern(
        &mut self,
        pat: &LPat,
        subject: &str,
        ty: &Ty,
        depth: usize,
        opens: &mut usize,
        out: &mut String,
        // `subject` is a value the pattern may move out of, not a reference
        owned: bool,
    ) {
        let p = self.r.p;
        let pad = "    ".repeat(depth + *opens);
        match pat {
            LPat::Wild => {}
            LPat::Bind(v) if owned => {
                let _ = writeln!(out, "{pad}let mut v{v}: {} = {subject};", self.var_ty(*v));
            }
            LPat::Bind(v) => {
                let _ = writeln!(
                    out,
                    "{pad}let mut v{v}: {} = ({subject}).clone();",
                    self.var_ty(*v)
                );
            }
            LPat::Int(n) => {
                let _ = writeln!(out, "{pad}if *{subject} == {} {{", int_lit(n));
                *opens += 1;
            }
            LPat::Text(s) => {
                let _ = writeln!(out, "{pad}if {subject}.as_str() == {s:?} {{");
                *opens += 1;
            }
            LPat::Bool(b) => {
                let _ = writeln!(out, "{pad}if *{subject} == {b} {{");
                *opens += 1;
            }
            LPat::Unwrap { def, arg } => {
                let inner = p
                    .def(*def)
                    .kind
                    .as_wrapper()
                    .map(|w| w.inner.clone())
                    .unwrap_or(Ty::Error);
                let n = format!("w{}", out.len());
                let deref = if self.r.boxed_wrapper(*def) { "*" } else { "" };
                let _ = writeln!(out, "{pad}{{ let {n} = &{deref}{subject}.0;");
                *opens += 1;
                self.pattern(arg, &n, &inner, depth, opens, out, false);
            }
            LPat::Ctor {
                def,
                variant,
                args,
                ty,
            } => {
                let targs = match ty {
                    Ty::Adt(_, a) => a.clone(),
                    _ => Vec::new(),
                };
                let names: Vec<String> = (0..args.len())
                    .map(|i| format!("x{}_{i}", out.len()))
                    .collect();
                let path = match std_type(p, *def) {
                    Some(StdType::Option) => {
                        if *variant == 0 {
                            "Some".to_string()
                        } else {
                            "None".to_string()
                        }
                    }
                    Some(StdType::Result) => {
                        if *variant == 0 {
                            "Ok".to_string()
                        } else {
                            "Err".to_string()
                        }
                    }
                    Some(StdType::ForeignErrorKind) => format!(
                        "cpl::ForeignErrorKind::{}",
                        p.def(*def)
                            .kind
                            .as_enum()
                            .map(|e| e.variants[*variant as usize].name.clone())
                            .unwrap_or_default()
                    ),
                    _ => format!(
                        "{}::{}",
                        self.r.path(*def),
                        ident(
                            &p.def(*def)
                                .kind
                                .as_enum()
                                .map(|e| e.variants[*variant as usize].name.clone())
                                .unwrap_or_default()
                        )
                    ),
                };
                if names.is_empty() {
                    let _ = writeln!(out, "{pad}if let {path} = {subject} {{");
                } else {
                    let _ = writeln!(
                        out,
                        "{pad}if let {path}({}) = {subject} {{",
                        names.join(", ")
                    );
                }
                *opens += 1;
                let payload: Vec<Ty> = p
                    .def(*def)
                    .kind
                    .as_enum()
                    .map(|e| {
                        e.variants[*variant as usize]
                            .payload
                            .iter()
                            .map(|t| instantiate(t, &targs))
                            .collect()
                    })
                    .unwrap_or_default();
                for (i, ((a, n), t)) in args.iter().zip(&names).zip(payload).enumerate() {
                    let boxed = std_type(p, *def).is_none()
                        && self.r.boxed_payload(*def, *variant as usize, i);
                    // an owned `Arc` payload is still read through it
                    let subject = match (boxed, owned) {
                        (true, true) => format!("(&*{n})"),
                        (true, false) => format!("(&**{n})"),
                        (false, _) => n.clone(),
                    };
                    self.pattern(a, &subject, &t, depth, opens, out, owned && !boxed);
                }
            }
        }
        let _ = ty;
    }

    /// `e` as a place to borrow or compare without cloning it: a variable or a field of one;
    /// any other expression is its value, a temporary.
    fn place(&mut self, e: &LExpr) -> String {
        match self.chain_place(e) {
            Some((place, _)) => place,
            None => self.expr(e),
        }
    }

    fn expr(&mut self, e: &LExpr) -> String {
        let p = self.r.p;
        match e {
            LExpr::Var(v) if self.refs.contains(v) => format!("v{v}.clone()"),
            LExpr::Var(v) if self.moves.contains(&crate::moves::site(e)) => format!("v{v}"),
            LExpr::Var(v) => self.r.read(*v, self.f_vars),
            // the last read of a boxed field of an owned place: moved out of its box where nothing else holds it
            LExpr::Field {
                base, def, index, ..
            } if self.moves.contains(&crate::moves::site(e))
                && std_type(p, *def).is_none()
                && self.r.boxed_field(*def, *index as usize)
                && matches!(self.chain_place(base), Some((_, false))) =>
            {
                let (b, _) = self.chain_place(base).expect("a place");
                let s = p.def(*def).kind.as_struct().expect("a struct");
                format!("{b}.{}.into_inner()", ident(&s.fields[*index as usize].name))
            }
            LExpr::Unwrap { base, def }
                if self.moves.contains(&crate::moves::site(e))
                    && self.r.boxed_wrapper(*def)
                    && matches!(self.chain_place(base), Some((_, false))) =>
            {
                let (b, _) = self.chain_place(base).expect("a place");
                format!("{b}.0.into_inner()")
            }
            LExpr::Field { .. } | LExpr::Unwrap { .. } if self.chain_place(e).is_some() => {
                let (place, through) = self.chain_place(e).expect("a chain");
                if !through && self.moves.contains(&crate::moves::site(e)) {
                    place
                } else {
                    format!("{place}.clone()")
                }
            }
            LExpr::Int(n) => int_lit(n),
            LExpr::Text(s) => format!("cpl::Text::lit({s:?})"),
            LExpr::Bool(b) => b.to_string(),
            LExpr::Unit => "()".into(),
            LExpr::Call {
                def,
                generics,
                args,
                using,
            } => {
                let mut a: Vec<String> = args.iter().chain(using).map(|x| self.expr(x)).collect();
                a.push("cx".into());
                let turbo = if generics.is_empty() {
                    String::new()
                } else {
                    format!(
                        "::<{}>",
                        generics
                            .iter()
                            .map(|g| self.ty(g))
                            .collect::<Vec<_>>()
                            .join(", ")
                    )
                };
                format!(
                    "{}::{}__x{turbo}({})?",
                    self.r.module_of(*def),
                    ident(&p.def(*def).name.display()),
                    a.join(", ")
                )
            }
            LExpr::Builtin { id, args, .. } => {
                // The builtins that only read an argument borrow it (`list_len(&xs)`).
                let a: Vec<String> = args
                    .iter()
                    .enumerate()
                    .map(|(i, x)| {
                        if borrowed(id, i) {
                            format!("&{}", self.place(x))
                        } else {
                            self.expr(x)
                        }
                    })
                    .collect();
                let q = if FALLIBLE.contains(&id.as_str()) {
                    "?"
                } else {
                    ""
                };
                format!("cpl::{id}({}){q}", a.join(", "))
            }
            LExpr::Op { op, args, ty } => {
                // Arithmetic borrows its operands and comparisons take them by reference: a
                // variable or field is read in place, not cloned.
                let a: Vec<String> = if matches!(op, Op::Concat | Op::Not | Op::And | Op::Or) {
                    args.iter().map(|x| self.expr(x)).collect()
                } else {
                    args.iter().map(|x| self.place(x)).collect()
                };
                match op {
                    Op::Add => format!("cpl::Int::add(&{}, &{})", a[0], a[1]),
                    Op::Sub => format!("cpl::Int::sub(&{}, &{})", a[0], a[1]),
                    Op::Mul => format!("cpl::Int::mul(&{}, &{})", a[0], a[1]),
                    Op::Neg => format!("cpl::Int::neg(&{})", a[0]),
                    Op::Lt => format!("({} < {})", a[0], a[1]),
                    Op::Le => format!("({} <= {})", a[0], a[1]),
                    Op::Gt => format!("({} > {})", a[0], a[1]),
                    Op::Ge => format!("({} >= {})", a[0], a[1]),
                    Op::Eq => format!("({} == {})", a[0], a[1]),
                    Op::Ne => format!("({} != {})", a[0], a[1]),
                    Op::Not => format!("!({})", a[0]),
                    Op::And => format!("({} && {})", a[0], a[1]),
                    Op::Or => format!("({} || {})", a[0], a[1]),
                    Op::Concat => match erase(p, ty) {
                        Ty::Text => format!("cpl::concat_text({}, {})", a[0], a[1]),
                        Ty::Bytes => format!("cpl::concat_bytes({}, {})", a[0], a[1]),
                        _ => format!("cpl::concat_list({}, {})", a[0], a[1]),
                    },
                }
            }
            LExpr::Div { a, b, rem, symbol } => {
                let (a, b) = (self.place(a), self.place(b));
                let f = if *rem { "rem" } else { "div" };
                format!("cpl::Int::{f}(&{a}, &{b}, {symbol:?})?")
            }
            LExpr::Ctor {
                def,
                variant,
                args,
                ty,
            } => {
                let a: Vec<String> = args.iter().map(|x| self.expr(x)).collect();
                let targs = match ty {
                    Ty::Adt(_, t) => t.clone(),
                    _ => Vec::new(),
                };
                match std_type(p, *def) {
                    Some(StdType::Option) => {
                        let t = self.ty(&targs[0]);
                        if *variant == 0 {
                            format!("Option::<{t}>::Some({})", a[0])
                        } else {
                            format!("Option::<{t}>::None")
                        }
                    }
                    Some(StdType::Result) => {
                        let (t, e) = (self.ty(&targs[0]), self.ty(&targs[1]));
                        let v = if *variant == 0 { "Ok" } else { "Err" };
                        format!("Result::<{t}, {e}>::{v}({})", a[0])
                    }
                    Some(StdType::Unit) => "()".into(),
                    Some(StdType::ForeignErrorKind) => {
                        let e = p.def(*def).kind.as_enum().expect("an enum");
                        format!(
                            "cpl::ForeignErrorKind::{}",
                            e.variants[*variant as usize].name
                        )
                    }
                    _ => {
                        let e = p.def(*def).kind.as_enum().expect("an enum");
                        let path = self.r.ty_expr(ty, self.generics);
                        let v = ident(&e.variants[*variant as usize].name);
                        let a: Vec<String> = a
                            .into_iter()
                            .enumerate()
                            .map(|(i, x)| {
                                if self.r.boxed_payload(*def, *variant as usize, i) {
                                    let t = &e.variants[*variant as usize].payload[i];
                                    format!("{}({x})", self.r.boxing(t))
                                } else {
                                    x
                                }
                            })
                            .collect();
                        if a.is_empty() {
                            format!("{path}::{v}")
                        } else {
                            format!("{path}::{v}({})", a.join(", "))
                        }
                    }
                }
            }
            LExpr::Struct { def, fields, ty } => {
                let s = p.def(*def).kind.as_struct().expect("a struct");
                let a: Vec<String> = fields.iter().map(|x| self.expr(x)).collect();
                let path = match std_type(p, *def) {
                    Some(StdType::ConstraintError) => "cpl::ConstraintError".to_string(),
                    Some(StdType::ForeignError) => "cpl::ForeignError".to_string(),
                    Some(StdType::ForeignDetail) => "cpl::ForeignDetail".to_string(),
                    _ => self.r.ty_expr(ty, self.generics),
                };
                let fs: Vec<String> = s
                    .fields
                    .iter()
                    .zip(a)
                    .enumerate()
                    .map(|(i, (f, v))| {
                        if std_type(p, *def).is_none() && self.r.boxed_field(*def, i) {
                            format!("{}: {}({v})", ident(&f.name), self.r.boxing(&f.ty))
                        } else {
                            format!("{}: {v}", ident(&f.name))
                        }
                    })
                    .collect();
                format!("{path} {{ {} }}", fs.join(", "))
            }
            LExpr::Wrap { def, arg } => {
                let a = self.expr(arg);
                if self.r.boxed_wrapper(*def) {
                    format!("{}(cpl::Boxed::new({a}))", self.r.path(*def))
                } else {
                    format!("{}({a})", self.r.path(*def))
                }
            }
            LExpr::Field {
                base, def, index, ..
            } => {
                let s = p.def(*def).kind.as_struct().expect("a struct");
                let f = ident(&s.fields[*index as usize].name);
                let boxed =
                    std_type(p, *def).is_none() && self.r.boxed_field(*def, *index as usize);
                match (base.as_ref(), boxed) {
                    (LExpr::Var(v), false) => format!("v{v}.{f}.clone()"),
                    (LExpr::Var(v), true) => format!("(*v{v}.{f}).clone()"),
                    (other, false) => format!("({}).{f}", self.expr(other)),
                    (other, true) => format!("(*({}).{f}).clone()", self.expr(other)),
                }
            }
            LExpr::Payload {
                base,
                def,
                variant,
                index,
                ty,
            } => {
                let b = match base.as_ref() {
                    LExpr::Var(v) => format!("(&v{v})"),
                    other => format!("(&{})", self.expr(other)),
                };
                let n = match ty {
                    Ty::Adt(d, _) => p
                        .def(*d)
                        .kind
                        .as_enum()
                        .map_or(1, |e| e.variants[*variant as usize].payload.len()),
                    _ => 1,
                };
                let mut xs = vec!["_".to_string(); n];
                xs[*index as usize] = "x".into();
                let path = match std_type(p, *def) {
                    Some(StdType::Option) => "Some".to_string(),
                    Some(StdType::Result) => {
                        if *variant == 0 {
                            "Ok".into()
                        } else {
                            "Err".into()
                        }
                    }
                    _ => format!(
                        "{}::{}",
                        self.r.path(*def),
                        ident(
                            &p.def(*def)
                                .kind
                                .as_enum()
                                .map(|e| e.variants[*variant as usize].name.clone())
                                .unwrap_or_default()
                        )
                    ),
                };
                let boxed = std_type(p, *def).is_none()
                    && self
                        .r
                        .boxed_payload(*def, *variant as usize, *index as usize);
                let x = if boxed { "(**x).clone()" } else { "x.clone()" };
                format!(
                    "(match {b} {{ {path}({}) => {x}, _ => unreachable!() }})",
                    xs.join(", ")
                )
            }
            LExpr::IsVariant {
                base, def, variant, ..
            } => {
                let b = match base.as_ref() {
                    LExpr::Var(v) => format!("v{v}"),
                    other => self.expr(other),
                };
                let pat = match std_type(p, *def) {
                    Some(StdType::Option) => {
                        if *variant == 0 {
                            "Some(_)".to_string()
                        } else {
                            "None".to_string()
                        }
                    }
                    Some(StdType::Result) => {
                        if *variant == 0 {
                            "Ok(_)".to_string()
                        } else {
                            "Err(_)".to_string()
                        }
                    }
                    _ => {
                        let e = p.def(*def).kind.as_enum().expect("an enum");
                        let v = &e.variants[*variant as usize];
                        if v.payload.is_empty() {
                            format!("{}::{}", self.r.path(*def), ident(&v.name))
                        } else {
                            format!("{}::{}(..)", self.r.path(*def), ident(&v.name))
                        }
                    }
                };
                format!("matches!({b}, {pat})")
            }
            LExpr::Unwrap { base, def } => match (base.as_ref(), self.r.boxed_wrapper(*def)) {
                (LExpr::Var(v), false) => format!("v{v}.0.clone()"),
                (LExpr::Var(v), true) => format!("(*v{v}.0).clone()"),
                (other, false) => format!("({}).0", self.expr(other)),
                (other, true) => format!("(*({}).0).clone()", self.expr(other)),
            },
            LExpr::List { elem, items } => {
                if items.is_empty() {
                    format!("cpl::List::<{}>::new()", self.ty(elem))
                } else {
                    let a: Vec<String> = items.iter().map(|x| self.expr(x)).collect();
                    format!(
                        "cpl::List::<{}>::from_vec(vec![{}])",
                        self.ty(elem),
                        a.join(", ")
                    )
                }
            }
            LExpr::CapCall {
                handle,
                capability,
                op,
                args,
                ..
            } => {
                let opdef = &p
                    .def(*capability)
                    .kind
                    .as_capability()
                    .expect("a capability")
                    .ops[*op as usize];
                let h = self.expr(handle);
                let a: Vec<String> = args.iter().map(|x| self.expr(x)).collect();
                format!("{h}.{}({})", ident(&opdef.name), a.join(", "))
            }
            LExpr::Pred { def, generics, arg } => {
                let a = self.expr(arg);
                let turbo = if generics.is_empty() {
                    String::new()
                } else {
                    format!(
                        "::<{}>",
                        generics
                            .iter()
                            .map(|g| self.ty(g))
                            .collect::<Vec<_>>()
                            .join(", ")
                    )
                };
                format!(
                    "{}::__pred_{}{turbo}({a}, cx)?",
                    self.r.module_of(*def),
                    ident(&p.def(*def).name.display())
                )
            }
            // A Rust `str` is always Unicode: a type with nothing else to check is valid.
            LExpr::Valid { ty, .. } if !needs_validation(self.r.p, ty) => "true".into(),
            LExpr::Valid { ty, arg } => {
                let a = self.place(arg);
                let v = self.r.validator_name(ty);
                format!("crate::__validate::{v}(&{a}, cx)?")
            }
            LExpr::CheckFailure {
                value,
                value_ty,
                type_name,
                predicate,
                ..
            } => {
                let v = self.expr(value);
                format!(
                    "cpl::check_failure::<_, {}>(&{v}, {type_name:?}, {predicate:?})",
                    self.ty(value_ty)
                )
            }
        }
    }
}

/// Whether builtin `id` borrows its argument `i` (it only reads it).
fn borrowed(id: &str, i: usize) -> bool {
    match id {
        "list_len" | "list_is_empty" | "list_first" | "list_last" | "list_drop_last"
        | "list_get" | "list_take" | "list_drop" | "text_len" | "text_is_empty" | "bytes_len"
        | "bytes_is_empty" | "option_is_some" | "option_is_none" | "result_is_ok"
        | "result_is_err" => i == 0,
        "list_contains" | "text_starts_with" | "text_ends_with" | "text_contains" => i < 2,
        _ => false,
    }
}

fn int_lit(n: &num_bigint::BigInt) -> String {
    match n.to_i64() {
        Some(v) => format!("cpl::Int::small({v})"),
        None => format!("cpl::Int::lit({:?})", n.to_string()),
    }
}

pub(crate) fn ident(name: &str) -> String {
    if RESERVED.contains(&name) {
        format!("{name}_")
    } else {
        name.to_string()
    }
}

/// `<GT: cpl::Value, GU: cpl::Value>`; `bounds` false for a type declaration's own list.
fn generics_decl(generics: &[String], bounds: bool) -> String {
    if generics.is_empty() {
        return String::new();
    }
    let gs: Vec<String> = generics
        .iter()
        .map(|g| format!("G{g}: cpl::Value"))
        .collect();
    let _ = bounds;
    format!("<{}>", gs.join(", "))
}

fn generics_use(generics: &[String]) -> String {
    if generics.is_empty() {
        return String::new();
    }
    format!(
        "<{}>",
        generics
            .iter()
            .map(|g| format!("G{g}"))
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn generics_turbofish(generics: &[String]) -> String {
    if generics.is_empty() {
        return String::new();
    }
    format!(
        "::<{}>",
        generics
            .iter()
            .map(|g| format!("G{g}"))
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn turbofish_args(r: &Printer<'_>, args: &[Ty]) -> String {
    if args.is_empty() {
        return String::new();
    }
    format!(
        "::<{}>",
        args.iter()
            .map(|a| r.ty(a, &[]))
            .collect::<Vec<_>>()
            .join(", ")
    )
}
