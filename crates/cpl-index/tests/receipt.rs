#[test]
fn receipt_inputs_record_every_source_set_file() {
    let (project, inputs) = reader_inputs();
    let root = workspace_path("examples/reader");
    let paths: Vec<&str> = inputs.sources.keys().map(String::as_str).collect();
    // The 8.1 example's list: cpl.toml included, cpl.lock and std never.
    assert_eq!(
        paths,
        [
            "cpl.toml",
            "src/reader/images.cpl",
            "src/reader/pages.cpl",
            "src/tests/pagination.cpl",
            "work/pagination.patch",
            "work/pagination.work"
        ]
    );
    for (path, digest) in &inputs.sources {
        let bytes = std::fs::read(root.join(path)).expect("read");
        assert_eq!(digest.as_str(), blake3_hex(&bytes), "{path}");
    }
    assert_eq!(inputs.manifest_digest, inputs.sources["cpl.toml"]);
    assert_eq!(inputs.std_digest, project.std_digest());
    assert_eq!(
        inputs.std_digest,
        cpl_project::std_digest(cpl_project::STD_FILES)
    );
    assert_eq!(inputs.lock_digest, None);
    assert_eq!(inputs.toolchain, ToolchainInfo::current());
    assert_eq!(inputs.revision.digest, source_digest(&project));
    // Section 6.3: blake3 of one `<path> <hex>` line per file, in path order.
    let lines: String = inputs
        .sources
        .iter()
        .map(|(path, digest)| format!("{path} {digest}\n"))
        .collect();
    assert_eq!(
        source_digest(&project).as_str(),
        blake3_hex(lines.as_bytes())
    );
    // The work files are digested even when they are not parsed.
    let unparsed =
        cpl_project::load_project(&root, &cpl_project::LoadOptions::default()).expect("load");
    assert_eq!(source_digest(&unparsed), source_digest(&project));
}

#[test]
fn the_lock_digest_is_blake3_of_cpl_lock() {
    let project = load_tree(&tree(&[("src/t.cpl", "module t\n")]));
    let lock = format!(
        "# Generated by cpl. Do not edit.\nversion = 1\n\n[toolchain]\ncpl = \"{}\"\nedition = \"0.1\"\nstd = \"{}\"\n\n[sources]\n\"cpl.toml\" = \"{}\"\n\n[verification]\nproof_timeout_ms = 10000\nadmit = []\n\n[foreign]\n[adapters]\n[targets]\n",
        cpl_diag::version::TOOLCHAIN,
        project.std_digest(),
        project.manifest_digest
    );
    let mut locked = tree(&[("src/t.cpl", "module t\n")]);
    locked
        .files
        .insert("cpl.lock".into(), lock.clone().into_bytes());
    let locked = load_tree(&locked);
    assert!(locked.lock.is_some());
    let inputs = receipt_inputs(&locked, unversioned(&locked));
    assert_eq!(
        inputs.lock_digest.as_ref().map(Digest::as_str),
        Some(blake3_hex(lock.as_bytes()).as_str())
    );
    // The lock is not a source-set member: no source digest changes.
    assert!(!inputs.sources.contains_key("cpl.lock"));
    assert_eq!(source_digest(&locked), source_digest(&project));
    assert_eq!(inputs.to_json().lock, inputs.lock_digest);
}

