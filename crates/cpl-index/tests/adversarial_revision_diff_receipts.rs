#[test]
fn source_digest_lines_are_in_byte_order_of_the_path() {
    let files = [
        ("src/a_b.cpl", "module a_b\n"),
        ("src/a/b.cpl", "module a.b\n"),
        ("src/a.cpl", "module a\n"),
        ("src/a-b.cpl", "module dash\n"),
        ("src/B.cpl", "module upper\n"),
        ("work/x.work", "change c {\n}\n"),
        (
            "work/x.patch",
            "patch f.body\n    expect base(f.body)\n{\n    1\n}\n",
        ),
    ];
    let project = load_vtree(&vtree(&files));
    // Section 6.3: one `<path> <hex>` line per file "in path order". Path
    // order is the byte order of the '/'-separated project-relative path
    // (T15's "lexicographic order of project-relative path", T4's BTreeMap
    // order): capitals first, and '-' < '.' < '/' < '_', so a component-wise
    // order (src/a/b.cpl before src/a-b.cpl) would be another digest.
    let order = [
        "cpl.toml",
        "src/B.cpl",
        "src/a-b.cpl",
        "src/a.cpl",
        "src/a/b.cpl",
        "src/a_b.cpl",
        "work/x.patch",
        "work/x.work",
    ];
    let bytes_of = |path: &str| -> &'static [u8] {
        if path == "cpl.toml" {
            MANIFEST.as_bytes()
        } else {
            files
                .iter()
                .find(|(p, _)| *p == path)
                .expect("a file")
                .1
                .as_bytes()
        }
    };
    let lines: String = order
        .iter()
        .map(|path| format!("{path} {}\n", blake3_hex(bytes_of(path))))
        .collect();
    let digest = source_digest(&project);
    assert_eq!(digest.as_str(), blake3_hex(lines.as_bytes()));
    assert!(is_lower_hex(digest.as_str(), 64), "{digest}");
}

#[test]
fn source_digest_covers_members_that_do_not_parse_or_are_not_utf8() {
    let broken = "module broken\n\nfn ( {\n";
    let latin1: &[u8] = b"module latin\n\n// caf\xe9\n";
    let mut tree = vtree(&[("src/ok.cpl", "module ok\n"), ("src/broken.cpl", broken)]);
    tree.files
        .insert("src/latin1.cpl".to_string(), latin1.to_vec());
    let project = load_vtree(&tree);
    let failed = project
        .parsed
        .iter()
        .filter(|p| matches!(p, ParsedFile::Failed))
        .count();
    assert_eq!(failed, 2, "precondition: two members that do not parse");
    // Section 0: every *.cpl file under the source directories is a member,
    // parsed or not; Section 6.3 digests its bytes, not a decoded text.
    let lines = format!(
        "cpl.toml {}\nsrc/broken.cpl {}\nsrc/latin1.cpl {}\nsrc/ok.cpl {}\n",
        blake3_hex(MANIFEST.as_bytes()),
        blake3_hex(broken.as_bytes()),
        blake3_hex(latin1),
        blake3_hex(b"module ok\n"),
    );
    assert_eq!(
        source_digest(&project).as_str(),
        blake3_hex(lines.as_bytes())
    );
    // Another invalid byte decodes to the same replacement character, but
    // the bytes, and so the revision, differ.
    let mut edited = tree.clone();
    let bytes = edited.files.get_mut("src/latin1.cpl").expect("the file");
    let at = bytes.iter().position(|&b| b == 0xe9).expect("the byte");
    bytes[at] = 0xe8;
    assert_ne!(source_digest(&load_vtree(&edited)), source_digest(&project));
}

#[test]
fn source_digest_ignores_the_lock_and_files_outside_the_source_set() {
    let base = vtree(&[
        ("src/m.cpl", "module m\n"),
        ("work/plan.work", "change c {\n}\n"),
    ]);
    let reference = source_digest(&load_vtree(&base));
    let lock = lock_text(10_000);
    let outsiders = [
        ("cpl.lock", lock.as_str()),
        ("work/deep/nested.work", "change d {\n}\n"),
        ("work/deep/nested.patch", "patch\n"),
        ("work/notes.md", "notes\n"),
        ("work/w.cpl", "module w\n"),
        ("src/notes.txt", "notes\n"),
        ("src/m.cpl.orig", "module m\n"),
        ("other/o.cpl", "module o\n"),
        ("root.cpl", "module root\n"),
        ("srcx/y.cpl", "module y\n"),
    ];
    for (path, text) in outsiders {
        let mut tree = base.clone();
        tree.files
            .insert(path.to_string(), text.as_bytes().to_vec());
        assert_eq!(
            source_digest(&load_vtree(&tree)),
            reference,
            "{path} is not a member of the source set (Section 0)"
        );
    }
    for (path, text) in [
        ("work/new.patch", "patch\n"),
        ("work/new.work", "change n {\n}\n"),
        ("src/deep/er/n.cpl", "module deep.er\n"),
    ] {
        let mut tree = base.clone();
        tree.files
            .insert(path.to_string(), text.as_bytes().to_vec());
        assert_ne!(
            source_digest(&load_vtree(&tree)),
            reference,
            "{path} is a member of the source set (Section 0)"
        );
    }
    for path in ["cpl.toml", "src/m.cpl", "work/plan.work"] {
        let mut tree = base.clone();
        tree.files
            .get_mut(path)
            .expect("a member")
            .extend_from_slice(b"\n");
        assert_ne!(
            source_digest(&load_vtree(&tree)),
            reference,
            "the bytes of {path} are digested"
        );
    }
}

#[test]
fn receipt_inputs_are_exactly_the_source_set_with_raw_byte_digests() {
    let lock = lock_text(5_000);
    let latin1: &[u8] = b"module latin\n\n// caf\xe9\n";
    let mut tree = vtree(&[
        ("cpl.lock", lock.as_str()),
        ("src/ok.cpl", "module ok\n"),
        ("src/broken.cpl", "module broken\n\nfn ( {\n"),
        ("src/notes.txt", "notes\n"),
        ("work/plan.work", "change c {\n}\n"),
        ("work/fix.patch", "patch\n"),
        ("work/deep/x.work", "change x {\n}\n"),
        ("work/readme.md", "readme\n"),
        ("other/o.cpl", "module o\n"),
    ]);
    tree.files
        .insert("src/latin1.cpl".to_string(), latin1.to_vec());
    let project = load_vtree(&tree);
    let revision = Revision {
        commit: Some("ab".repeat(20)),
        state: WORKTREE,
        digest: source_digest(&project),
    };
    let inputs = receipt_inputs(&project, revision.clone());
    // Section 8 `inputs.sources`: every source-set file, `cpl.toml`
    // included; never `cpl.lock` or std (Section 0).
    let paths: Vec<&str> = inputs.sources.keys().map(String::as_str).collect();
    assert_eq!(
        paths,
        [
            "cpl.toml",
            "src/broken.cpl",
            "src/latin1.cpl",
            "src/ok.cpl",
            "work/fix.patch",
            "work/plan.work"
        ]
    );
    for (path, digest) in &inputs.sources {
        assert_eq!(digest.as_str(), blake3_hex(&tree.files[path]), "{path}");
    }
    assert_eq!(
        inputs.manifest_digest.as_str(),
        blake3_hex(MANIFEST.as_bytes())
    );
    assert_eq!(
        inputs.lock_digest.as_ref().map(Digest::as_str),
        Some(blake3_hex(lock.as_bytes()).as_str())
    );
    // Section 3.6: `name LF content LF` of every std file in sorted order.
    assert_eq!(
        inputs.std_digest.as_str(),
        std_digest_of_the_std_directory()
    );
    assert_eq!(inputs.revision, revision);
    assert_eq!(
        inputs.toolchain,
        ToolchainInfo {
            version: cpl_diag::version::TOOLCHAIN.to_string(),
            edition: "0.1".to_string(),
            json_schema: 1,
        }
    );
    // The `inputs` object of 8.1, keys in its order.
    let json = inputs.to_json();
    assert_eq!(json.sources, inputs.sources);
    let text = serde_json::to_string(&json).expect("serializes");
    let at: Vec<usize> = ["\"manifest\":", "\"lock\":", "\"std\":", "\"sources\":"]
        .iter()
        .map(|key| text.find(key).unwrap_or_else(|| panic!("{key} in {text}")))
        .collect();
    assert!(at.windows(2).all(|w| w[0] < w[1]), "{text}");
}

