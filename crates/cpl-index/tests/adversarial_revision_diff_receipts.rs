#[test]
fn staged_deleted_and_untracked_members_make_the_revision_worktree() {
    if !git_available() {
        return;
    }
    let repo = TestRepo::init("dirty-kinds");
    repo.write(&[
        ("cpl.toml", MANIFEST),
        ("src/m.cpl", "module m\n"),
        ("src/n.cpl", "module n\n"),
        ("work/plan.work", "change c {\n}\n"),
    ]);
    let head = repo.commit("one");
    let git = discovered(&repo.dir);
    let revision = || current_revision(&load_dir(&repo.dir), Some(&git)).expect("revision");
    let clean = revision();
    assert_eq!(clean.state, CLEAN);

    // A staged modification (Section 6.3: `git status --porcelain` lists it).
    repo.write(&[("src/m.cpl", "module m\n\nfn f() -> Int {\n    1\n}\n")]);
    repo.git(&["add", "src/m.cpl"]);
    let staged = revision();
    assert_eq!(staged.state, WORKTREE);
    assert_eq!(staged.commit.as_deref(), Some(head.as_str()));
    assert_ne!(staged.digest, clean.digest);
    repo.git(&["reset", "-q", "--hard", "HEAD"]);
    assert_eq!(revision(), clean);

    // A deleted member.
    repo.remove("src/n.cpl");
    let deleted = revision();
    assert_eq!(deleted.state, WORKTREE);
    assert_ne!(deleted.digest, clean.digest);
    repo.git(&["checkout", "--", "src/n.cpl"]);
    assert_eq!(revision(), clean);

    // A staged deletion of a file still on disk: the bytes are HEAD's, the
    // index is not.
    repo.git(&["rm", "-q", "--cached", "src/n.cpl"]);
    let unstaged = revision();
    assert_eq!(unstaged.state, WORKTREE);
    assert_eq!(unstaged.digest, clean.digest);
    repo.git(&["reset", "-q", "--", "src/n.cpl"]);
    assert_eq!(revision(), clean);

    // An untracked patch directly under work/ (a source-set member).
    repo.write(&[("work/fix.patch", "patch f.body\n{\n    1\n}\n")]);
    assert_eq!(revision().state, WORKTREE);
    repo.remove("work/fix.patch");
    assert_eq!(revision(), clean);
}

