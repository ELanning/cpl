#[test]
fn malformed_locks_are_lock_errors() {
    let good = render_lock(&sample());
    let cases: Vec<(String, &str)> = vec![
        ("version = \n".to_string(), "cpl.lock is not valid TOML: "),
        (
            good.replace("version = 1", "version = 2"),
            "unsupported cpl.lock version 2",
        ),
        (
            good.replace("version = 1", "version = \"1\""),
            "`version` in cpl.lock must be an integer",
        ),
        (
            good.replace("version = 1\n", ""),
            "missing required key `version`",
        ),
        (
            good.replace("[toolchain]\n", "[toolchains]\n"),
            "unknown key `toolchains`",
        ),
        (format!("{good}[extra]\n"), "unknown key `extra`"),
        (
            good.replace("edition = \"0.1\"\n", ""),
            "missing required key `toolchain.edition`",
        ),
        (
            good.replace("edition = \"0.1\"", "edition = 0"),
            "`toolchain.edition` in cpl.lock must be a string",
        ),
        (
            good.replace("edition = \"0.1\"", "edition = \"0.1\"\nextra = 1"),
            "unknown key `toolchain.extra`",
        ),
        (
            good.replace(&format!("std = \"{}\"", hex('a')), "std = \"abc\""),
            "`toolchain.std` in cpl.lock must be a digest",
        ),
        (
            good.replace(
                &format!("std = \"{}\"", hex('a')),
                &format!("std = \"{}\"", hex('A')),
            ),
            "`toolchain.std` in cpl.lock must be a digest",
        ),
        (
            good.replace(&hex('2'), "nothex"),
            "`sources.\"src/reader/pages.cpl\"` in cpl.lock must be a digest",
        ),
        (
            good.replace(
                &format!("\"cpl.toml\" = \"{}\"", hex('1')),
                "\"cpl.toml\" = 1",
            ),
            "`sources.\"cpl.toml\"` in cpl.lock must be a digest string",
        ),
        (
            good.replace("[sources]\n", "[sourcez]\n"),
            "unknown key `sourcez`",
        ),
        (
            good.replace("proof_timeout_ms = 10000", "proof_timeout_ms = -1"),
            "`verification.proof_timeout_ms` in cpl.lock must be a non-negative integer",
        ),
        (
            good.replace("proof_timeout_ms = 10000\n", ""),
            "missing required key `verification.proof_timeout_ms`",
        ),
        (
            good.replace("admit = []", "admit = [1]"),
            "`verification.admit` in cpl.lock must be an array of strings",
        ),
        (
            good.replace("admit = []", "admit = \"x\""),
            "`verification.admit` in cpl.lock must be an array of strings",
        ),
        (
            good.replace("admit = []\n", ""),
            "missing required key `verification.admit`",
        ),
        (
            good.replace("admit = []", "admit = []\nextra = 1"),
            "unknown key `verification.extra`",
        ),
        (good.replace("[foreign]\n", "foreign = 1\n"), ""),
    ];
    for (text, message) in cases {
        let Err(e) = parse_lock(&text) else {
            panic!("expected a LockError for\n{text}");
        };
        assert!(
            e.message.contains(message),
            "{:?} does not contain {message:?}\n{text}",
            e.message
        );
    }
    let e = parse_lock("version = 1\n[toolchain\n").unwrap_err();
    assert_eq!(e.line, Some(2));
    let e = parse_lock(&good.replace("[verification]\nproof_timeout_ms = 10000\nadmit = []\n", ""))
        .unwrap_err();
    assert_eq!(
        e.message,
        "missing required table `[verification]` in cpl.lock"
    );
}

#[test]
fn a_lock_that_does_not_parse_is_load_error_lock() {
    let tree = tree(&[
        ("cpl.toml", MANIFEST),
        ("cpl.lock", "version = 2\n"),
        ("src/a.cpl", "module a\n"),
    ]);
    match load_project_from_tree(&tree, FileOrigin::Virtual, &LoadOptions::default()) {
        Err(LoadError::Lock { path, message, .. }) => {
            assert_eq!(path, "cpl.lock");
            assert!(
                message.starts_with("unsupported cpl.lock version 2"),
                "{message}"
            );
        }
        other => panic!("expected LoadError::Lock, found {other:?}"),
    }

    let mut tree = tree;
    tree.files
        .insert("cpl.lock".to_string(), b"version = 1\n# \xfe\n".to_vec());
    match load_project_from_tree(&tree, FileOrigin::Virtual, &LoadOptions::default()) {
        Err(LoadError::Lock {
            path,
            message,
            line,
        }) => {
            assert_eq!(path, "cpl.lock");
            assert!(
                message.starts_with("cpl.lock is not valid UTF-8"),
                "{message}"
            );
            assert_eq!(line, Some(2));
        }
        other => panic!("expected LoadError::Lock, found {other:?}"),
    }
}

// ---- loading's part ---------------------------------------------------------------

fn current_lock() -> Lock {
    let mut lock = sample();
    lock.toolchain.cpl = version::TOOLCHAIN.to_string();
    lock.toolchain.edition = version::EDITION.to_string();
    lock.toolchain.std = std_digest(STD_FILES);
    lock
}

#[test]
fn a_present_lock_is_parsed_into_the_project() {
    let lock = current_lock();
    let tree = tree(&[
        ("cpl.toml", MANIFEST),
        ("cpl.lock", &render_lock(&lock)),
        ("src/a.cpl", "module a\n"),
    ]);
    let project = load_tree(&tree, false);
    assert_eq!(project.lock, Some(lock));
    assert!(project.diagnostics.is_empty(), "{:?}", project.diagnostics);
    // The lock is not a member of the source set: not registered, not digested.
    assert_eq!(project_paths(&project), ["src/a.cpl"]);
}

#[test]
fn a_lock_from_another_toolchain_is_project_lock_toolchain_mismatch() {
    for (cpl, edition) in [
        ("0.0.9", version::EDITION),
        (version::TOOLCHAIN, "0.0"),
        ("9.9.9", "9.9"),
    ] {
        let mut lock = current_lock();
        lock.toolchain.cpl = cpl.to_string();
        lock.toolchain.edition = edition.to_string();
        let tree = tree(&[
            ("cpl.toml", MANIFEST),
            ("cpl.lock", &render_lock(&lock)),
            ("src/a.cpl", "module a\n"),
        ]);
        let project = load_tree(&tree, false);
        assert_eq!(
            codes(&project.diagnostics),
            ["project_lock_toolchain_mismatch"]
        );
        let d = &project.diagnostics[0];
        assert_eq!(d.code, codes::PROJECT_LOCK_TOOLCHAIN_MISMATCH);
        assert_eq!(
            (d.category, d.severity, d.span),
            (Category::Project, Severity::Warning, None)
        );
        assert_eq!(d.data["found"], json!({ "cpl": cpl, "edition": edition }));
        assert_eq!(
            d.data["expected"],
            json!({ "cpl": version::TOOLCHAIN, "edition": version::EDITION })
        );
        assert_eq!(project.lock, Some(lock));
    }
}

#[test]
fn loading_reports_neither_a_missing_nor_a_stale_lock() {
    // `project_lock_missing` and `project_lock_stale` are `cpl check
    // --release`'s (Section 11.2, T37), never loading's.
    let project = load_dir(&example("reader"), true);
    assert!(project.lock.is_none());
    assert!(project.diagnostics.is_empty());

    let mut stale = current_lock();
    stale.sources = BTreeMap::from([("src/gone.cpl".to_string(), Digest(hex('f')))]);
    stale.verification.proof_timeout_ms = 1;
    stale.toolchain.std = Digest(hex('0'));
    let tree = tree(&[
        ("cpl.toml", MANIFEST),
        ("cpl.lock", &render_lock(&stale)),
        ("src/a.cpl", "module a\n"),
    ]);
    let project = load_tree(&tree, false);
    assert!(project.diagnostics.is_empty(), "{:?}", project.diagnostics);
    assert_eq!(project.lock, Some(stale));
}
