use std::collections::BTreeMap;

fn hex(c: char) -> String {
    std::iter::repeat_n(c, 64).collect()
}

fn sample() -> Lock {
    Lock {
        version: 1,
        toolchain: LockToolchain {
            cpl: "0.1.0".to_string(),
            edition: "0.1".to_string(),
            std: Digest(hex('a')),
        },
        sources: BTreeMap::from([
            ("src/reader/pages.cpl".to_string(), Digest(hex('2'))),
            ("cpl.toml".to_string(), Digest(hex('1'))),
            ("work/pagination.work".to_string(), Digest(hex('3'))),
        ]),
        verification: VerificationSection {
            proof_timeout_ms: 10_000,
            admit: vec![],
        },
        foreign: toml::Table::new(),
        adapters: toml::Table::new(),
        targets: toml::Table::new(),
    }
}

#[test]
fn render_lock_produces_the_documented_layout() {
    let expected = format!(
        "# Generated by cpl. Do not edit.\n\
         version = 1\n\
         \n\
         [toolchain]\n\
         cpl = \"0.1.0\"\n\
         edition = \"0.1\"\n\
         std = \"{a}\"\n\
         \n\
         [sources]\n\
         \"cpl.toml\" = \"{one}\"\n\
         \"src/reader/pages.cpl\" = \"{two}\"\n\
         \"work/pagination.work\" = \"{three}\"\n\
         \n\
         [verification]\n\
         proof_timeout_ms = 10000\n\
         admit = []\n\
         \n\
         [foreign]\n\
         [adapters]\n\
         [targets]\n",
        a = hex('a'),
        one = hex('1'),
        two = hex('2'),
        three = hex('3'),
    );
    assert_eq!(render_lock(&sample()), expected);
}

#[test]
fn parse_lock_reads_what_render_lock_writes() {
    let mut lock = sample();
    lock.verification.admit = vec![
        "fn_k7w3qz2mb9ptx4ve".to_string(),
        "reader.pages.paginate".to_string(),
    ];
    let text = render_lock(&lock);
    assert_eq!(parse_lock(&text), Ok(lock));
}

#[test]
fn reserved_sections_are_carried_through_canonically() {
    let text = format!(
        "version = 1\n\
         [targets]\n\
         abi = \"x86_64\"\n\
         [foreign.python]\n\
         zlib = {{ version = \"1.0\", hash = \"h\" }}\n\
         numpy = \"2.0\"\n\
         [toolchain]\n\
         std = \"{a}\"\n\
         edition = \"0.1\"\n\
         cpl = \"0.1.0\"\n\
         [verification]\n\
         admit = [\"a.b\"]\n\
         proof_timeout_ms = 5\n\
         [sources]\n\
         \"z.cpl\" = \"{one}\"\n\
         \"a.cpl\" = \"{one}\"\n\
         [adapters]\n\
         list = [1, 2.5, true, \"s\"]\n",
        a = hex('a'),
        one = hex('1'),
    );
    let lock = parse_lock(&text).unwrap();
    assert_eq!(lock.targets["abi"].as_str(), Some("x86_64"));
    assert_eq!(lock.foreign["python"]["numpy"].as_str(), Some("2.0"));
    let rendered = render_lock(&lock);
    let expected = format!(
        "# Generated by cpl. Do not edit.\n\
         version = 1\n\
         \n\
         [toolchain]\n\
         cpl = \"0.1.0\"\n\
         edition = \"0.1\"\n\
         std = \"{a}\"\n\
         \n\
         [sources]\n\
         \"a.cpl\" = \"{one}\"\n\
         \"z.cpl\" = \"{one}\"\n\
         \n\
         [verification]\n\
         proof_timeout_ms = 5\n\
         admit = [\"a.b\"]\n\
         \n\
         [foreign]\n\
         python = {{ numpy = \"2.0\", zlib = {{ hash = \"h\", version = \"1.0\" }} }}\n\
         \n\
         [adapters]\n\
         list = [1, 2.5, true, \"s\"]\n\
         \n\
         [targets]\n\
         abi = \"x86_64\"\n",
        a = hex('a'),
        one = hex('1'),
    );
    assert_eq!(rendered, expected);
    // Canonical: rendering what was parsed from a rendering changes nothing.
    assert_eq!(parse_lock(&rendered).as_ref(), Ok(&lock));
    assert_eq!(render_lock(&parse_lock(&rendered).unwrap()), rendered);
}

#[test]
fn strings_are_escaped() {
    let mut lock = sample();
    lock.sources = BTreeMap::from([("src/odd \"name\"\\\t.cpl".to_string(), Digest(hex('1')))]);
    lock.toolchain.cpl = "0.1.0\u{1}é".to_string();
    let text = render_lock(&lock);
    assert!(
        text.contains("\"src/odd \\\"name\\\"\\\\\\t.cpl\" = "),
        "{text}"
    );
    assert!(text.contains("cpl = \"0.1.0\\u0001é\""), "{text}");
    assert_eq!(parse_lock(&text), Ok(lock));
}

