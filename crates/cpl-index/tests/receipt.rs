fn blake3_hex(bytes: &[u8]) -> String {
    blake3::hash(bytes).to_hex().to_string()
}

fn reader_inputs() -> (cpl_project::Project, ReceiptInputs) {
    let project = load_dir(&workspace_path("examples/reader"));
    let revision = Revision {
        commit: Some("3f2e9c1d00000000000000000000000000000000".into()),
        state: RevisionState::Clean,
        digest: source_digest(&project),
    };
    let inputs = receipt_inputs(&project, revision);
    (project, inputs)
}

/// The top-level keys of a JSON text in the order they are written.
fn written_keys(json: &str) -> Vec<String> {
    let value: Value = serde_json::from_str(json).expect("json");
    let mut keys: Vec<(usize, String)> = value
        .as_object()
        .expect("object")
        .keys()
        .map(|k| {
            let needle = format!("\n  \"{k}\":");
            (json.find(&needle).expect("a top-level key"), k.clone())
        })
        .collect();
    keys.sort();
    keys.into_iter().map(|(_, k)| k).collect()
}

fn version(project: &cpl_project::Project, path: &str, name: &str) -> SymbolVersion {
    let m = module(project, path);
    symbol_version(&module_path(m), decl(m, name))
}

fn core(project: &cpl_project::Project, check_configuration: Value) -> ReceiptCore {
    ReceiptCore {
        source_revision: "3f2e9c1d00000000000000000000000000000000".into(),
        dirty: None,
        toolchain: ReceiptToolchain::current(project.std_digest()),
        modules: vec![ModuleHash {
            module: "reader.pages".into(),
            content_hash: Digest("0".repeat(64)),
        }],
        check_configuration,
        assumptions: vec![],
        fixtures: None,
        environment: None,
    }
}

