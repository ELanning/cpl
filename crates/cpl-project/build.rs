//! Embeds the standard-library stubs (`spec/toolchain.md` 3.6, Embedding).
//!
//! Reads `std/*.cpl` at the workspace root (`../../std` from this crate) in
//! sorted file-name order and generates `$OUT_DIR/std_files.rs`, which
//! defines `pub static STD_FILES: &[(&str, &str)]`: one `(file name, text)`
//! pair per file, such as `("prelude.cpl", "...")`. Adding a file to `std/`
//! needs no Rust edit. Section 3.6 names `cpl-sema/build.rs`; the embedding
//! lives here because project loading moved into this crate.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

fn main() {
    let manifest_dir =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"));
    let std_dir = manifest_dir.join("..").join("..").join("std");
    // A directory is scanned recursively for changes, so adding or removing
    // a stub reruns this script; each file is listed as well.
    println!("cargo:rerun-if-changed={}", std_dir.display());

    let entries = fs::read_dir(&std_dir).unwrap_or_else(|e| {
        panic!(
            "cannot read the standard library directory {}: {e}",
            std_dir.display()
        )
    });
    let mut names = Vec::new();
    for entry in entries {
        let entry = entry.unwrap_or_else(|e| panic!("cannot read {}: {e}", std_dir.display()));
        let Ok(name) = entry.file_name().into_string() else {
            continue;
        };
        if name.len() > ".cpl".len() && name.ends_with(".cpl") && entry.path().is_file() {
            names.push(name);
        }
    }
    names.sort();

    let mut out = String::from(
        "// Generated by crates/cpl-project/build.rs from the workspace's std/ directory\n\
         // (spec/toolchain.md 3.6). Do not edit.\n\n\
         /// The embedded standard-library stubs (`spec/toolchain.md` 3.6): one\n\
         /// `(file name, text)` pair per `std/*.cpl` file of the workspace, in\n\
         /// sorted file-name order. A file `prelude.cpl` is registered in a\n\
         /// project's `SourceMap` as `std/prelude.cpl` (`FileOrigin::Std`).\n\
         pub static STD_FILES: &[(&str, &str)] = &[\n",
    );
    for name in &names {
        let path = std_dir.join(name);
        println!("cargo:rerun-if-changed={}", path.display());
        let bytes =
            fs::read(&path).unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
        if let Err(e) = std::str::from_utf8(&bytes) {
            panic!(
                "{} is not valid UTF-8 (byte {}): standard-library stubs are UTF-8 text",
                path.display(),
                e.valid_up_to()
            );
        }
        let path = path
            .to_str()
            .unwrap_or_else(|| panic!("{} is not a UTF-8 path", path.display()));
        writeln!(out, "    ({name:?}, include_str!({path:?})),").expect("writing to a String");
    }
    out.push_str("];\n");

    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    fs::write(out_dir.join("std_files.rs"), out).expect("cannot write std_files.rs");
}
