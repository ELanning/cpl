/// The methods every generated type has, which no field may be named.
const METHODS: &[&str] = &["Equal", "EqualAny", "WriteText", "ToJSON"];

pub fn emit(p: &Program, lowered: &Lowered, options: &Options) -> Package {
    let module = options.name.clone();
    let package = package_name(&options.name);
    let names = Names::new(p, lowered);
    let mut g = Printer {
        p,
        names,
        validators: BTreeMap::new(),
        pending: Vec::new(),
        decoders: BTreeMap::new(),
        pending_dec: Vec::new(),
        fn_ids: lowered
            .fns
            .iter()
            .enumerate()
            .map(|(i, f)| (f.def, i as u32))
            .collect(),
        counter: 0,
        used_labels: BTreeSet::new(),
    };
    let mut files = BTreeMap::new();
    files.insert(
        "go.mod".to_string(),
        format!("module {module}\n\ngo 1.21\n"),
    );
    files.insert(
        "cpl/cpl.go".to_string(),
        include_str!("runtime/cpl.go").to_string(),
    );
    let header = format!(
        "// Generated by `cpl build --target go`: do not edit.\n\npackage {package}\n\nimport \"{module}/cpl\"\n\nvar _ = cpl.Unit{{}}\n\n"
    );
    let mut modules: BTreeMap<Vec<String>, Vec<DefId>> = BTreeMap::new();
    for d in p.defs() {
        if lowered.defs.contains(&d.id) && std_type(p, d.id).is_none() {
            modules
                .entry(p.module(d.module).path.clone())
                .or_default()
                .push(d.id);
        }
    }
    let fns: BTreeMap<DefId, &LFn> = lowered.fns.iter().map(|f| (f.def, f)).collect();
    let preds: BTreeMap<DefId, &LPred> = lowered.preds.iter().map(|q| (q.def, q)).collect();
    let mut exports = Vec::new();
    for (path, defs) in &modules {
        let mut out = header.clone();
        for d in defs {
            g.def(*d, &fns, &preds, &mut exports, &mut out);
        }
        let mut stem = path.join(".");
        if stem.is_empty() || stem.starts_with(['_', '.']) {
            stem = format!("m{stem}");
        }
        files.insert(format!("{stem}.cpl.go"), out);
    }
    let mut support = header.clone();
    if options.driver {
        g.driver(lowered, &mut support);
        files.insert(
            "cmd/cpl-driver/main.go".to_string(),
            format!(
                "// Generated by `cpl build --target go`: do not edit.\n\n// The JSON driver of the differential tests (spec/hosts.md 4).\npackage main\n\nimport (\n\tpkg \"{module}\"\n\t\"{module}/cpl\"\n)\n\nfunc main() {{ cpl.Serve(pkg.DriverCall) }}\n"
            ),
        );
    }
    // Every validator and decoder requested while printing.
    let mut done = BTreeSet::new();
    loop {
        if let Some((key, ty)) = g.pending.pop() {
            if done.insert(format!("v {key}")) {
                g.validator(&key, &ty, &mut support);
            }
        } else if let Some((key, ty)) = g.pending_dec.pop() {
            if done.insert(format!("d {key}")) {
                g.decoder(&key, &ty, &mut support);
            }
        } else {
            break;
        }
    }
    files.insert("support.cpl.go".to_string(), support);
    Package { files, exports }
}

/// A Go package name from the project's name.
fn package_name(name: &str) -> String {
    let mut s: String = name
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .collect();
    if s.is_empty() || s.starts_with(|c: char| c.is_ascii_digit()) {
        s.insert(0, 'p');
    }
    if RESERVED.contains(&s.as_str()) || s == "main" {
        s.push('_');
    }
    s
}

/// The Go names of the program's definitions: a definition keeps its CPL name unless another
/// emitted definition has the same one, when its module path qualifies it.
struct Names {
    /// The name in the internal forms: `x_<short>`, `b_<short>`, `pred_<short>`.
    short: BTreeMap<DefId, String>,
    /// The exported names of types.
    ty: BTreeMap<DefId, String>,
    /// The exported names of `pub fn`s.
    host: BTreeMap<DefId, String>,
}

impl Names {
    fn new(p: &Program, lowered: &Lowered) -> Names {
        let defs: Vec<DefId> = p
            .defs()
            .filter(|d| lowered.defs.contains(&d.id) && std_type(p, d.id).is_none())
            .map(|d| d.id)
            .collect();
        let mut count: BTreeMap<String, usize> = BTreeMap::new();
        for d in &defs {
            *count.entry(p.def(*d).name.display()).or_default() += 1;
        }
        let mut short = BTreeMap::new();
        let mut ty = BTreeMap::new();
        let mut taken: BTreeSet<String> = BTreeSet::new();
        for d in &defs {
            let def = p.def(*d);
            let name = def.name.display();
            let path = &p.module(def.module).path;
            let unique = count[&name] == 1;
            let s = if unique {
                name.clone()
            } else {
                format!("{}_{name}", path.join("_"))
            };
            short.insert(*d, s);
            if matches!(
                def.kind,
                DefKind::Struct(_)
                    | DefKind::Enum(_)
                    | DefKind::Wrapper(_)
                    | DefKind::Capability(_)
            ) {
                let base = if unique {
                    upper_first(&name)
                } else {
                    format!(
                        "{}{}",
                        path.iter().map(|s| pascal(s)).collect::<String>(),
                        upper_first(&name)
                    )
                };
                let mut t = base.clone();
                while taken.contains(&t) {
                    t.push('_');
                }
                taken.insert(t.clone());
                if let DefKind::Enum(e) = &def.kind {
                    for v in &e.variants {
                        taken.insert(format!("{t}_{}", v.name));
                    }
                }
                ty.insert(*d, t);
            }
        }
        let mut host = BTreeMap::new();
        for f in &lowered.fns {
            if !p.def(f.def).is_pub {
                continue;
            }
            let mut h = pascal(&short[&f.def]);
            if h.is_empty() || !h.starts_with(|c: char| c.is_uppercase()) {
                h = format!("F{h}");
            }
            while taken.contains(&h) {
                h.push_str("Fn");
            }
            taken.insert(h.clone());
            host.insert(f.def, h);
        }
        Names { short, ty, host }
    }
}

fn upper_first(s: &str) -> String {
    let mut c = s.chars();
    match c.next() {
        Some(f) => f.to_uppercase().chain(c).collect(),
        None => String::new(),
    }
}

/// A local name from CPL, safe in Go.
fn ident(name: &str) -> String {
    if RESERVED.contains(&name) {
        format!("{name}_")
    } else {
        name.to_string()
    }
}

/// A Go string literal: ASCII printable characters as they are, everything else escaped.
fn go_str(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (' '..='~').contains(&c) => out.push(c),
            c if (c as u32) < 0x80 => {
                let _ = write!(out, "\\x{:02x}", c as u32);
            }
            c if (c as u32) <= 0xFFFF => {
                let _ = write!(out, "\\u{:04x}", c as u32);
            }
            c => {
                let _ = write!(out, "\\U{:08x}", c as u32);
            }
        }
    }
    out.push('"');
    out
}

fn generics_decl(generics: &[String]) -> String {
    if generics.is_empty() {
        return String::new();
    }
    format!(
        "[{}]",
        generics
            .iter()
            .map(|g| format!("G{g} any"))
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn generics_use(generics: &[String]) -> String {
    if generics.is_empty() {
        return String::new();
    }
    format!(
        "[{}]",
        generics
            .iter()
            .map(|g| format!("G{g}"))
            .collect::<Vec<_>>()
            .join(", ")
    )
}

struct Printer<'p> {
    p: &'p Program,
    names: Names,
    validators: BTreeMap<String, String>,
    pending: Vec<(String, Ty)>,
    decoders: BTreeMap<String, String>,
    pending_dec: Vec<(String, Ty)>,
    fn_ids: BTreeMap<DefId, u32>,
    counter: usize,
    used_labels: BTreeSet<String>,
}

impl<'p> Printer<'p> {
    fn fresh(&mut self, prefix: &str) -> String {
        self.counter += 1;
        format!("{prefix}{}", self.counter)
    }

    fn short(&self, d: DefId) -> &str {
        &self.names.short[&d]
    }

    fn type_name(&self, d: DefId) -> String {
        self.names.ty[&d].clone()
    }

    fn variant_name(&self, d: DefId, variant: u32) -> String {
        let e = self.p.def(d).kind.as_enum().expect("an enum");
        format!(
            "{}_{}",
            self.type_name(d),
            e.variants[variant as usize].name
        )
    }

    /// The Go type of variant `variant` of the enum type `ty`.
    fn variant_ty(&self, d: DefId, variant: u32, ty: &Ty, generics: &[String]) -> String {
        let args = match ty {
            Ty::Adt(_, a) if !a.is_empty() => {
                format!(
                    "[{}]",
                    a.iter()
                        .map(|t| self.ty(t, generics))
                        .collect::<Vec<_>>()
                        .join(", ")
                )
            }
            _ => String::new(),
        };
        format!("{}{args}", self.variant_name(d, variant))
    }

    fn field_name(&self, d: DefId, i: usize) -> String {
        let s = self.p.def(d).kind.as_struct().expect("a struct");
        let mut name = upper_first(&pascal(&s.fields[i].name));
        if name.is_empty() || !name.starts_with(|c: char| c.is_uppercase()) {
            name = format!("F{name}");
        }
        if METHODS.contains(&name.as_str()) {
            name.push('_');
        }
        // Two CPL fields with one Go name: the later gets its index.
        let earlier = (0..i).any(|j| {
            upper_first(&pascal(&s.fields[j].name)) == upper_first(&pascal(&s.fields[i].name))
        });
        if earlier {
            name = format!("{name}_{i}");
        }
        name
    }

    /// A field that contains its own struct is held by pointer (an enum is an interface, a
    /// reference already).
    fn boxed_field(&self, d: DefId, i: usize) -> bool {
        std_type(self.p, d).is_none()
            && self
                .p
                .def(d)
                .kind
                .as_struct()
                .is_some_and(|s| crate::reaches(self.p, &s.fields[i].ty, d, false))
    }

    fn boxed_wrapper(&self, d: DefId) -> bool {
        self.p
            .def(d)
            .kind
            .as_wrapper()
            .is_some_and(|w| crate::reaches(self.p, &w.inner, d, false))
    }

    fn is_unit(&self, t: &Ty) -> bool {
        matches!(t, Ty::Adt(d, _) if *d == self.p.std_defs().unit)
    }

    // ---- types -----------------------------------------------------------------------

    fn ty(&self, t: &Ty, generics: &[String]) -> String {
        let p = self.p;
        match t {
            Ty::Int => "cpl.Int".into(),
            Ty::Bool => "bool".into(),
            Ty::Text => "string".into(),
            Ty::Bytes => "cpl.Bytes".into(),
            Ty::List(e) => format!("cpl.List[{}]", self.ty(e, generics)),
            Ty::Adt(d, args) => {
                let a: Vec<String> = args.iter().map(|x| self.ty(x, generics)).collect();
                match std_type(p, *d) {
                    Some(StdType::Unit) => "cpl.Unit".into(),
                    Some(StdType::Option) => format!("cpl.Option[{}]", a[0]),
                    Some(StdType::Result) => format!("cpl.Result[{}, {}]", a[0], a[1]),
                    Some(StdType::ConstraintError) => "cpl.ConstraintError".into(),
                    Some(StdType::ForeignError) => "cpl.ForeignError".into(),
                    Some(StdType::ForeignErrorKind) => "cpl.ForeignErrorKind".into(),
                    Some(StdType::ForeignDetail) => "cpl.ForeignDetail".into(),
                    None if a.is_empty() => self.type_name(*d),
                    None => format!("{}[{}]", self.type_name(*d), a.join(", ")),
                }
            }
            Ty::Wrapper(d) | Ty::Capability(d) => self.type_name(*d),
            Ty::Refined(..) => self.ty(&erase(p, t), generics),
            Ty::Param(i) => generics
                .get(*i as usize)
                .map(|g| format!("G{g}"))
                .unwrap_or_else(|| "cpl.Unit".into()),
            Ty::Gen(_) | Ty::Error => "cpl.Unit".into(),
        }
    }

    /// Structural equality of `a` and `b` of type `t`.
    fn eq(&self, t: &Ty, a: &str, b: &str, generics: &[String]) -> String {
        match t {
            Ty::Int => format!("({a}).Eq({b})"),
            Ty::Bool | Ty::Text | Ty::Bytes => format!("({a} == {b})"),
            Ty::List(e) => format!("cpl.ListEq({a}, {b}, {})", self.eqfn(e, generics)),
            Ty::Adt(d, args) => match std_type(self.p, *d) {
                Some(StdType::Unit) => format!("cpl.UnitEq({a}, {b})"),
                Some(StdType::Option) => {
                    format!("cpl.OptionEq({a}, {b}, {})", self.eqfn(&args[0], generics))
                }
                Some(StdType::Result) => format!(
                    "cpl.ResultEq({a}, {b}, {}, {})",
                    self.eqfn(&args[0], generics),
                    self.eqfn(&args[1], generics)
                ),
                _ => format!("({a}).Equal({b})"),
            },
            Ty::Wrapper(_) => format!("({a}).Equal({b})"),
            Ty::Refined(..) => self.eq(&erase(self.p, t), a, b, generics),
            Ty::Param(_) => format!("cpl.Eq({a}, {b})"),
            _ => "true".into(),
        }
    }

    /// Equality of type `t` as a function value.
    fn eqfn(&self, t: &Ty, generics: &[String]) -> String {
        match t {
            Ty::Int => "cpl.Int.Eq".into(),
            Ty::Bool => "cpl.BoolEq".into(),
            Ty::Text => "cpl.TextEq".into(),
            Ty::Bytes => "cpl.BytesEq".into(),
            Ty::Refined(..) => self.eqfn(&erase(self.p, t), generics),
            Ty::Param(_) => format!("cpl.Eq[{}]", self.ty(t, generics)),
            Ty::Adt(d, _) if std_type(self.p, *d) == Some(StdType::Unit) => "cpl.UnitEq".into(),
            Ty::List(_) => self.eq_closure(t, generics),
            Ty::Adt(d, _)
                if matches!(
                    std_type(self.p, *d),
                    Some(StdType::Option | StdType::Result)
                ) =>
            {
                self.eq_closure(t, generics)
            }
            _ => format!("{}.Equal", self.ty(t, generics)),
        }
    }

    fn eq_closure(&self, t: &Ty, generics: &[String]) -> String {
        let ty = self.ty(t, generics);
        format!(
            "func(x, y {ty}) bool {{ return {} }}",
            self.eq(t, "x", "y", generics)
        )
    }

    // ---- declarations ----------------------------------------------------------------

    fn def(
        &mut self,
        d: DefId,
        fns: &BTreeMap<DefId, &LFn>,
        preds: &BTreeMap<DefId, &LPred>,
        exports: &mut Vec<String>,
        out: &mut String,
    ) {
        let p = self.p;
        let def = p.def(d);
        match &def.kind {
            DefKind::Struct(s) => {
                let name = self.type_name(d);
                let g = generics_decl(&s.generics);
                let gu = generics_use(&s.generics);
                let qualified = crate::lower::type_name(p, d);
                let bare = def.name.display();
                let _ = writeln!(
                    out,
                    "// {name} is the CPL struct `{}`.\ntype {name}{g} struct {{",
                    p.display_path(d)
                );
                let mut fields = Vec::new();
                for (i, f) in s.fields.iter().enumerate() {
                    let fname = self.field_name(d, i);
                    let mut t = self.ty(&f.ty, &s.generics);
                    let boxed = self.boxed_field(d, i);
                    if boxed {
                        t = format!("*{t}");
                    }
                    let _ = writeln!(out, "\t{fname} {t}");
                    fields.push((f.name.clone(), fname, f.ty.clone(), boxed));
                }
                let _ = writeln!(out, "}}\n");
                let recv = format!("{name}{gu}");
                let eqs: Vec<String> = fields
                    .iter()
                    .map(|(_, f, t, boxed)| {
                        let (a, b) = if *boxed {
                            (format!("*a.{f}"), format!("*b.{f}"))
                        } else {
                            (format!("a.{f}"), format!("b.{f}"))
                        };
                        self.eq(t, &a, &b, &s.generics)
                    })
                    .collect();
                let eq = if eqs.is_empty() {
                    "true".to_string()
                } else {
                    eqs.join(" && ")
                };
                let _ = writeln!(
                    out,
                    "func (a {recv}) Equal(b {recv}) bool {{ return {eq} }}"
                );
                let _ = writeln!(out, "func (a {recv}) EqualAny(o any) bool {{ b, ok := o.({recv}); return ok && a.Equal(b) }}");
                let _ = writeln!(out, "func (a {recv}) WriteText(sb *cpl.TextBuilder) {{");
                if fields.is_empty() {
                    let _ = writeln!(out, "\tsb.WriteString({})", go_str(&format!("{bare} {{}}")));
                } else {
                    for (i, (cpl_name, f, _, boxed)) in fields.iter().enumerate() {
                        let lead = if i == 0 {
                            format!("{bare} {{ {cpl_name}: ")
                        } else {
                            format!(", {cpl_name}: ")
                        };
                        let star = if *boxed { "*" } else { "" };
                        let _ = writeln!(
                            out,
                            "\tsb.WriteString({})\n\tcpl.WriteText(sb, {star}a.{f})",
                            go_str(&lead)
                        );
                    }
                    let _ = writeln!(out, "\tsb.WriteString(\" }}\")");
                }
                let _ = writeln!(out, "}}");
                let js: Vec<String> = fields
                    .iter()
                    .map(|(cpl_name, f, _, boxed)| {
                        format!(
                            "{}: cpl.ToJSON({}a.{f})",
                            go_str(cpl_name),
                            if *boxed { "*" } else { "" }
                        )
                    })
                    .collect();
                let _ = writeln!(
                    out,
                    "func (a {recv}) ToJSON() any {{ return map[string]any{{\"$type\": {}{}}} }}\n",
                    go_str(&qualified),
                    js.iter().map(|j| format!(", {j}")).collect::<String>()
                );
                if let Some(pred) = preds.get(&d) {
                    self.pred(pred, out);
                }
            }
            DefKind::Enum(e) => {
                let name = self.type_name(d);
                let g = generics_decl(&e.generics);
                let gu = generics_use(&e.generics);
                let qualified = crate::lower::type_name(p, d);
                let variants: Vec<String> = (0..e.variants.len())
                    .map(|i| self.variant_name(d, i as u32))
                    .collect();
                let _ = writeln!(
                    out,
                    "// {name} is the CPL enum `{}`: {}.\ntype {name}{g} interface {{\n\tis{name}()\n\tEqual({name}{gu}) bool\n\tcpl.Value\n}}\n",
                    p.display_path(d),
                    if variants.is_empty() { "no value".to_string() } else { variants.join(", ") }
                );
                for (vi, v) in e.variants.iter().enumerate() {
                    let vn = &variants[vi];
                    let fields: Vec<String> = v
                        .payload
                        .iter()
                        .enumerate()
                        .map(|(i, t)| format!("F{i} {}", self.ty(t, &e.generics)))
                        .collect();
                    if fields.is_empty() {
                        let _ = writeln!(out, "type {vn}{g} struct{{}}");
                    } else {
                        let _ = writeln!(out, "type {vn}{g} struct {{ {} }}", fields.join("; "));
                    }
                    let recv = format!("{vn}{gu}");
                    let _ = writeln!(out, "func ({recv}) is{name}() {{}}");
                    let eqs: Vec<String> = v
                        .payload
                        .iter()
                        .enumerate()
                        .map(|(i, t)| {
                            self.eq(t, &format!("a.F{i}"), &format!("b.F{i}"), &e.generics)
                        })
                        .collect();
                    let binder = if eqs.is_empty() { "_" } else { "b" };
                    let _ = writeln!(
                        out,
                        "func (a {recv}) Equal(o {name}{gu}) bool {{ {binder}, ok := o.({recv}); return ok{} }}",
                        eqs.iter().map(|e| format!(" && {e}")).collect::<String>()
                    );
                    let _ = writeln!(out, "func (a {recv}) EqualAny(o any) bool {{ b, ok := o.({name}{gu}); return ok && a.Equal(b) }}");
                    if v.payload.is_empty() {
                        let _ = writeln!(out, "func (a {recv}) WriteText(sb *cpl.TextBuilder) {{ sb.WriteString({}) }}", go_str(&v.name));
                        let _ = writeln!(
                            out,
                            "func (a {recv}) ToJSON() any {{ return cpl.Tagged({}, {}, nil) }}\n",
                            go_str(&qualified),
                            go_str(&v.name)
                        );
                    } else {
                        let _ = writeln!(out, "func (a {recv}) WriteText(sb *cpl.TextBuilder) {{\n\tsb.WriteString({})", go_str(&format!("{}(", v.name)));
                        for i in 0..v.payload.len() {
                            if i > 0 {
                                let _ = writeln!(out, "\tsb.WriteString(\", \")");
                            }
                            let _ = writeln!(out, "\tcpl.WriteText(sb, a.F{i})");
                        }
                        let _ = writeln!(out, "\tsb.WriteString(\")\")\n}}");
                        let js: Vec<String> = (0..v.payload.len())
                            .map(|i| format!("cpl.ToJSON(a.F{i})"))
                            .collect();
                        let _ = writeln!(
                            out,
                            "func (a {recv}) ToJSON() any {{ return cpl.Tagged({}, {}, []any{{{}}}) }}\n",
                            go_str(&qualified),
                            go_str(&v.name),
                            js.join(", ")
                        );
                    }
                }
            }
            DefKind::Wrapper(w) => {
                let name = self.type_name(d);
                let boxed = self.boxed_wrapper(d);
                let inner = self.ty(&w.inner, &[]);
                let qualified = crate::lower::type_name(p, d);
                let bare = def.name.display();
                let star = if boxed { "*" } else { "" };
                let _ = writeln!(
                    out,
                    "// {name} is the CPL wrapper `{}`.\ntype {name} struct{{ V {star}{inner} }}\n",
                    p.display_path(d)
                );
                let eq = self.eq(&w.inner, &format!("{star}a.V"), &format!("{star}b.V"), &[]);
                let _ = writeln!(
                    out,
                    "func (a {name}) Equal(b {name}) bool {{ return {eq} }}"
                );
                let _ = writeln!(out, "func (a {name}) EqualAny(o any) bool {{ b, ok := o.({name}); return ok && a.Equal(b) }}");
                let _ = writeln!(
                    out,
                    "func (a {name}) WriteText(sb *cpl.TextBuilder) {{\n\tsb.WriteString({})\n\tcpl.WriteText(sb, {star}a.V)\n\tsb.WriteString(\")\")\n}}",
                    go_str(&format!("{bare}("))
                );
                let _ = writeln!(out, "func (a {name}) ToJSON() any {{ return cpl.Tagged({}, \"\", []any{{cpl.ToJSON({star}a.V)}}) }}\n", go_str(&qualified));
            }
            DefKind::Refinement(_) => {
                if let Some(pred) = preds.get(&d) {
                    self.pred(pred, out);
                }
            }
            DefKind::Capability(c) => {
                let name = self.type_name(d);
                let _ = writeln!(out, "// {name} is the CPL capability `{}`: the host implements it.\ntype {name} interface {{", p.display_path(d));
                for op in &c.ops {
                    let params: Vec<String> = op
                        .params
                        .iter()
                        .map(|q| format!("{} {}", ident(&q.name), self.ty(&q.ty, &[])))
                        .collect();
                    let ret = if self.is_unit(&op.ret) {
                        String::new()
                    } else {
                        format!(" {}", self.ty(&op.ret, &[]))
                    };
                    let _ = writeln!(
                        out,
                        "\t{}({}){ret}",
                        upper_first(&pascal(&op.name)),
                        params.join(", ")
                    );
                }
                let _ = writeln!(out, "}}\n");
            }
            DefKind::Fn(_) => {
                if let Some(f) = fns.get(&d) {
                    self.function(f, out);
                    if def.is_pub {
                        exports.push(p.display_path(d));
                        self.host_function(f, out);
                    }
                }
            }
            _ => {}
        }
    }

    // ---- functions -------------------------------------------------------------------

    fn params(&self, f: &LFn) -> Vec<String> {
        f.params
            .iter()
            .chain(&f.using)
            .map(|v| format!("v{v} {}", self.ty(&f.vars[*v as usize].ty, &f.generics)))
            .collect()
    }

    fn function(&mut self, f: &LFn, out: &mut String) {
        let p = self.p;
        let short = self.short(f.def).to_string();
        let g = generics_decl(&f.generics);
        let gu = generics_use(&f.generics);
        let ret = self.ty(&f.ret, &f.generics);
        let mut params = self.params(f);
        params.push("cx *cpl.Cx".into());
        let args: Vec<String> = f
            .params
            .iter()
            .chain(&f.using)
            .map(|v| format!("v{v}, "))
            .collect();
        let id = self.fn_ids[&f.def];
        let mut w = String::new();
        let _ = writeln!(
            w,
            "func x_{short}{g}({}) {ret} {{\n\tcx.Enter()",
            params.join(", ")
        );
        if f.measure.is_some() {
            let _ = writeln!(w, "\tcx.MeasurePush({id})");
        }
        let mut fx = Fx {
            r: self,
            vars: &f.vars,
            generics: &f.generics,
        };
        fx.stmts(&f.requires, 1, &mut w);
        if let Some((stmts, value, clause)) = &f.measure {
            fx.stmts(stmts, 1, &mut w);
            let v = fx.expr(value);
            let _ = writeln!(
                w,
                "\tcx.MeasureSet({id}, {v}, {}, {})",
                go_str(clause),
                go_str(p.def(f.def).stable_id.as_str())
            );
        }
        let _ = writeln!(w, "\tr := b_{short}{gu}({}cx)", args.concat());
        if !f.ensures.is_empty() {
            if let Some(r) = f.result {
                let _ = writeln!(
                    w,
                    "\tvar v{r} {} = r\n\t_ = v{r}",
                    fx.r.ty(&f.vars[r as usize].ty, &f.generics)
                );
            }
            fx.stmts(&f.ensures, 1, &mut w);
        }
        if f.measure.is_some() {
            let _ = writeln!(w, "\tcx.MeasurePop()");
        }
        let _ = writeln!(w, "\tcx.Leave()\n\treturn r\n}}\n");
        let mut b = String::new();
        let mut params = fx.r.params(f);
        params.push("cx *cpl.Cx".into());
        let _ = writeln!(b, "func b_{short}{g}({}) {ret} {{", params.join(", "));
        fx.stmts(&f.body, 1, &mut b);
        // A body that diverges ends in a terminating statement in Go's sense (all breaks are
        // labeled, a match is a `switch` with a `default`), and nothing may follow it there.
        if !diverges(&f.body) {
            b.push_str("\tpanic(\"cpl: unreachable\")\n");
        }
        b.push_str("}\n\n");
        out.push_str(&w);
        out.push_str(&b);
    }

    /// The exported form of a `pub fn` (`spec/hosts.md` 3.3).
    fn host_function(&mut self, f: &LFn, out: &mut String) {
        let p = self.p;
        let def = p.def(f.def);
        let fd = def.kind.as_fn().expect("a function");
        let name = self.names.host[&f.def].clone();
        let short = self.short(f.def).to_string();
        let g = generics_decl(&f.generics);
        let gu = generics_use(&f.generics);
        let ret = self.ty(&f.ret, &f.generics);
        let params: Vec<String> = fd
            .params
            .iter()
            .chain(&fd.using)
            .map(|q| format!("{} {}", ident(&q.name), self.ty(&q.ty, &f.generics)))
            .collect();
        let doc = def
            .docs
            .as_ref()
            .and_then(|d| d.lines().next())
            .map(|l| format!(": {l}"))
            .unwrap_or_default();
        let _ = writeln!(
            out,
            "// {name} is the CPL function `{}`{doc}\nfunc {name}{g}({}) (r__ {ret}, err__ error) {{\n\tcx := cpl.NewCx()\n\tdefer cpl.Recover(cx, &err__)",
            p.display_path(f.def),
            params.join(", ")
        );
        let symbol = go_str(def.stable_id.as_str());
        for q in &fd.params {
            // a generic function's arguments get no validator; its plain texts are still checked
            if !f.generics.is_empty() && matches!(erase(p, &q.ty), Ty::Text) {
                let _ = writeln!(out, "\tif !cpl.ValidText({}) {{\n\t\treturn r__, cpl.RefinementFault(\"Text\", {symbol})\n\t}}", ident(&q.name));
            }
            if f.generics.is_empty() && needs_validation(p, &q.ty) {
                let v = self.validator_name(&q.ty);
                let _ = writeln!(
                    out,
                    "\tif !{v}({}, cx) {{\n\t\treturn r__, cpl.RefinementFault({}, {symbol})\n\t}}",
                    ident(&q.name),
                    go_str(&p.display_ty(&q.ty))
                );
            }
        }
        let args: Vec<String> = fd
            .params
            .iter()
            .chain(&fd.using)
            .map(|q| format!("{}, ", ident(&q.name)))
            .collect();
        let _ = writeln!(
            out,
            "\treturn x_{short}{gu}({}cx), nil\n}}\n",
            args.concat()
        );
    }

    fn pred(&mut self, q: &LPred, out: &mut String) {
        let short = self.short(q.def).to_string();
        let g = generics_decl(&q.generics);
        let self_ty = self.ty(&q.self_ty, &q.generics);
        let _ = writeln!(
            out,
            "func pred_{short}{g}(v{} {self_ty}, cx *cpl.Cx) bool {{",
            q.self_var
        );
        let mut fx = Fx {
            r: self,
            vars: &q.vars,
            generics: &q.generics,
        };
        let mut body = String::new();
        fx.stmts(&q.body, 1, &mut body);
        out.push_str(&body);
        if !diverges(&q.body) {
            let v = fx.expr(&q.value);
            let _ = writeln!(out, "\treturn {v}");
        }
        out.push_str("}\n\n");
    }

    // ---- validation and decoding at the boundary ------------------------------------

    fn validator_name(&mut self, ty: &Ty) -> String {
        let key = self.p.display_ty(ty);
        let n = self.validators.len();
        let name = self
            .validators
            .entry(key.clone())
            .or_insert_with(|| format!("valid_{n}"))
            .clone();
        self.pending.push((key, ty.clone()));
        name
    }

    fn validator(&mut self, key: &str, ty: &Ty, out: &mut String) {
        let p = self.p;
        let name = self.validators[key].clone();
        let t = self.ty(ty, &[]);
        let mut body = String::new();
        match ty {
            Ty::Refined(_, d) => {
                if let Some(b) = p
                    .def(*d)
                    .kind
                    .as_refinement()
                    .map(|r| r.base.clone())
                    .filter(|b| needs_validation(p, b))
                {
                    let v = self.validator_name(&b);
                    let _ = writeln!(body, "\tif !{v}(x, cx) {{\n\t\treturn false\n\t}}");
                }
                for r in crate::lower::check_order(p, *d) {
                    let _ = writeln!(
                        body,
                        "\tif !pred_{}(x, cx) {{\n\t\treturn false\n\t}}",
                        self.short(r)
                    );
                }
            }
            Ty::List(e) => {
                let v = self.validator_name(e);
                let _ = writeln!(body, "\tfor _, y := range x.Items() {{\n\t\tif !{v}(y, cx) {{\n\t\t\treturn false\n\t\t}}\n\t}}");
            }
            Ty::Wrapper(d) => {
                if let Some(w) = p.def(*d).kind.as_wrapper() {
                    let v = self.validator_name(&w.inner);
                    let star = if self.boxed_wrapper(*d) { "*" } else { "" };
                    let _ = writeln!(body, "\tif !{v}({star}x.V, cx) {{\n\t\treturn false\n\t}}");
                }
            }
            Ty::Adt(d, args) => {
                match (std_type(p, *d), &p.def(*d).kind) {
                    (Some(StdType::Option), _) => {
                        if needs_validation(p, &args[0]) {
                            let v = self.validator_name(&args[0]);
                            let _ = writeln!(body, "\tif y, ok := x.Get(); ok && !{v}(y, cx) {{\n\t\treturn false\n\t}}");
                        }
                    }
                    // the runtime's records hold texts a host may have made
                    (Some(StdType::ForeignError), _) => {
                        let _ = writeln!(body, "\tif !cpl.ValidText(x.Message) {{\n\t\treturn false\n\t}}\n\tfor _, d := range x.Details.Items() {{\n\t\tif !cpl.ValidText(d.Key) || !cpl.ValidText(d.Value) {{\n\t\t\treturn false\n\t\t}}\n\t}}");
                    }
                    (Some(StdType::ForeignDetail), _) => {
                        let _ = writeln!(body, "\tif !cpl.ValidText(x.Key) || !cpl.ValidText(x.Value) {{\n\t\treturn false\n\t}}");
                    }
                    (Some(StdType::ConstraintError), _) => {
                        let _ = writeln!(body, "\tif !cpl.ValidText(x.TypeName) || !cpl.ValidText(x.Message) {{\n\t\treturn false\n\t}}");
                    }
                    (Some(StdType::Result), _) => {
                        if needs_validation(p, &args[0]) {
                            let v = self.validator_name(&args[0]);
                            let _ = writeln!(body, "\tif y, _, ok := x.Get(); ok && !{v}(y, cx) {{\n\t\treturn false\n\t}}");
                        }
                        if needs_validation(p, &args[1]) {
                            let v = self.validator_name(&args[1]);
                            let _ = writeln!(body, "\tif _, e, ok := x.Get(); !ok && !{v}(e, cx) {{\n\t\treturn false\n\t}}");
                        }
                    }
                    (None, DefKind::Struct(s)) => {
                        for (i, f) in s.fields.iter().enumerate() {
                            let ft = instantiate(&f.ty, args);
                            if needs_validation(p, &ft) {
                                let v = self.validator_name(&ft);
                                let star = if self.boxed_field(*d, i) { "*" } else { "" };
                                let _ = writeln!(
                                    body,
                                    "\tif !{v}({star}x.{}, cx) {{\n\t\treturn false\n\t}}",
                                    self.field_name(*d, i)
                                );
                            }
                        }
                        if s.invariant.is_some() {
                            let targs = if args.is_empty() {
                                String::new()
                            } else {
                                format!(
                                    "[{}]",
                                    args.iter()
                                        .map(|a| self.ty(a, &[]))
                                        .collect::<Vec<_>>()
                                        .join(", ")
                                )
                            };
                            let _ = writeln!(
                                body,
                                "\tif !pred_{}{targs}(x, cx) {{\n\t\treturn false\n\t}}",
                                self.short(*d)
                            );
                        }
                    }
                    (None, DefKind::Enum(e)) => {
                        for (vi, v) in e.variants.iter().enumerate() {
                            let tys: Vec<Ty> =
                                v.payload.iter().map(|t| instantiate(t, args)).collect();
                            if !tys.iter().any(|t| needs_validation(p, t)) {
                                continue;
                            }
                            let vt = self.variant_ty(*d, vi as u32, ty, &[]);
                            let _ = writeln!(body, "\tif y, ok := x.({vt}); ok {{");
                            for (i, t) in tys.iter().enumerate() {
                                if needs_validation(p, t) {
                                    let vn = self.validator_name(t);
                                    let _ = writeln!(
                                        body,
                                        "\t\tif !{vn}(y.F{i}, cx) {{\n\t\t\treturn false\n\t\t}}"
                                    );
                                }
                            }
                            let _ = writeln!(body, "\t}}");
                        }
                    }
                    _ => {}
                }
            }
            Ty::Text => {
                let _ = writeln!(body, "\tif !cpl.ValidText(x) {{\n\t\treturn false\n\t}}");
            }
            _ => {}
        }
        let _ = writeln!(
            out,
            "func {name}(x {t}, cx *cpl.Cx) bool {{\n{body}\treturn true\n}}\n"
        );
    }

    /// The decoder of value JSON at a concrete type: a function value.
    fn decoder_of(&mut self, ty: &Ty) -> String {
        let p = self.p;
        match ty {
            Ty::Int => "cpl.DecInt".into(),
            Ty::Bool => "cpl.DecBool".into(),
            Ty::Text => "cpl.DecText".into(),
            Ty::Bytes => "cpl.DecBytes".into(),
            Ty::Refined(..) => self.decoder_of(&erase(p, ty)),
            Ty::Adt(d, _) if std_type(p, *d) == Some(StdType::Unit) => "cpl.DecUnit".into(),
            Ty::Adt(d, _) if std_type(p, *d) == Some(StdType::ConstraintError) => {
                "cpl.DecConstraintError".into()
            }
            Ty::Adt(d, _) if std_type(p, *d) == Some(StdType::ForeignError) => {
                "cpl.DecForeignError".into()
            }
            Ty::Adt(d, _) if std_type(p, *d) == Some(StdType::ForeignErrorKind) => {
                "cpl.DecForeignErrorKind".into()
            }
            Ty::Adt(d, _) if std_type(p, *d) == Some(StdType::ForeignDetail) => {
                "cpl.DecForeignDetail".into()
            }
            _ => {
                let key = p.display_ty(ty);
                let n = self.decoders.len();
                let name = self
                    .decoders
                    .entry(key.clone())
                    .or_insert_with(|| format!("dec_{n}"))
                    .clone();
                self.pending_dec.push((key, ty.clone()));
                name
            }
        }
    }

    fn decoder(&mut self, key: &str, ty: &Ty, out: &mut String) {
        let p = self.p;
        let name = self.decoders[key].clone();
        let t = self.ty(ty, &[]);
        let _ = writeln!(out, "func {name}(j any) ({t}, error) {{");
        match ty {
            Ty::List(e) => {
                let de = self.decoder_of(e);
                let _ = writeln!(out, "\treturn cpl.DecList(j, {de})");
            }
            Ty::Wrapper(d) => {
                let inner = p
                    .def(*d)
                    .kind
                    .as_wrapper()
                    .map(|w| w.inner.clone())
                    .unwrap_or(Ty::Error);
                let de = self.decoder_of(&inner);
                let wrap = if self.boxed_wrapper(*d) {
                    "cpl.Box(x)"
                } else {
                    "x"
                };
                let _ = writeln!(
                    out,
                    "\t_, payload, err := cpl.Untag(j, {})\n\tif err != nil || len(payload) != 1 {{\n\t\treturn {t}{{}}, cpl.NewFault(\"decode\", \"\", \"\", \"\", \"expected a wrapper\")\n\t}}\n\tx, err := {de}(payload[0])\n\treturn {t}{{V: {wrap}}}, err",
                    go_str(&crate::lower::type_name(p, *d))
                );
            }
            Ty::Adt(d, args) => match (std_type(p, *d), &p.def(*d).kind) {
                (Some(StdType::Option), _) => {
                    let de = self.decoder_of(&args[0]);
                    let _ = writeln!(out, "\treturn cpl.DecOption(j, {de})");
                }
                (Some(StdType::Result), _) => {
                    let (a, b) = (self.decoder_of(&args[0]), self.decoder_of(&args[1]));
                    let _ = writeln!(out, "\treturn cpl.DecResult(j, {a}, {b})");
                }
                (None, DefKind::Struct(s)) => {
                    let _ = writeln!(out, "\tvar v {t}\n\tif err := cpl.ExpectType(j, {}); err != nil {{\n\t\treturn v, err\n\t}}", go_str(&crate::lower::type_name(p, *d)));
                    for (i, f) in s.fields.iter().enumerate() {
                        let ft = instantiate(&f.ty, args);
                        let de = self.decoder_of(&ft);
                        let fname = self.field_name(*d, i);
                        let _ = writeln!(
                            out,
                            "\tif fj, err := cpl.Field(j, {}); err != nil {{\n\t\treturn v, err\n\t}} else if fv, err := {de}(fj); err != nil {{\n\t\treturn v, err\n\t}} else {{\n\t\tv.{fname} = {}\n\t}}",
                            go_str(&f.name),
                            if self.boxed_field(*d, i) { "cpl.Box(fv)" } else { "fv" }
                        );
                    }
                    let _ = writeln!(out, "\treturn v, nil");
                }
                (None, DefKind::Enum(e)) => {
                    let _ = writeln!(out, "\tvariant, payload, err := cpl.Untag(j, {})\n\tif err != nil {{\n\t\treturn nil, err\n\t}}\n\t_, _ = variant, payload", go_str(&crate::lower::type_name(p, *d)));
                    for (vi, v) in e.variants.iter().enumerate() {
                        let tys: Vec<Ty> = v.payload.iter().map(|x| instantiate(x, args)).collect();
                        let vt = self.variant_ty(*d, vi as u32, ty, &[]);
                        let _ = writeln!(
                            out,
                            "\tif variant == {} && len(payload) == {} {{\n\t\tvar x {vt}",
                            go_str(&v.name),
                            tys.len()
                        );
                        for (i, pt) in tys.iter().enumerate() {
                            let de = self.decoder_of(pt);
                            let _ = writeln!(out, "\t\tif x.F{i}, err = {de}(payload[{i}]); err != nil {{\n\t\t\treturn nil, err\n\t\t}}");
                        }
                        let _ = writeln!(out, "\t\treturn x, nil\n\t}}");
                    }
                    let _ = writeln!(out, "\treturn nil, cpl.NewFault(\"decode\", \"\", \"\", \"\", \"expected a {}\")", p.def(*d).name.display());
                }
                _ => {
                    let _ = writeln!(out, "\tvar v {t}\n\treturn v, cpl.NewFault(\"decode\", \"\", \"\", \"\", \"not decodable\")");
                }
            },
            _ => {
                let _ = writeln!(out, "\tvar v {t}\n\treturn v, cpl.NewFault(\"decode\", \"\", \"\", \"\", \"not decodable\")");
            }
        }
        let _ = writeln!(out, "}}\n");
    }

    // ---- the JSON driver ---------------------------------------------------------------

    fn driver(&mut self, lowered: &Lowered, out: &mut String) {
        let p = self.p;
        let _ = writeln!(
            out,
            "// DriverCall answers one request of the JSON driver (spec/hosts.md 4).\nfunc DriverCall(function string, args []any) (answer any) {{\n\tcx := cpl.NewCx()\n\tdefer cpl.Guard(cx, &answer)\n\tswitch function {{"
        );
        for d in crate::driver_functions(p, lowered) {
            let fd = p.def(d).kind.as_fn().expect("a function");
            let _ = writeln!(out, "\tcase {}:\n\t\tif len(args) != {} {{\n\t\t\treturn cpl.Outside(\"arity\")\n\t\t}}", go_str(&p.display_path(d)), fd.params.len());
            let mut names = Vec::new();
            for (i, q) in fd.params.iter().enumerate() {
                let de = self.decoder_of(&q.ty);
                let _ = writeln!(out, "\t\ta{i}, err := {de}(args[{i}])\n\t\tif err != nil {{\n\t\t\treturn cpl.Outside(err.Error())\n\t\t}}");
                if needs_validation(p, &q.ty) {
                    let v = self.validator_name(&q.ty);
                    let _ = writeln!(out, "\t\tif !{v}(a{i}, cx) {{\n\t\t\treturn cpl.Outside(\"refinement\")\n\t\t}}");
                }
                names.push(format!("a{i}, "));
            }
            let _ = writeln!(
                out,
                "\t\treturn cpl.Answer(x_{}({}cx))",
                self.short(d),
                names.concat()
            );
        }
        let _ = writeln!(
            out,
            "\t}}\n\treturn cpl.Outside(\"unknown function\")\n}}\n"
        );
    }
}

/// The printing context of one function body.
struct Fx<'a, 'p> {
    r: &'a mut Printer<'p>,
    vars: &'a [VarDef],
    generics: &'a [String],
}

impl Fx<'_, '_> {
    fn ty(&self, t: &Ty) -> String {
        self.r.ty(t, self.generics)
    }

    fn var_ty(&self, v: Var) -> String {
        self.ty(&self.vars[v as usize].ty)
    }

    fn stmts(&mut self, stmts: &[LStmt], depth: usize, out: &mut String) {
        for s in stmts {
            self.stmt(s, depth, out);
        }
    }

    /// A capability operation returning Unit, which the Go interface declares without a
    /// result: `(handle, call)`.
    fn unit_cap_call(&mut self, e: &LExpr) -> Option<String> {
        if let LExpr::CapCall {
            handle,
            capability,
            op,
            args,
            ty,
        } = e
        {
            if self.r.is_unit(ty) {
                let opdef = &self
                    .r
                    .p
                    .def(*capability)
                    .kind
                    .as_capability()
                    .expect("a capability")
                    .ops[*op as usize];
                let h = self.expr(handle);
                let a: Vec<String> = args.iter().map(|x| self.expr(x)).collect();
                return Some(format!(
                    "({h}).{}({})",
                    upper_first(&pascal(&opdef.name)),
                    a.join(", ")
                ));
            }
        }
        None
    }

    fn stmt(&mut self, s: &LStmt, depth: usize, out: &mut String) {
        let pad = "\t".repeat(depth);
        match s {
            LStmt::Let { var, value } => {
                if let Some(call) = self.unit_cap_call(value) {
                    let _ = writeln!(
                        out,
                        "{pad}{call}\n{pad}var v{var} cpl.Unit\n{pad}_ = v{var}"
                    );
                    return;
                }
                let e = self.expr(value);
                let _ = writeln!(
                    out,
                    "{pad}var v{var} {} = {e}\n{pad}_ = v{var}",
                    self.var_ty(*var)
                );
            }
            LStmt::Decl { var } => {
                let _ = writeln!(
                    out,
                    "{pad}var v{var} {}\n{pad}_ = v{var}",
                    self.var_ty(*var)
                );
            }
            LStmt::Assign { var, value } => {
                let e = self.expr(value);
                let _ = writeln!(out, "{pad}v{var} = {e}");
            }
            LStmt::Expr(e) => {
                if let Some(call) = self.unit_cap_call(e) {
                    let _ = writeln!(out, "{pad}{call}");
                    return;
                }
                let e = self.expr(e);
                let _ = writeln!(out, "{pad}_ = {e}");
            }
            LStmt::If { cond, then, els } => {
                let c = self.expr(cond);
                let _ = writeln!(out, "{pad}if {c} {{");
                self.stmts(then, depth + 1, out);
                if els.is_empty() {
                    let _ = writeln!(out, "{pad}}}");
                } else {
                    let _ = writeln!(out, "{pad}}} else {{");
                    self.stmts(els, depth + 1, out);
                    let _ = writeln!(out, "{pad}}}");
                }
            }
            LStmt::Match { scrutinee, arms } => {
                let label = self.r.fresh("m");
                let mut body = String::new();
                // an arm whose pattern tests nothing always matches: no arm after it runs
                let mut caught = false;
                for arm in arms {
                    let mut opens = 0;
                    self.pattern(
                        &arm.pattern,
                        &format!("v{scrutinee}"),
                        depth + 1,
                        &mut opens,
                        &mut body,
                    );
                    let inner = depth + 1 + opens;
                    self.stmts(&arm.body, inner, &mut body);
                    if !diverges(&arm.body) {
                        let _ = writeln!(body, "{}break {label}", "\t".repeat(inner));
                        self.r.used_labels.insert(label.clone());
                    }
                    for k in (0..opens).rev() {
                        let _ = writeln!(body, "{}}}", "\t".repeat(depth + 1 + k));
                    }
                    if opens == 0 {
                        caught = true;
                        break;
                    }
                }
                if !caught {
                    let _ = writeln!(body, "{pad}\tpanic(\"cpl: no arm matched\")");
                }
                let head = if self.r.used_labels.contains(&label) {
                    format!("{label}:\n{pad}")
                } else {
                    String::new()
                };
                let _ = writeln!(out, "{pad}{head}switch {{\n{pad}default:\n{body}{pad}}}");
            }
            LStmt::Loop { label, body } => {
                // Labels are numbered per function: whether this one is used is known after
                // its body is printed.
                let l = format!("l{label}");
                self.r.used_labels.remove(&l);
                let mut inner = String::new();
                self.stmts(body, depth + 1, &mut inner);
                let head = if self.r.used_labels.contains(&l) {
                    format!("{l}:\n{pad}")
                } else {
                    String::new()
                };
                let _ = writeln!(out, "{pad}{head}for {{\n{inner}{pad}}}");
            }
            LStmt::ForEach {
                label,
                var,
                list,
                body,
            } => {
                let l = self.expr(list);
                let it = self.r.fresh("it");
                let lab = format!("l{label}");
                self.r.used_labels.remove(&lab);
                let mut inner = String::new();
                self.stmts(body, depth + 1, &mut inner);
                let head = if self.r.used_labels.contains(&lab) {
                    format!("{lab}:\n{pad}")
                } else {
                    String::new()
                };
                let _ = writeln!(
                    out,
                    "{pad}{head}for _, {it} := range ({l}).Items() {{\n{pad}\tvar v{var} {} = {it}\n{pad}\t_ = v{var}\n{inner}{pad}}}",
                    self.var_ty(*var)
                );
            }
            LStmt::Break { label } => {
                let l = format!("l{label}");
                let _ = writeln!(out, "{pad}break {l}");
                self.r.used_labels.insert(l);
            }
            LStmt::Return(e) => {
                let e = self.expr(e);
                let _ = writeln!(out, "{pad}return {e}");
            }
            LStmt::Fault(f) => {
                let _ = writeln!(
                    out,
                    "{pad}panic(cpl.NewFault({}, {}, {}, {}, {}))",
                    go_str(f.code),
                    go_str(f.clause_kind.unwrap_or("")),
                    go_str(&f.clause),
                    go_str(&f.symbol),
                    go_str(&f.message)
                );
            }
            LStmt::Push { list, value } => {
                let e = self.expr(value);
                let _ = writeln!(out, "{pad}v{list} = v{list}.Push({e})");
            }
            LStmt::ClauseEnter { owner } => {
                let _ = writeln!(out, "{pad}cx.ClauseEnter({})", go_str(owner));
            }
            LStmt::ClauseLeave => {
                let _ = writeln!(out, "{pad}cx.ClauseLeave()");
            }
        }
    }

    /// Open the tests of `pat` against `subject` (a Go expression of the matched value),
    /// binding its variables; each block opened counts in `opens`.
    fn pattern(
        &mut self,
        pat: &LPat,
        subject: &str,
        depth: usize,
        opens: &mut usize,
        out: &mut String,
    ) {
        let p = self.r.p;
        let pad = "\t".repeat(depth + *opens);
        match pat {
            LPat::Wild => {}
            LPat::Bind(v) => {
                let _ = writeln!(
                    out,
                    "{pad}var v{v} {} = {subject}\n{pad}_ = v{v}",
                    self.var_ty(*v)
                );
            }
            LPat::Int(n) => {
                let _ = writeln!(out, "{pad}if ({subject}).Eq({}) {{", int_lit(n));
                *opens += 1;
            }
            LPat::Text(s) => {
                let _ = writeln!(out, "{pad}if {subject} == {} {{", go_str(s));
                *opens += 1;
            }
            LPat::Bool(b) => {
                let _ = writeln!(out, "{pad}if {}{subject} {{", if *b { "" } else { "!" });
                *opens += 1;
            }
            LPat::Unwrap { def, arg } => {
                let inner = if self.r.boxed_wrapper(*def) {
                    format!("(*({subject}).V)")
                } else {
                    format!("({subject}).V")
                };
                self.pattern(arg, &inner, depth, opens, out);
            }
            LPat::Ctor {
                def,
                variant,
                args,
                ty,
            } => match std_type(p, *def) {
                Some(StdType::Option) => {
                    if *variant == 0 {
                        let _ = writeln!(out, "{pad}if ({subject}).IsSome() {{");
                        *opens += 1;
                        self.pattern(
                            &args[0],
                            &format!("({subject}).Unwrap()"),
                            depth,
                            opens,
                            out,
                        );
                    } else {
                        let _ = writeln!(out, "{pad}if ({subject}).IsNone() {{");
                        *opens += 1;
                    }
                }
                Some(StdType::Result) => {
                    let (test, get) = if *variant == 0 {
                        ("IsOk", "Unwrap")
                    } else {
                        ("IsErr", "UnwrapErr")
                    };
                    let _ = writeln!(out, "{pad}if ({subject}).{test}() {{");
                    *opens += 1;
                    self.pattern(&args[0], &format!("({subject}).{get}()"), depth, opens, out);
                }
                Some(StdType::ForeignErrorKind) => {
                    let e = p.def(*def).kind.as_enum().expect("an enum");
                    let _ = writeln!(
                        out,
                        "{pad}if {subject} == cpl.ForeignErrorKind_{} {{",
                        e.variants[*variant as usize].name
                    );
                    *opens += 1;
                }
                _ => {
                    let vt = self.r.variant_ty(*def, *variant, ty, self.generics);
                    let o = self.r.fresh("o");
                    let _ = writeln!(
                        out,
                        "{pad}if {o}, ok := ({subject}).({vt}); ok {{\n{pad}\t_ = {o}"
                    );
                    *opens += 1;
                    for (i, a) in args.iter().enumerate() {
                        self.pattern(a, &format!("{o}.F{i}"), depth, opens, out);
                    }
                }
            },
        }
    }

    fn expr(&mut self, e: &LExpr) -> String {
        let p = self.r.p;
        match e {
            LExpr::Var(v) => format!("v{v}"),
            LExpr::Int(n) => int_lit(n),
            LExpr::Text(s) => go_str(s),
            LExpr::Bool(b) => b.to_string(),
            LExpr::Unit => "cpl.Unit{}".into(),
            LExpr::Call {
                def,
                generics,
                args,
                using,
            } => {
                let mut a: Vec<String> = args.iter().chain(using).map(|x| self.expr(x)).collect();
                a.push("cx".into());
                let targs = if generics.is_empty() {
                    String::new()
                } else {
                    format!(
                        "[{}]",
                        generics
                            .iter()
                            .map(|g| self.ty(g))
                            .collect::<Vec<_>>()
                            .join(", ")
                    )
                };
                format!("x_{}{targs}({})", self.r.short(*def), a.join(", "))
            }
            LExpr::Builtin { id, args, .. } => {
                let a: Vec<String> = args.iter().map(|x| self.expr(x)).collect();
                format!("cpl.{}({})", pascal(id), a.join(", "))
            }
            LExpr::Op { op, args, ty } => {
                let a: Vec<String> = args.iter().map(|x| self.expr(x)).collect();
                let int = matches!(erase(p, ty), Ty::Int);
                match op {
                    Op::Add => format!("({}).Add({})", a[0], a[1]),
                    Op::Sub => format!("({}).Sub({})", a[0], a[1]),
                    Op::Mul => format!("({}).Mul({})", a[0], a[1]),
                    Op::Neg => format!("({}).Neg()", a[0]),
                    Op::Lt if int => format!("({}).Lt({})", a[0], a[1]),
                    Op::Le if int => format!("({}).Le({})", a[0], a[1]),
                    Op::Gt if int => format!("({}).Gt({})", a[0], a[1]),
                    Op::Ge if int => format!("({}).Ge({})", a[0], a[1]),
                    Op::Lt => format!("({} < {})", a[0], a[1]),
                    Op::Le => format!("({} <= {})", a[0], a[1]),
                    Op::Gt => format!("({} > {})", a[0], a[1]),
                    Op::Ge => format!("({} >= {})", a[0], a[1]),
                    Op::Eq => self.r.eq(ty, &a[0], &a[1], self.generics),
                    Op::Ne => format!("!{}", self.r.eq(ty, &a[0], &a[1], self.generics)),
                    Op::Not => format!("!({})", a[0]),
                    Op::And => format!("({} && {})", a[0], a[1]),
                    Op::Or => format!("({} || {})", a[0], a[1]),
                    Op::Concat => match erase(p, ty) {
                        Ty::Text => format!("({} + {})", a[0], a[1]),
                        Ty::Bytes => format!("cpl.BytesConcat({}, {})", a[0], a[1]),
                        _ => format!("cpl.ListConcat({}, {})", a[0], a[1]),
                    },
                }
            }
            LExpr::Div { a, b, rem, symbol } => {
                let (a, b) = (self.expr(a), self.expr(b));
                format!(
                    "({a}).{}({b}, {})",
                    if *rem { "Rem" } else { "Div" },
                    go_str(symbol)
                )
            }
            LExpr::Ctor {
                def,
                variant,
                args,
                ty,
            } => {
                let a: Vec<String> = args.iter().map(|x| self.expr(x)).collect();
                let targs = match ty {
                    Ty::Adt(_, t) => t.clone(),
                    _ => Vec::new(),
                };
                match std_type(p, *def) {
                    Some(StdType::Option) => {
                        let t = self.ty(&targs[0]);
                        if *variant == 0 {
                            format!("cpl.Some[{t}]({})", a[0])
                        } else {
                            format!("cpl.None[{t}]()")
                        }
                    }
                    Some(StdType::Result) => {
                        let (t, e) = (self.ty(&targs[0]), self.ty(&targs[1]));
                        let v = if *variant == 0 { "Ok" } else { "Err" };
                        format!("cpl.{v}[{t}, {e}]({})", a[0])
                    }
                    Some(StdType::Unit) => "cpl.Unit{}".into(),
                    Some(StdType::ForeignErrorKind) => {
                        let e = p.def(*def).kind.as_enum().expect("an enum");
                        format!(
                            "cpl.ForeignErrorKind_{}",
                            e.variants[*variant as usize].name
                        )
                    }
                    _ => {
                        let enum_ty = self.ty(ty);
                        let vt = self.r.variant_ty(*def, *variant, ty, self.generics);
                        let fs: Vec<String> = a
                            .iter()
                            .enumerate()
                            .map(|(i, x)| format!("F{i}: {x}"))
                            .collect();
                        format!("{enum_ty}({vt}{{{}}})", fs.join(", "))
                    }
                }
            }
            LExpr::Struct { def, fields, ty } => {
                let s = p.def(*def).kind.as_struct().expect("a struct");
                let a: Vec<String> = fields.iter().map(|x| self.expr(x)).collect();
                let t = self.ty(ty);
                let fs: Vec<String> = s
                    .fields
                    .iter()
                    .enumerate()
                    .zip(a)
                    .map(|((i, f), v)| {
                        let name = if std_type(p, *def).is_some() {
                            upper_first(&pascal(&f.name))
                        } else {
                            self.r.field_name(*def, i)
                        };
                        if self.r.boxed_field(*def, i) {
                            format!("{name}: cpl.Box({v})")
                        } else {
                            format!("{name}: {v}")
                        }
                    })
                    .collect();
                format!("{t}{{{}}}", fs.join(", "))
            }
            LExpr::Wrap { def, arg } => {
                let a = self.expr(arg);
                let w = self.r.type_name(*def);
                if self.r.boxed_wrapper(*def) {
                    format!("{w}{{V: cpl.Box({a})}}")
                } else {
                    format!("{w}{{V: {a}}}")
                }
            }
            LExpr::Field {
                base, def, index, ..
            } => {
                let b = self.expr(base);
                let f = if std_type(p, *def).is_some() {
                    upper_first(&pascal(
                        &p.def(*def).kind.as_struct().expect("a struct").fields[*index as usize]
                            .name,
                    ))
                } else {
                    self.r.field_name(*def, *index as usize)
                };
                if self.r.boxed_field(*def, *index as usize) {
                    format!("(*({b}).{f})")
                } else {
                    format!("({b}).{f}")
                }
            }
            LExpr::Payload {
                base,
                def,
                variant,
                index,
                ty,
            } => {
                let b = self.expr(base);
                match std_type(p, *def) {
                    Some(StdType::Option) => format!("({b}).Unwrap()"),
                    Some(StdType::Result) if *variant == 0 => format!("({b}).Unwrap()"),
                    Some(StdType::Result) => format!("({b}).UnwrapErr()"),
                    _ => {
                        let vt = self.r.variant_ty(*def, *variant, ty, self.generics);
                        format!("({b}).({vt}).F{index}")
                    }
                }
            }
            LExpr::IsVariant {
                base,
                def,
                variant,
                ty,
            } => {
                let b = self.expr(base);
                match std_type(p, *def) {
                    Some(StdType::Option) => format!(
                        "({b}).{}()",
                        if *variant == 0 { "IsSome" } else { "IsNone" }
                    ),
                    Some(StdType::Result) => {
                        format!("({b}).{}()", if *variant == 0 { "IsOk" } else { "IsErr" })
                    }
                    Some(StdType::ForeignErrorKind) => {
                        let e = p.def(*def).kind.as_enum().expect("an enum");
                        format!(
                            "({b} == cpl.ForeignErrorKind_{})",
                            e.variants[*variant as usize].name
                        )
                    }
                    _ => {
                        let vt = self.r.variant_ty(*def, *variant, ty, self.generics);
                        format!("cpl.Is[{vt}]({b})")
                    }
                }
            }
            LExpr::Unwrap { base, def } => {
                let b = self.expr(base);
                if self.r.boxed_wrapper(*def) {
                    format!("(*({b}).V)")
                } else {
                    format!("({b}).V")
                }
            }
            LExpr::List { elem, items } => {
                let t = self.ty(elem);
                if items.is_empty() {
                    format!("cpl.List[{t}]{{}}")
                } else {
                    let a: Vec<String> = items.iter().map(|x| self.expr(x)).collect();
                    format!("cpl.ListLit[{t}]({})", a.join(", "))
                }
            }
            LExpr::CapCall { .. } => {
                if let Some(call) = self.unit_cap_call(e) {
                    return format!("func() cpl.Unit {{ {call}; return cpl.Unit{{}} }}()");
                }
                let LExpr::CapCall {
                    handle,
                    capability,
                    op,
                    args,
                    ..
                } = e
                else {
                    unreachable!()
                };
                let opdef = &p
                    .def(*capability)
                    .kind
                    .as_capability()
                    .expect("a capability")
                    .ops[*op as usize];
                let h = self.expr(handle);
                let a: Vec<String> = args.iter().map(|x| self.expr(x)).collect();
                format!(
                    "({h}).{}({})",
                    upper_first(&pascal(&opdef.name)),
                    a.join(", ")
                )
            }
            LExpr::Pred { def, generics, arg } => {
                let a = self.expr(arg);
                let targs = if generics.is_empty() {
                    String::new()
                } else {
                    format!(
                        "[{}]",
                        generics
                            .iter()
                            .map(|g| self.ty(g))
                            .collect::<Vec<_>>()
                            .join(", ")
                    )
                };
                format!("pred_{}{targs}({a}, cx)", self.r.short(*def))
            }
            LExpr::Valid { ty, arg } => {
                let a = self.expr(arg);
                let v = self.r.validator_name(ty);
                format!("{v}({a}, cx)")
            }
            LExpr::CheckFailure {
                value,
                type_name,
                predicate,
                ty,
                ..
            } => {
                let v = self.expr(value);
                let ok = match ty {
                    Ty::Adt(_, a) if !a.is_empty() => self.ty(&a[0]),
                    _ => "cpl.Unit".into(),
                };
                format!(
                    "cpl.CheckFailure[{ok}]({v}, {}, {})",
                    go_str(type_name),
                    go_str(predicate)
                )
            }
        }
    }
}

fn int_lit(n: &num_bigint::BigInt) -> String {
    match n.to_i64() {
        Some(v) => format!("cpl.I({v})"),
        None => format!("cpl.IntLit({:?})", n.to_string()),
    }
}
