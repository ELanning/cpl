//! Embeds the runtime files (`spec/toolchain.md` 1.12; `spec/cabi.md` 2.2, Embedding).
//!
//! Reads every `*.c` and `*.h` file under `c/` (recursively: `c/include/cpl.h` is one), the *runtime files*, in
//! sorted order of their `/`-separated paths relative to `c/`, and generates `$OUT_DIR/runtime_files.rs`, which
//! defines `pub static RUNTIME_FILES: &[(&str, &str)]`: one `(relative path, include_str!(...))` pair per file, such
//! as `("include/cpl.h", "...")`. Any other file under `c/` (`c/README.md`) is neither embedded nor digested. A
//! runtime file that is not UTF-8 fails the build. This is the mechanism `crates/cpl-project/build.rs` uses for
//! `std/` (toolchain 3.6, T52); Cargo compiles no C.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

/// Every runtime file below `dir` as (relative path with `/` separators, absolute path).
fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    println!("cargo:rerun-if-changed={}", dir.display());
    let entries = fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("cannot read the runtime directory {}: {e}", dir.display()));
    for entry in entries {
        let entry = entry.unwrap_or_else(|e| panic!("cannot read {}: {e}", dir.display()));
        let path = entry.path();
        let file_type = entry
            .file_type()
            .unwrap_or_else(|e| panic!("cannot inspect {}: {e}", path.display()));
        if file_type.is_dir() {
            collect(root, &path, out);
            continue;
        }
        let is_runtime_file = path
            .extension()
            .and_then(|e| e.to_str())
            .is_some_and(|e| e == "c" || e == "h");
        if !is_runtime_file || !path.is_file() {
            continue;
        }
        let relative = path
            .strip_prefix(root)
            .expect("a runtime file lies under c/")
            .components()
            .map(|c| {
                c.as_os_str()
                    .to_str()
                    .unwrap_or_else(|| panic!("{} is not a UTF-8 path", path.display()))
                    .to_string()
            })
            .collect::<Vec<_>>()
            .join("/");
        out.push((relative, path));
    }
}

fn main() {
    let manifest_dir =
        PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("cargo sets CARGO_MANIFEST_DIR"));
    let c_dir = manifest_dir.join("c");
    let mut files = Vec::new();
    collect(&c_dir, &c_dir, &mut files);
    files.sort();

    let mut out = String::from(
        "// Generated by crates/cpl-rt/build.rs from the runtime files under crates/cpl-rt/c/\n\
         // (spec/toolchain.md 1.12, spec/cabi.md 2.2). Do not edit.\n\n\
         /// The runtime files (`spec/cabi.md` 2.2): one `(relative path, text)` pair per `*.c` and `*.h` file under\n\
         /// `crates/cpl-rt/c/`, in sorted order of the `/`-separated paths relative to that directory, such as\n\
         /// `(\"cpl_rt.h\", \"...\")` and `(\"include/cpl.h\", \"...\")`. Every other file there is neither embedded\n\
         /// nor digested.\n\
         pub static RUNTIME_FILES: &[(&str, &str)] = &[\n",
    );
    for (relative, path) in &files {
        println!("cargo:rerun-if-changed={}", path.display());
        let bytes =
            fs::read(path).unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
        if let Err(e) = std::str::from_utf8(&bytes) {
            panic!(
                "{} is not valid UTF-8 (byte {}): runtime files are UTF-8 text",
                path.display(),
                e.valid_up_to()
            );
        }
        let absolute = path
            .to_str()
            .unwrap_or_else(|| panic!("{} is not a UTF-8 path", path.display()));
        writeln!(out, "    ({relative:?}, include_str!({absolute:?})),")
            .expect("writing to a String");
    }
    out.push_str("];\n");

    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("cargo sets OUT_DIR"));
    fs::write(out_dir.join("runtime_files.rs"), out).expect("cannot write runtime_files.rs");
}
