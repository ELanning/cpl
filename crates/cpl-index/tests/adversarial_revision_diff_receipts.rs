/// A minimal `cpl.toml` (Section 11.1); `[build] sources` defaults to `["src"]`.
const MANIFEST: &str = "[project]\nname = \"adversarial\"\nedition = \"0.1\"\n";

fn blake3_hex(bytes: &[u8]) -> String {
    blake3::hash(bytes).to_hex().to_string()
}

fn is_lower_hex(text: &str, len: usize) -> bool {
    text.len() == len
        && text
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}

/// A valid `cpl.lock` (Section 11.2) whose `[verification]` timeout is `timeout`.
fn lock_text(timeout: u64) -> String {
    format!(
        "# Generated by cpl. Do not edit.\nversion = 1\n\n[toolchain]\ncpl = \"{}\"\nedition = \"{}\"\nstd = \"{}\"\n\n[sources]\n\n[verification]\nproof_timeout_ms = {timeout}\nadmit = []\n",
        cpl_diag::version::TOOLCHAIN,
        cpl_diag::version::EDITION,
        "0".repeat(64),
    )
}

/// `cpl.toml` plus `files`, in memory.
fn vtree(files: &[(&str, &str)]) -> VirtualTree {
    let mut tree = VirtualTree::default();
    tree.files
        .insert("cpl.toml".to_string(), MANIFEST.as_bytes().to_vec());
    for (path, text) in files {
        tree.files
            .insert((*path).to_string(), text.as_bytes().to_vec());
    }
    tree
}

#[track_caller]
fn load_vtree(tree: &VirtualTree) -> Project {
    load_project_from_tree(tree, FileOrigin::Virtual, &LoadOptions::default())
        .unwrap_or_else(|e| panic!("the in-memory tree does not load: {e}"))
}

/// The revision of a project outside any repository (Section 6.3, row 1).
fn unversioned(project: &Project) -> Revision {
    Revision {
        commit: None,
        state: WORKTREE,
        digest: source_digest(project),
    }
}

/// An in-memory project that loads without an error, so that no
/// declaration silently drops out of a facet map.
#[track_caller]
fn parsed_project(files: &[(&str, &str)]) -> Project {
    let project = load_vtree(&vtree(files));
    let errors: Vec<String> = project
        .diagnostics
        .iter()
        .filter(|d| d.is_error())
        .map(|d| format!("{}: {}", d.code.0, d.message))
        .collect();
    assert!(errors.is_empty(), "the test input has errors: {errors:?}");
    project
}

#[track_caller]
fn map_of(files: &[(&str, &str)]) -> FacetMap {
    let project = parsed_project(files);
    facet_map(&project, unversioned(&project))
}

#[track_caller]
fn diff_of(before: &[(&str, &str)], after: &[(&str, &str)]) -> DiffOutput {
    semantic_diff(&map_of(before), &map_of(after))
}

/// The JSON spelling of a statement kind (`identity_added`, ...).
fn word(kind: K) -> String {
    serde_json::to_value(kind)
        .expect("a statement kind serializes")
        .as_str()
        .expect("as a string")
        .to_string()
}

/// `(statement, path)` of every statement, in order.
fn summary(diff: &DiffOutput) -> Vec<(String, String)> {
    diff.statements
        .iter()
        .map(|s| (word(s.statement), s.path.clone()))
        .collect()
}

fn pairs(items: &[(&str, &str)]) -> Vec<(String, String)> {
    items
        .iter()
        .map(|(a, b)| ((*a).to_string(), (*b).to_string()))
        .collect()
}

/// The one statement of `kind` about `path`.
#[track_caller]
fn only<'d>(diff: &'d DiffOutput, kind: K, path: &str) -> &'d DiffStatement {
    let found: Vec<&DiffStatement> = diff
        .statements
        .iter()
        .filter(|s| s.statement == kind && s.path == path)
        .collect();
    assert_eq!(
        found.len(),
        1,
        "one {} about {path} in {:?}",
        word(kind),
        summary(diff)
    );
    found[0]
}

/// The `SymbolVersion` of the declaration `name` in the file at `path`.
#[track_caller]
fn version_in(files: &[(&str, &str)], path: &str, name: &str) -> SymbolVersion {
    let project = parsed_project(files);
    let id = project
        .source_map
        .find(path)
        .unwrap_or_else(|| panic!("no file {path}"));
    let index = project
        .files
        .iter()
        .position(|e| e.file == id)
        .expect("a source entry");
    let ParsedFile::Module(module) = &project.parsed[index] else {
        panic!("{path} is not a parsed module");
    };
    let module_path: Vec<String> = module
        .header
        .path
        .segments
        .iter()
        .map(|s| s.text.clone())
        .collect();
    let decl = module
        .declarations
        .iter()
        .find(|d| d.display_name() == name)
        .unwrap_or_else(|| panic!("no declaration {name}"));
    symbol_version(&module_path, decl)
}

