/// `[targets] c`: the runtime, compiler, flags, platform files, and export
/// table of the locked C build (Section 11.2).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TargetC {
    /// The C API version, `cpl_rtspec::limits::C_API_VERSION` as `"<major>.<minor>"`.
    pub api: String,
    /// `cpl_rt::RUNTIME_VERSION`.
    pub runtime: String,
    /// `cpl_rt::runtime_digest` of the runtime used.
    pub runtime_digest: Digest,
    /// The compiler's `-dumpmachine`.
    pub target: String,
    /// Family and version, `"gcc 11.4.0"`.
    pub compiler: String,
    /// The resolved driver binary.
    pub compiler_path: String,
    /// blake3 of that binary.
    pub compiler_digest: Digest,
    /// The effective flag set of the locked profile, the manifest's flags included.
    pub flags_digest: Digest,
    /// The platform files the link opened.
    pub system_digest: Digest,
    pub prefix: String,
    pub abi: u16,
    /// The canonical export table (`spec/cabi.md` Section 9).
    pub exports_digest: Digest,
    /// One entry per export symbol.
    pub exports: BTreeMap<String, LockedExport>,
    /// Every name the version script exports, sorted.
    pub symbols: Vec<String>,
}

/// One locked export of [`TargetC::exports`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct LockedExport {
    /// The target's qualified name.
    pub function: String,
    pub id: StableId,
    /// The ABI digest (`spec/cabi.md` Section 9).
    pub signature: Digest,
    pub int: IntMapping,
}

/// One backend-`c` entry of `[adapters]` (the stored table also has
/// `backend = "c"`, which this view implies).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct AdapterC {
    pub form: AdapterForm,
    /// `"in_process"` in edition 0.1 (the value is one of `worker`, `in_process`).
    pub isolation: String,
    /// The capability as the manifest names it.
    pub capability: String,
    /// The adapter file's digest, by project-relative path.
    pub files: BTreeMap<String, Digest>,
}

/// The native dependencies of one backend-`c` binding (`[foreign] c`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ForeignC {
    /// The vendored sources' digests, by project-relative path.
    pub sources: BTreeMap<String, Digest>,
    /// Every header the binding's compilations read, from their depfiles.
    pub headers: Digest,
    /// By `-l` name: the file the linker opened for it.
    pub libraries: BTreeMap<String, LockedLibrary>,
}

/// The file the linker opened for one `-l<name>` of a binding.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct LockedLibrary {
    /// Project-relative under the project root, absolute elsewhere.
    pub path: String,
    pub digest: Digest,
}

/// `[targets] python` (`spec/python.md` 9): the locked Python build's package, compiler, flags, runtime, and the
/// interpreter headers the extension unit read.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TargetPython {
    /// The import name (`[interop.python] package`).
    pub package: String,
    /// The distribution version (`[interop.python] version`).
    pub version: String,
    /// The C API version, `"<major>.<minor>"`.
    pub api: String,
    /// The resolved C compiler driver.
    pub compiler_path: String,
    pub compiler_digest: Digest,
    /// The effective flag set (cabi.md 1.5) of the locked profile, the extension's own flags included.
    pub flags_digest: Digest,
    pub runtime_digest: Digest,
    /// Every interpreter header the extension unit's depfile lists.
    pub python_headers_digest: Digest,
}

/// One backend-`python` entry of `[adapters]` (`spec/python.md` 9; the stored table also has `backend = "python"`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct AdapterPython {
    /// The adapter module's dotted path.
    pub module: String,
    /// The binding's input digest (`crate::python_input_digest`).
    pub digest: Digest,
}

impl Lock {
    /// `[targets] c`, `None` when absent. (A malformed entry, which
    /// [`parse_lock`] rejects, can exist only in a hand-built `Lock`, and
    /// reads as absent.)
    pub fn target_c(&self) -> Option<TargetC> {
        self.targets
            .get("c")
            .and_then(|v| target_c_from(v, "targets.c").ok())
    }

    /// The `[adapters]` entries with `backend = "c"`, by binding name.
    pub fn c_adapters(&self) -> BTreeMap<String, AdapterC> {
        self.adapters
            .iter()
            .filter(|(_, v)| is_c_adapter(v))
            .filter_map(|(name, v)| {
                adapter_c_from(v, &format!("adapters.{}", key(name)))
                    .ok()
                    .map(|a| (name.clone(), a))
            })
            .collect()
    }

    /// `[foreign] c`, by binding name; empty when absent.
    pub fn foreign_c(&self) -> BTreeMap<String, ForeignC> {
        let Some(toml::Value::Table(bindings)) = self.foreign.get("c") else {
            return BTreeMap::new();
        };
        bindings
            .iter()
            .filter_map(|(name, v)| {
                foreign_c_from(v, &format!("foreign.c.{}", key(name)))
                    .ok()
                    .map(|f| (name.clone(), f))
            })
            .collect()
    }

    /// Whether the lock has a C entry: `[targets] c`, a backend-`c`
    /// `[adapters]` entry, or `[foreign] c` (Section 11.2: only then does
    /// the release check compare the C build inputs).
    pub fn has_c_entry(&self) -> bool {
        self.targets.contains_key("c")
            || self.foreign.contains_key("c")
            || self.adapters.values().any(is_c_adapter)
    }

    /// Replace `[targets] c` (`None` removes it); every other key of
    /// `[targets]` is kept.
    pub fn set_target_c(&mut self, target: Option<TargetC>) {
        match target {
            Some(t) => {
                self.targets.insert("c".to_string(), target_c_value(&t));
            }
            None => {
                self.targets.remove("c");
            }
        }
    }

    /// Replace the backend-`c` entries of `[adapters]`, keeping the others
    /// (an entry of another backend under a name in `adapters` is replaced).
    pub fn set_c_adapters(&mut self, adapters: BTreeMap<String, AdapterC>) {
        let stale: Vec<String> = self
            .adapters
            .iter()
            .filter(|(name, v)| is_c_adapter(v) || adapters.contains_key(*name))
            .map(|(name, _)| name.clone())
            .collect();
        for name in stale {
            self.adapters.remove(&name);
        }
        for (name, adapter) in adapters {
            self.adapters.insert(name, adapter_c_value(&adapter));
        }
    }

    /// Replace `[foreign] c` (an empty map removes it); every other key of
    /// `[foreign]` is kept.
    pub fn set_foreign_c(&mut self, foreign: BTreeMap<String, ForeignC>) {
        if foreign.is_empty() {
            self.foreign.remove("c");
            return;
        }
        let mut table = toml::Table::new();
        for (name, f) in foreign {
            table.insert(name, foreign_c_value(&f));
        }
        self.foreign
            .insert("c".to_string(), toml::Value::Table(table));
    }
}

