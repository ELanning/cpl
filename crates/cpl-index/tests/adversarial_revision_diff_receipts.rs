#[test]
fn the_receipt_digest_leaves_out_exactly_the_two_informational_fields() {
    let s = sample();
    let receipt = serde_json::to_value(verification(&s.inputs, &s)).expect("serializes");
    let digest = receipt_digest(&receipt);
    let mut without = receipt.clone();
    let object = without.as_object_mut().expect("an object");
    assert!(object.remove("produced_at").is_some());
    assert!(object.remove("duration_ms").is_some());
    assert_eq!(receipt_digest(&without), digest);
    let mut changed = receipt.clone();
    changed["produced_at"] = json!("1999-12-31T23:59:59Z");
    changed["duration_ms"] = json!(987_654_321);
    assert_eq!(receipt_digest(&changed), digest);
    // Every other key is evidence, however informational it sounds.
    let mut extra = receipt.clone();
    extra["produced_by"] = json!("someone");
    assert_ne!(receipt_digest(&extra), digest);
    // Section 8: blake3 of the receipt with keys sorted, no whitespace, and
    // the two fields removed.
    let mut text = String::new();
    canonical_json(&without, &mut text);
    assert_eq!(digest.as_str(), blake3_hex(text.as_bytes()));
    assert!(is_lower_hex(digest.as_str(), 64));
}

#[test]
fn the_receipt_digest_does_not_depend_on_whitespace_or_key_order() {
    let s = sample();
    let receipt = verification(&s.inputs, &s);
    let value = serde_json::to_value(&receipt).expect("serializes");
    let pretty: Value =
        serde_json::from_str(&serde_json::to_string_pretty(&receipt).expect("serializes"))
            .expect("json");
    let compact: Value =
        serde_json::from_str(&serde_json::to_string(&receipt).expect("serializes")).expect("json");
    assert_eq!(receipt_digest(&pretty), receipt_digest(&value));
    assert_eq!(receipt_digest(&compact), receipt_digest(&value));
    let shuffled: Value = serde_json::from_str(
        r#"{ "z": { "b": [1, 2], "a": "x y" },
             "a": null,
             "produced_at": "2026-10-28T00:00:00Z" }"#,
    )
    .expect("json");
    let sorted: Value =
        serde_json::from_str(r#"{"a":null,"z":{"a":"x y","b":[1,2]}}"#).expect("json");
    assert_eq!(receipt_digest(&shuffled), receipt_digest(&sorted));
    assert_eq!(
        receipt_digest(&sorted).as_str(),
        blake3_hex(br#"{"a":null,"z":{"a":"x y","b":[1,2]}}"#)
    );
    // "Keys sorted" sorts the keys themselves ('"' < '#'), not their
    // escaped spellings ('\\' > '#'), as RFC 8785 does.
    let escaped: Value = serde_json::from_str(r#"{"a#b": 2, "a\"b": 1}"#).expect("json");
    assert_eq!(
        receipt_digest(&escaped).as_str(),
        blake3_hex(br#"{"a\"b":1,"a#b":2}"#)
    );
    // Arrays keep their order: it is part of the evidence.
    let reversed: Value =
        serde_json::from_str(r#"{"a":null,"z":{"a":"x y","b":[2,1]}}"#).expect("json");
    assert_ne!(receipt_digest(&reversed), receipt_digest(&sorted));
}

