//! The Go printer: a module whose root package holds the program (`spec/hosts.md` 3).
//!
//! CPL functions are Go functions, structs are structs, enums are sealed interfaces with one
//! struct per variant (`Shape` and `Shape_Line{F0: ...}`), wrappers are structs with one field
//! `V`, and capabilities are interfaces the host implements. Text is `string` and Bool is
//! `bool`; the runtime package `cpl` has the rest.
//!
//! Every function has an internal form `x_f(args..., cx)` that the program's own calls use and
//! that panics with a `*cpl.Fault`; a `pub fn` also has an exported form `F(args...) (T,
//! error)` that makes the calling context, checks the refinements and invariants of its
//! arguments, and recovers a fault as its error.

use crate::lir::*;
use crate::lower::{diverges, Lowered};
use crate::{erase, instantiate, pascal, std_type, Options, Package, StdType};
use cpl_hir::{DefId, DefKind, Program, Ty};
use num_traits::ToPrimitive;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

/// Whether a value entering at `ty` is checked at the boundary: its refinements and invariants,
/// and its texts, which a Go string or a Java string may hold invalid (not Unicode scalars).
fn needs_validation(p: &Program, ty: &Ty) -> bool {
    crate::needs_validation(p, ty) || crate::contains_text(p, ty)
}

