//! The package header `<prefix>.h` (`spec/cabi.md` 5.3, Appendix C.1).

use crate::api::{self, ExportModel};
use crate::map::Form;
use crate::print::comment_text;
use crate::InteropPlan;
use cpl_hir::{DefKind, Program, Ty};
use cpl_sema::interop::snake_case;
use std::fmt::Write as _;

/// The comment of a listed type (5.3).
fn type_comment(p: &Program, text: &str, ty: &Ty) -> String {
    match ty {
        Ty::Adt(d, args) if args.is_empty() => {
            let def = p.def(*d);
            let g = def.kind.generics();
            let qn = p.display_path(*d);
            match &def.kind {
                DefKind::Struct(s) => {
                    let fields: Vec<String> = s
                        .fields
                        .iter()
                        .map(|f| format!("{}: {}", f.name, p.display_ty_in(&f.ty, g)))
                        .collect();
                    format!("struct {qn} {{ {} }}", fields.join(", "))
                }
                DefKind::Enum(e) => {
                    let vs: Vec<String> = e
                        .variants
                        .iter()
                        .map(|v| {
                            if v.payload.is_empty() {
                                v.name.clone()
                            } else {
                                let ts: Vec<String> =
                                    v.payload.iter().map(|t| p.display_ty_in(t, g)).collect();
                                format!("{}({})", v.name, ts.join(", "))
                            }
                        })
                        .collect();
                    format!("enum {qn} {{ {} }}", vs.join(", "))
                }
                _ => text.to_string(),
            }
        }
        Ty::Wrapper(d) => {
            let qn = p.display_path(*d);
            let inner = p
                .def(*d)
                .kind
                .as_wrapper()
                .map(|w| p.display_ty(&w.inner))
                .unwrap_or_default();
            format!("type {qn}({inner})")
        }
        Ty::Refined(_, d) => {
            let qn = p.display_path(*d);
            match p.def(*d).kind.as_refinement() {
                Some(rd) => format!(
                    "type {qn} = {} where {}",
                    p.display_ty(&rd.base),
                    rd.predicate.text
                ),
                None => text.to_string(),
            }
        }
        Ty::Capability(d) => format!("capability {}", p.display_path(*d)),
        _ => text.to_string(),
    }
}

/// The text of `<prefix>.h`.
#[allow(clippy::too_many_arguments)]
pub(crate) fn render(
    p: &Program,
    plan: &InteropPlan,
    prefix: &str,
    project_name: &str,
    edition: &str,
    runtime_digest: &str,
    program_digest: &str,
    exports_digest: &str,
    target: &str,
    models: &[ExportModel],
) -> String {
    let upper = prefix.to_ascii_uppercase();
    let mut h = String::new();
    let _ = writeln!(
        h,
        "/* {prefix}.h: generated by cpl {} (edition {edition}, C API 0.1) for project \"{}\"; do not edit.",
        cpl_diag::version::TOOLCHAIN,
        comment_text(project_name)
    );
    h.push_str("   Regenerate with `cpl build --target c`; the CPL sources and cpl.toml are the editing authority.\n");
    let _ = writeln!(
        h,
        "   runtime {runtime_digest}; program {program_digest}; exports {exports_digest}; target {} */",
        if target.is_empty() { "unknown" } else { target }
    );
    let _ = writeln!(
        h,
        "#ifndef {upper}_H\n#define {upper}_H 1\n#include \"cpl.h\""
    );
    let _ = writeln!(
        h,
        "#if CPL_API_VERSION_MAJOR != 0 || CPL_API_VERSION_MINOR < 1\n#error \"{prefix}.h was generated for CPL C API 0.1\"\n#endif"
    );
    h.push_str("#ifdef __cplusplus\nextern \"C\" {\n#endif\n");
    let _ = writeln!(h, "#define {upper}_ABI {}u\n", plan.abi);
    h.push_str("/* ---- package ---- */\n");
    let _ = writeln!(h, "const cpl_library_info *{prefix}_library_info(void);");
    let _ = writeln!(
        h,
        "cpl_status {prefix}_runtime_open(const cpl_runtime_options *options, cpl_runtime **out, cpl_error **error);"
    );
    let types = api::listed_types(plan);
    if !types.is_empty() {
        h.push_str("\n/* ---- types; ids are valid only with this package's runtimes ---- */\n");
        for (c_name, text, ty) in &types {
            let _ = writeln!(h, "/* {} */", comment_text(&type_comment(p, text, ty)));
            let _ = writeln!(h, "cpl_type {prefix}_type_{c_name}(void);");
            if let Some(d) = api::decl_kind(p, ty) {
                let name_up = c_name.to_ascii_uppercase();
                match &p.def(d).kind {
                    DefKind::Struct(s) => {
                        for (i, f) in s.fields.iter().enumerate() {
                            let _ = writeln!(
                                h,
                                "#define {upper}_{name_up}_F_{} {i}u",
                                f.name.to_ascii_uppercase()
                            );
                        }
                    }
                    DefKind::Enum(e) => {
                        for (i, v) in e.variants.iter().enumerate() {
                            let _ = writeln!(
                                h,
                                "#define {upper}_{name_up}_V_{} {i}u",
                                snake_case(&v.name).to_ascii_uppercase()
                            );
                        }
                    }
                    _ => {}
                }
            }
        }
    }
    let caps = api::listed_capabilities(p, plan);
    if !caps.is_empty() {
        h.push_str("\n/* ---- capabilities ---- */\n");
        for cap in &caps {
            let qn = p.display_path(*cap);
            let name = snake_case(&p.def(*cap).name.display());
            let ops_t = format!("{prefix}_{name}_ops");
            let cd = p.def(*cap).kind.as_capability().expect("a capability");
            let members = api::op_members(p, *cap);
            let _ = writeln!(h, "/* capability {qn} */");
            let _ = writeln!(h, "typedef struct {ops_t} {{");
            let _ = writeln!(h, "    /* sizeof({ops_t}) */\n    uint32_t struct_size;\n    /* padding; never read */\n    uint32_t reserved;");
            for (i, op) in cd.ops.iter().enumerate() {
                let params = api::callback_params(p, *cap, i);
                let ps: Vec<String> = op
                    .params
                    .iter()
                    .map(|x| format!("{}: {}", x.name, p.display_ty(&x.ty)))
                    .collect();
                let _ = writeln!(
                    h,
                    "    /* fn {}({}) -> {}",
                    op.name,
                    ps.join(", "),
                    p.display_ty(&op.ret)
                );
                let notes: Vec<String> = params
                    .iter()
                    .map(|x| match x.form {
                        Form::Bytes => format!("{}: a borrowed byte span, valid for the call", x.c),
                        Form::Text => format!("{}: a borrowed UTF-8 span, valid for the call", x.c),
                        Form::Bool => format!("{}: 0 or 1", x.c),
                        _ => format!("{}: borrowed for the call", x.c),
                    })
                    .collect();
                if !notes.is_empty() {
                    let _ = writeln!(h, "       {}", notes.join("; "));
                }
                let _ = writeln!(
                    h,
                    "       on CPL_OK *result: an owned {}, validated by the runtime before CPL sees it */",
                    p.display_ty(&op.ret)
                );
                let mut args = vec!["void *user".to_string(), "cpl_call *call".to_string()];
                for x in &params {
                    match x.form {
                        Form::Text => args.push(format!(
                            "const char *{}, size_t {}",
                            x.c,
                            x.len.as_deref().unwrap_or("len")
                        )),
                        Form::Bytes => args.push(format!(
                            "const uint8_t *{}, size_t {}",
                            x.c,
                            x.len.as_deref().unwrap_or("len")
                        )),
                        Form::Bool => args.push(format!("int32_t {}", x.c)),
                        _ => args.push(format!("cpl_value {}", x.c)),
                    }
                }
                args.push("cpl_value *result".to_string());
                let _ = writeln!(h, "    cpl_status (*{})({});", members[i], args.join(", "));
            }
            h.push_str(
                "    /* optional; called once, after the last reference is released and no call is in flight */\n    void (*drop)(void *user);\n",
            );
            let _ = writeln!(h, "}} {ops_t};");
            let _ = writeln!(
                h,
                "CPL_LAYOUT_ASSERT(sizeof({ops_t}) == {}u)",
                8 + 8 * (cd.ops.len() + 1)
            );
            let head = format!("cpl_status {prefix}_{name}_new(");
            let _ = writeln!(
                h,
                "{head}cpl_runtime *rt, const {ops_t} *ops, void *user,\n{}cpl_cap *out, cpl_error **error);",
                " ".repeat(head.len())
            );
        }
    }
    // one grant per binding (cabi.md 5.3): the backend-c ones, then from Milestone 3 the backend-python ones
    if plan.ngrants() > 0 {
        h.push_str("\n/* ---- grants ---- */\n");
        for b in &plan.bindings {
            let _ = writeln!(
                h,
                "/* [bindings.{}]: backend c, isolation {}, adapter {}.\n   The manifest requests the binding; the host grants it by calling this function. */",
                b.name,
                if b.worker { "worker (the C adapter host, spec/python.md 6.6)" } else { "in_process" },
                b.adapter
            );
            let _ = writeln!(
                h,
                "cpl_status {prefix}_bind_{}(cpl_runtime *rt, cpl_cap *out, cpl_error **error);",
                b.name
            );
        }
        for b in &plan.python_bindings {
            let _ = writeln!(
                h,
                "/* [bindings.{}]: backend python, adapter module {}, run in a Python worker (spec/python.md 6:\n   CPL_PYTHON, else python3, with this process's environment). The host grants it by calling this function. */",
                b.name, b.module
            );
            let _ = writeln!(
                h,
                "cpl_status {prefix}_bind_{}(cpl_runtime *rt, cpl_cap *out, cpl_error **error);",
                b.name
            );
        }
    }
    if !models.is_empty() {
        h.push_str("\n/* ---- exports ---- */\n");
        for m in models {
            h.push_str(&api::export_comment(p, m));
            h.push_str(&api::export_prototype(m, ""));
            h.push_str(";\n");
        }
    }
    let mut skipped: Vec<_> = plan.skipped.iter().map(|d| p.display_path(*d)).collect();
    skipped.sort();
    if !skipped.is_empty() {
        h.push('\n');
        for s in skipped {
            let _ = writeln!(
                h,
                "/* not exported: {s} is generic (project_export_skipped_generic) */"
            );
        }
    }
    h.push_str("#ifdef __cplusplus\n}\n#endif\n#endif\n");
    h
}
