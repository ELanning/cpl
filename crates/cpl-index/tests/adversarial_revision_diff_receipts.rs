/// Section 3.6 computed from the `std/` directory itself: blake3 over
/// `name LF content LF` for every `*.cpl` file in sorted name order.
fn std_digest_of_the_std_directory() -> String {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../std");
    let mut names: Vec<String> = std::fs::read_dir(&dir)
        .expect("the std directory")
        .map(|e| {
            e.expect("an entry")
                .file_name()
                .into_string()
                .expect("utf-8")
        })
        .filter(|n| n.len() > ".cpl".len() && n.ends_with(".cpl"))
        .collect();
    names.sort();
    let mut hasher = blake3::Hasher::new();
    for name in names {
        let content = std::fs::read(dir.join(&name)).expect("a std file");
        hasher.update(name.as_bytes());
        hasher.update(b"\n");
        hasher.update(&content);
        hasher.update(b"\n");
    }
    hasher.finalize().to_hex().to_string()
}

/// The canonical JSON of Section 8, written independently of the crate:
/// object keys sorted (Rust's string order, which for the keys used here is
/// also the UTF-16 order of RFC 8785), no whitespace, scalars as `serde_json`
/// writes them.
fn canonical_json(value: &Value, out: &mut String) {
    match value {
        Value::Object(map) => {
            let mut keys: Vec<&String> = map.keys().collect();
            keys.sort();
            out.push('{');
            for (i, key) in keys.into_iter().enumerate() {
                if i > 0 {
                    out.push(',');
                }
                out.push_str(&serde_json::to_string(key).expect("a key"));
                out.push(':');
                canonical_json(map.get(key.as_str()).expect("the value"), out);
            }
            out.push('}');
        }
        Value::Array(items) => {
            out.push('[');
            for (i, item) in items.iter().enumerate() {
                if i > 0 {
                    out.push(',');
                }
                canonical_json(item, out);
            }
            out.push(']');
        }
        scalar => out.push_str(&serde_json::to_string(scalar).expect("a scalar")),
    }
}

