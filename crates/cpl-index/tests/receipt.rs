fn record(name: &str, kind: TestKind, status: TestStatus) -> TestCaseRecord {
    let qualified = format!("tests.pagination.\"{name}\"");
    TestCaseRecord {
        symbol: StableId::parse(&qualified).expect("id"),
        qualified_name: qualified,
        kind,
        status,
        duration_ms: 3,
        seed: (kind == TestKind::Property).then_some(1),
        property_seed: (kind == TestKind::Property).then(|| "c0".repeat(32)),
        cases: (kind == TestKind::Property).then_some(100),
        failing_case: None,
        shrunk: None,
        fault: None,
        counterexamples: vec![],
        receipt: None,
    }
}

fn report(results: Vec<TestCaseRecord>) -> TestReport {
    let failed = results
        .iter()
        .filter(|r| r.status == TestStatus::Failed)
        .count() as u32;
    TestReport {
        seed: 1,
        cases: 100,
        selected: results.len() as u32,
        tested: results.len() as u32 - failed,
        failed,
        results,
    }
}

fn config() -> TestRunConfig {
    TestRunConfig {
        seed: 1,
        cases: 100,
        max_shrinks: 1000,
        timeout_ms: 0,
        selector: TestSelectorSpec {
            namespace: Some(vec!["tests".into(), "pagination".into()]),
            name: None,
            id: None,
        },
        check_contracts: true,
        fail_fast: false,
    }
}

fn environment() -> BTreeMap<String, String> {
    [("os", "linux"), ("arch", "x86_64")]
        .into_iter()
        .map(|(k, v)| (k.to_string(), v.to_string()))
        .collect()
}

#[test]
fn a_test_receipt_has_the_section_8_2_shape() {
    let (project, inputs) = reader_inputs();
    let tested = vec![
        version(&project, "std/prelude.cpl", "flatten"),
        version(&project, "src/reader/pages.cpl", "paginate"),
    ];
    let results = vec![
        record(
            "pagination handles empty input",
            TestKind::Test,
            TestStatus::Tested,
        ),
        record(
            "pagination preserves a short tail",
            TestKind::Test,
            TestStatus::Tested,
        ),
        record(
            "pagination preserves input",
            TestKind::Property,
            TestStatus::Tested,
        ),
    ];
    let mut test_core = core(
        &project,
        json!({ "cases": 100, "max_shrinks": 1000, "max_call_depth": 10000, "seed": 1 }),
    );
    test_core.fixtures = Some(vec![]);
    test_core.environment = Some(environment());
    let receipt = test_receipt(
        &inputs,
        test_core,
        &report(results),
        tested,
        config(),
        vec![],
        vec![],
        environment(),
    );
    assert_eq!(receipt.status, TestStatus::Tested);
    assert_eq!(receipt.summary.selected, 3);
    assert_eq!(receipt.summary.tested, 3);
    let paths: Vec<&str> = receipt.tested.iter().map(|v| v.path.as_str()).collect();
    assert_eq!(paths, ["reader.pages.paginate", "std.prelude.flatten"]);
    let json = serde_json::to_string_pretty(&receipt).expect("serializes");
    assert_eq!(
        written_keys(&json),
        [
            "receipt",
            "schema",
            "toolchain",
            "revision",
            "inputs",
            "core",
            "configuration",
            "tested",
            "tests",
            "summary",
            "fixtures",
            "assumptions",
            "environment",
            "status",
            "produced_at",
            "duration_ms"
        ]
    );
    let value: Value = serde_json::from_str(&json).expect("json");
    assert_eq!(value["receipt"], json!("test"));
    assert_eq!(value["status"], json!("tested"));
    // The deterministic part of each record: no duration, no seed.
    assert_eq!(
        value["tests"][2],
        json!({
            "symbol": "tests.pagination.\"pagination preserves input\"",
            "qualified_name": "tests.pagination.\"pagination preserves input\"",
            "kind": "property",
            "status": "tested",
            "property_seed": "c0".repeat(32),
            "cases": 100
        })
    );
    assert_eq!(value["tests"][0].get("cases"), None);
    assert_eq!(
        value["environment"],
        json!({ "arch": "x86_64", "os": "linux" })
    );
    assert_eq!(
        value["configuration"]["selector"],
        json!({ "namespace": ["tests", "pagination"], "name": null, "id": null })
    );
}

#[test]
fn a_test_receipt_is_failed_unless_every_selected_test_is_tested() {
    let (project, inputs) = reader_inputs();
    let make = |results: Vec<TestCaseRecord>| {
        test_receipt(
            &inputs,
            core(&project, json!({})),
            &report(results),
            vec![],
            config(),
            vec![],
            vec![],
            BTreeMap::new(),
        )
    };
    let failing = make(vec![
        record("a", TestKind::Test, TestStatus::Tested),
        record("b", TestKind::Test, TestStatus::Failed),
    ]);
    assert_eq!(failing.status, TestStatus::Failed);
    assert_eq!(failing.summary.failed, 1);
    // An empty selection is a configuration failure, not evidence.
    let empty = make(vec![]);
    assert_eq!(empty.status, TestStatus::Failed);
    assert_eq!(empty.summary.selected, 0);
}

