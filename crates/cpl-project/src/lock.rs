//! `cpl.lock` (`spec/toolchain.md` 11.2): the [`Lock`] model,
//! [`parse_lock`], and the canonical [`render_lock`].
//!
//! Loading parses a present lock (a lock that does not parse is the fatal
//! `project_lock_invalid`) and reports `project_lock_toolchain_mismatch`;
//! comparing the lock with the tree (`project_lock_stale`) and reporting an
//! absent one (`project_lock_missing`) happen only under `cpl check
//! --release` (T37).
//!
//! From Milestone 2 (T75, T80) three keys of the reserved tables have closed
//! schemas: `[targets] c` ([`TargetC`]), every `[adapters]` entry whose
//! value is a table with `backend = "c"` ([`AdapterC`]), and `[foreign] c`
//! ([`ForeignC`] per binding). [`parse_lock`] validates them (a malformed
//! one is a [`LockError`]); [`Lock`] keeps its Milestone 1 fields, and the
//! entries are read and written through the typed views
//! ([`Lock::target_c`], [`Lock::c_adapters`], [`Lock::foreign_c`] and their
//! setters), which store them as the inline values [`render_lock`] writes.
//! Every other key of the three tables stays opaque and is carried through.

use crate::manifest::{AdapterForm, IntMapping, VerificationSection};
use crate::util::{key, line_at, quote};
use cpl_diag::json::Digest;
use cpl_diag::StableId;
use std::collections::BTreeMap;
use std::fmt::Write as _;

/// The first line of every rendered lock.
const HEADER: &str = "# Generated by cpl. Do not edit.";
/// The one lock format this toolchain reads and writes.
const VERSION: u32 = 1;
/// The top-level keys of the format, in rendering order.
const TOP_LEVEL: [&str; 7] = [
    "version",
    "toolchain",
    "sources",
    "verification",
    "foreign",
    "adapters",
    "targets",
];

/// The parsed `cpl.lock`.
#[derive(Clone, Debug, PartialEq)]
pub struct Lock {
    /// The format version; always 1.
    pub version: u32,
    pub toolchain: LockToolchain,
    /// The digest of every source-set file at lock time (`cpl.toml`, the
    /// `.cpl`, `.work`, and `.patch` files; never the lock itself, never
    /// std), by project-relative path.
    pub sources: BTreeMap<String, Digest>,
    /// The manifest's `[verification]` values at lock time.
    pub verification: VerificationSection,
    /// Reserved sections (Milestones 2-4), parsed as opaque tables and
    /// carried through unchanged by [`render_lock`].
    pub foreign: toml::Table,
    pub adapters: toml::Table,
    pub targets: toml::Table,
}

/// `[toolchain]` of `cpl.lock`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct LockToolchain {
    /// The toolchain version that wrote the lock (`cpl_diag::version::TOOLCHAIN`).
    pub cpl: String,
    /// The edition (`cpl_diag::version::EDITION`).
    pub edition: String,
    /// `std_digest` of the standard library (Section 3.6).
    pub std: Digest,
}

/// Why `cpl.lock` is unusable (`project_lock_invalid`, the fatal
/// [`crate::LoadError::Lock`]).
#[derive(thiserror::Error, Clone, Debug, PartialEq, Eq)]
#[error("{message}")]
pub struct LockError {
    pub message: String,
    /// 1-based line in `cpl.lock`, when the error has a location (TOML syntax errors).
    pub line: Option<u32>,
}

fn invalid(message: impl Into<String>) -> LockError {
    LockError {
        message: message.into(),
        line: None,
    }
}

fn type_name(value: &toml::Value) -> &'static str {
    value.type_str()
}

/// Parse `cpl.lock`. The format is closed: `version = 1`, `[toolchain]`
/// (`cpl`, `edition`, `std`), `[sources]` (path = digest), and
/// `[verification]` (`proof_timeout_ms`, `admit`) are required; `[foreign]`,
/// `[adapters]`, and `[targets]` are optional opaque tables; any other key,
/// a wrong type, another version, or a digest that is not 64 lowercase hex
/// characters is a [`LockError`].
pub fn parse_lock(text: &str) -> Result<Lock, LockError> {
    let table: toml::Table = text.parse().map_err(|e: toml::de::Error| LockError {
        message: format!("cpl.lock is not valid TOML: {}", e.message()),
        line: e.span().map(|span| line_at(text.as_bytes(), span.start)),
    })?;
    for name in table.keys() {
        if !TOP_LEVEL.contains(&name.as_str()) {
            return Err(invalid(format!("unknown key `{}` in cpl.lock", key(name))));
        }
    }

    let version = match table.get("version") {
        None => return Err(invalid("missing required key `version` in cpl.lock")),
        Some(toml::Value::Integer(v)) if *v == i64::from(VERSION) => VERSION,
        Some(toml::Value::Integer(v)) => {
            return Err(invalid(format!(
                "unsupported cpl.lock version {v}: this toolchain reads version {VERSION}"
            )))
        }
        Some(other) => {
            return Err(invalid(format!(
                "`version` in cpl.lock must be an integer, found {}",
                type_name(other)
            )))
        }
    };

    let toolchain_table = required_table(&table, "toolchain")?;
    closed(toolchain_table, "toolchain", &["cpl", "edition", "std"])?;
    let toolchain = LockToolchain {
        cpl: required_string(toolchain_table, "toolchain", "cpl")?,
        edition: required_string(toolchain_table, "toolchain", "edition")?,
        std: digest(
            &required_string(toolchain_table, "toolchain", "std")?,
            "toolchain.std",
        )?,
    };

    let mut sources = BTreeMap::new();
    for (path, value) in required_table(&table, "sources")? {
        let toml::Value::String(hex) = value else {
            return Err(invalid(format!(
                "`sources.{}` in cpl.lock must be a digest string, found {}",
                key(path),
                type_name(value)
            )));
        };
        sources.insert(
            path.clone(),
            digest(hex, &format!("sources.{}", key(path)))?,
        );
    }

    let verification_table = required_table(&table, "verification")?;
    closed(
        verification_table,
        "verification",
        &["proof_timeout_ms", "admit"],
    )?;
    let proof_timeout_ms = match verification_table.get("proof_timeout_ms") {
        None => {
            return Err(invalid(
                "missing required key `verification.proof_timeout_ms` in cpl.lock",
            ))
        }
        Some(toml::Value::Integer(v)) if *v >= 0 => *v as u64,
        Some(other) => {
            return Err(invalid(format!(
                "`verification.proof_timeout_ms` in cpl.lock must be a non-negative integer, found {other}"
            )))
        }
    };
    let admit = match verification_table.get("admit") {
        None => {
            return Err(invalid(
                "missing required key `verification.admit` in cpl.lock",
            ))
        }
        Some(toml::Value::Array(items)) => items
            .iter()
            .map(|item| match item {
                toml::Value::String(s) => Ok(s.clone()),
                other => Err(invalid(format!(
                    "`verification.admit` in cpl.lock must be an array of strings, found {}",
                    type_name(other)
                ))),
            })
            .collect::<Result<Vec<_>, _>>()?,
        Some(other) => {
            return Err(invalid(format!(
                "`verification.admit` in cpl.lock must be an array of strings, found {}",
                type_name(other)
            )))
        }
    };

    let lock = Lock {
        version,
        toolchain,
        sources,
        verification: VerificationSection {
            proof_timeout_ms,
            admit,
        },
        foreign: optional_table(&table, "foreign")?,
        adapters: optional_table(&table, "adapters")?,
        targets: optional_table(&table, "targets")?,
    };
    validate_c_entries(&lock).map_err(invalid)?;
    Ok(lock)
}

fn required_table<'t>(table: &'t toml::Table, name: &str) -> Result<&'t toml::Table, LockError> {
    match table.get(name) {
        None => Err(invalid(format!(
            "missing required table `[{name}]` in cpl.lock"
        ))),
        Some(toml::Value::Table(t)) => Ok(t),
        Some(other) => Err(invalid(format!(
            "`{name}` in cpl.lock must be a table, found {}",
            type_name(other)
        ))),
    }
}

fn optional_table(table: &toml::Table, name: &str) -> Result<toml::Table, LockError> {
    match table.get(name) {
        None => Ok(toml::Table::new()),
        Some(toml::Value::Table(t)) => Ok(t.clone()),
        Some(other) => Err(invalid(format!(
            "`{name}` in cpl.lock must be a table, found {}",
            type_name(other)
        ))),
    }
}

/// Every key of the table at `path` is one of `known`.
fn closed(table: &toml::Table, path: &str, known: &[&str]) -> Result<(), LockError> {
    match table.keys().find(|k| !known.contains(&k.as_str())) {
        None => Ok(()),
        Some(k) => Err(invalid(format!(
            "unknown key `{path}.{}` in cpl.lock",
            key(k)
        ))),
    }
}

fn required_string(table: &toml::Table, path: &str, name: &str) -> Result<String, LockError> {
    match table.get(name) {
        None => Err(invalid(format!(
            "missing required key `{path}.{name}` in cpl.lock"
        ))),
        Some(toml::Value::String(s)) => Ok(s.clone()),
        Some(other) => Err(invalid(format!(
            "`{path}.{name}` in cpl.lock must be a string, found {}",
            type_name(other)
        ))),
    }
}

/// A blake3-256 digest: 64 lowercase hex characters.
fn digest(hex: &str, path: &str) -> Result<Digest, LockError> {
    let valid = hex.len() == 64
        && hex
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b));
    if valid {
        Ok(Digest(hex.to_string()))
    } else {
        Err(invalid(format!(
            "`{path}` in cpl.lock must be a digest of 64 lowercase hex characters, found {hex:?}"
        )))
    }
}

/// The canonical text of a lock: the header comment, then `version`,
/// `[toolchain]`, `[sources]`, `[verification]`, `[foreign]`, `[adapters]`,
/// and `[targets]` in the layout of Section 11.2, one entry per line, LF
/// line ends, string values as TOML basic strings. The fixed keys keep the
/// order of the 11.2 example; the keys of `[sources]` and of the reserved
/// tables are sorted, and a reserved table's nested values are rendered
/// inline with sorted keys. A blank line separates the sections, except
/// that a reserved section that has no entries is followed directly by the
/// next reserved header, as in the 11.2 example.
/// `parse_lock(&render_lock(lock)) == Ok(lock.clone())` for every lock whose
/// digests are well formed.
pub fn render_lock(lock: &Lock) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "{HEADER}");
    let _ = writeln!(out, "version = {}", lock.version);

    out.push_str("\n[toolchain]\n");
    let _ = writeln!(out, "cpl = {}", quote(&lock.toolchain.cpl));
    let _ = writeln!(out, "edition = {}", quote(&lock.toolchain.edition));
    let _ = writeln!(out, "std = {}", quote(lock.toolchain.std.as_str()));

    out.push_str("\n[sources]\n");
    for (path, digest) in &lock.sources {
        let _ = writeln!(out, "{} = {}", quote(path), quote(digest.as_str()));
    }

    out.push_str("\n[verification]\n");
    let _ = writeln!(
        out,
        "proof_timeout_ms = {}",
        lock.verification.proof_timeout_ms
    );
    let admit: Vec<String> = lock.verification.admit.iter().map(|s| quote(s)).collect();
    let _ = writeln!(out, "admit = [{}]", admit.join(", "));

    let reserved = [
        ("foreign", &lock.foreign),
        ("adapters", &lock.adapters),
        ("targets", &lock.targets),
    ];
    let mut previous_empty = false;
    for (name, table) in reserved {
        if !previous_empty {
            out.push('\n');
        }
        let _ = writeln!(out, "[{name}]");
        for (k, value) in sorted(table) {
            let _ = writeln!(out, "{} = {}", key(k), render_value(value));
        }
        previous_empty = table.is_empty();
    }
    out
}

/// The entries of a table in key order, whatever the map's own order.
fn sorted(table: &toml::Table) -> Vec<(&String, &toml::Value)> {
    let mut entries: Vec<(&String, &toml::Value)> = table.iter().collect();
    entries.sort_by(|a, b| a.0.cmp(b.0));
    entries
}

/// One value on one line: arrays and tables inline, table keys sorted.
fn render_value(value: &toml::Value) -> String {
    match value {
        toml::Value::String(s) => quote(s),
        toml::Value::Integer(i) => i.to_string(),
        toml::Value::Float(_) | toml::Value::Boolean(_) | toml::Value::Datetime(_) => {
            value.to_string()
        }
        toml::Value::Array(items) => {
            let items: Vec<String> = items.iter().map(render_value).collect();
            format!("[{}]", items.join(", "))
        }
        toml::Value::Table(table) if table.is_empty() => "{}".to_string(),
        toml::Value::Table(table) => {
            let entries: Vec<String> = sorted(table)
                .into_iter()
                .map(|(k, v)| format!("{} = {}", key(k), render_value(v)))
                .collect();
            format!("{{ {} }}", entries.join(", "))
        }
    }
}

