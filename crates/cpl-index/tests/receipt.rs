fn milestone_one_receipt() -> (cpl_project::Project, cpl_diag::json::VerificationReceipt) {
    let (project, inputs) = reader_inputs();
    let target = version(&project, "src/reader/pages.cpl", "paginate");
    let positive = version(&project, "src/reader/pages.cpl", "Positive");
    let flatten = version(&project, "std/prelude.cpl", "flatten");
    let obligation = Obligation {
        id: "pgn_7c2d#ensures/1".into(),
        kind: "ensures".into(),
        clause: "flatten(result) == items".into(),
        location: Location {
            file: "src/reader/pages.cpl".into(),
            line: 46,
            col: 5,
            end_line: 46,
            end_col: 37,
        },
        status: ObligationStatus::Unknown,
        reason: Some("verifier_unavailable".into()),
        evidence: None,
        assumptions: vec![],
    };
    let receipt = verification_receipt(
        &inputs,
        core(&project, json!({ "release": false })),
        target,
        // Out of order and repeated: the receipt orders them by path.
        vec![flatten.clone(), positive.clone(), flatten],
        VerificationConfig {
            release: false,
            policy: VerificationPolicyJson { prove: true },
            proof_timeout_ms: 10_000,
            admitted: vec![],
        },
        ProofStatus::Unknown,
        vec![obligation],
        vec![],
        VerifierInfo {
            name: "none".into(),
            version: None,
            configuration: Default::default(),
        },
    );
    (project, receipt)
}

#[test]
fn a_verification_receipt_has_the_section_8_1_shape() {
    let (_, receipt) = milestone_one_receipt();
    assert_eq!(receipt.receipt, ReceiptKind::Verification);
    assert_eq!(receipt.schema, cpl_diag::version::JSON_SCHEMA);
    let paths: Vec<&str> = receipt
        .dependencies
        .iter()
        .map(|d| d.path.as_str())
        .collect();
    assert_eq!(paths, ["reader.pages.Positive", "std.prelude.flatten"]);
    assert_eq!(receipt.target.id.as_str(), "pgn_7c2d");
    assert_eq!(receipt.duration_ms, 0);
    let stamp = receipt.produced_at.as_bytes();
    assert_eq!(stamp.len(), 20, "{}", receipt.produced_at);
    assert_eq!((stamp[4], stamp[10], stamp[19]), (b'-', b'T', b'Z'));
    let json = serde_json::to_string_pretty(&receipt).expect("serializes");
    assert_eq!(
        written_keys(&json),
        [
            "receipt",
            "schema",
            "toolchain",
            "verifier",
            "revision",
            "core",
            "target",
            "dependencies",
            "inputs",
            "configuration",
            "status",
            "obligations",
            "assumptions",
            "produced_at",
            "duration_ms"
        ]
    );
    let value: Value = serde_json::from_str(&json).expect("json");
    assert_eq!(value["receipt"], json!("verification"));
    assert_eq!(value["status"], json!("unknown"));
    assert_eq!(
        value["verifier"],
        json!({ "name": "none", "version": null, "configuration": {} })
    );
    assert_eq!(value["inputs"]["lock"], Value::Null);
    assert_eq!(
        value["inputs"]["sources"].as_object().expect("map").len(),
        6
    );
    assert_eq!(
        value["configuration"],
        json!({ "release": false, "policy": { "prove": true }, "proof_timeout_ms": 10000, "admitted": [] })
    );
    assert_eq!(
        value["core"]["check_configuration"],
        json!({ "release": false })
    );
    assert_eq!(value["obligations"][0]["evidence"], Value::Null);
}

